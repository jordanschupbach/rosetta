if arg and arg[1] then package.preload.demo = assert(package.loadlib(arg[1], "luaopen_demo")) end
local demo = require("demo")
local directory = debug.getinfo(1, "S").source:sub(2):match("^(.*[/\\])") or "./"
local Calls = dofile(directory .. "../examples/demo_calls.lua")(demo)
local Object = demo.demo__CallObject
local function collect() collectgarbage("collect"); collectgarbage("collect") end
local function rejects(fn, expected)
    local ok, message = pcall(fn)
    assert(not ok and tostring(message):find(expected, 1, true), tostring(message))
end
assert(Object.live() == 0 and Object.new == nil)
assert(Calls.choose(41) == 42 and Calls.choose(41.5) == 42)
assert(Calls.choose(41.0) == 41.5 and demo.demo__overload_real(41) == 41.5)
local binary = string.rep("a\0b\255", 1000)
assert(Calls.choose(binary) == "string:" .. binary)
assert(Calls.choose("41") == "string:41")
rejects(function() Calls.choose(true) end, "no matching")
rejects(function() Calls.choose(nil) end, "no matching")
rejects(function() Calls.choose(1, 2) end, "exactly 1")
rejects(function() Calls.choose(2147483648) end, "range") -- no fallback to double
rejects(function() Calls.choose(2147483647) end, "overflow")
rejects(function() Calls.choose(math.huge) end, "range")
rejects(function() Calls.ambiguous(42) end, "ambiguous integer overload")
assert(Calls.signed(42) == 1 and Calls.unsigned(42) == 2)
assert(Calls.ambiguous(-1) == 1 and Calls.ambiguous(4294967295) == 2)
rejects(function() Calls.ambiguous(4294967296) end, "no matching")
rejects(function() Calls.ambiguous(42.0) end, "no matching")
rejects(function() Calls.unsigned(-1) end, "range")
local defaults = demo.demo__default_factor_calls()
assert(Calls.scale(21) == 42 and demo.demo__default_factor_calls() == defaults + 1)
assert(Calls.scale(6, 7) == 42 and demo.demo__default_factor_calls() == defaults + 1)
rejects(function() Calls.scale(21, nil) end, "number expected")
rejects(function() Calls.scale() end, "1 or 2")
rejects(function() Calls.scale(1, 2, 3) end, "1 or 2")
rejects(function() Calls.scale("21") end, "number expected")
assert(demo.demo__default_factor_calls() == defaults + 1)
rejects(function() Calls.scale(2147483647) end, "overflow")
assert(demo.demo__default_factor_calls() == defaults + 2) -- native side effects are not rolled back
assert(Calls.sum({}) == 0 and Calls.sum({42}) == 42 and Calls.sum({20, 22}) == 42)
assert(Calls.sum({10, 20, 12}) == 42 and demo.demo__initializer_sum({10, 20, 12}) == 42)
rejects(function() Calls.sum({1, 2, 3, 4}) end, "at most 3")
rejects(function() Calls.sum({2147483647, 1}) end, "overflow")
rejects(function() Calls.sum({1, "2"}) end, "number expected")
rejects(function() demo.demo__initializer_sum({1, 2}) end, "fixed array length")
rejects(function() demo.demo__make_call_text("42\0junk") end, "complete decimal")
rejects(function() demo.demo__make_call_text("2147483648") end, "out of range")
rejects(function() demo.demo__make_call_text("") end, "complete decimal")
do
    local zero <close> = demo.demo__make_call_default()
    local object <close> = demo.demo__make_call_number(20)
    local parsed <close> = demo.demo__make_call_text("-42")
    assert(zero:as_integer() == 0 and parsed:as_integer() == -42)
    assert(object:secret() == 20)
    assert(object:adjust_readonly(22) == 42 and object:as_integer() == 20)
    assert(object:adjust_mutable(22) == 42 and object:as_integer() == 42)
    local readonly <close> = object:readonly()
    assert(readonly:adjust_readonly(1) == 43 and readonly:secret() == 42)
    rejects(function() readonly:adjust_mutable(1) end, "readonly")
    rejects(function() readonly:take() end, "readonly")
    rejects(function() object:adjust_mutable(2147483647) end, "overflow")
    assert(object:as_integer() == 42 and object:take() == 42 and object:as_integer() == 0)
    assert(readonly:as_integer() == 0 and object:take() == 0)
    object:close(); object:close()
    rejects(function() readonly:as_integer() end, "expired")
end
do local abandoned = demo.demo__make_call_text("42"); assert(abandoned:secret() == 42) end
collect()
assert(Object.live() == 0)
print("Lua overload/default/variadic call adapters passed")
