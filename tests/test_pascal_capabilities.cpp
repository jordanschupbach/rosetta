// Generator and CLI checks of the Pascal backend (--language pascal) that need no Free Pascal: output
// shape, names, options and the CLI artifacts.
#include "rosetta/frontend.hpp"
#include "rosetta/pascal.hpp"
#include "rosetta/cli.hpp"
#include "process.hpp"
#include <functional>
#include <iostream>
#include <sstream>

namespace {
void require(bool value, const std::string& message) { if (!value) throw std::runtime_error(message); }
bool contains(const std::string& text, const std::string& part) { return text.find(part) != std::string::npos; }
void rejects(const std::function<void()>& action, const std::string& expected) {
    try { action(); }
    catch (const rosetta::BindingError& error) {
        require(contains(error.what(), expected), "expected '" + expected + "', got: " + error.what());
        return;
    }
    throw std::runtime_error("expected rejection: " + expected);
}
}
int main(int argc, char** argv) {
    if (argc != 2) return 1;
    try {
        rosetta::detail::TemporaryDirectory temporary;
        const auto header = temporary.path() / "pascal api.hpp";
        auto parse = [&](const std::string& source) {
            rosetta::detail::write_file(header, source);
            return rosetta::parse(header, argv[1], {"-std=c++17"});
        };
        const auto policy_file = temporary.path() / "policy.json";
        rosetta::detail::write_file(policy_file, "{\"version\": 1, \"select\": \"all\", \"names\": \"flat\"}\n");
        const auto policy = rosetta::load_policy(policy_file);

        // Output shape, names and determinism.
        const auto module = parse("#include <cstdint>\n#include <string>\n#include <vector>\nenum class Mode { on, On, BEGIN, self };\n"
                                  "struct Cursor { int close() { return 0; } int getName() const { return 0; } int get_name(int) const { return 1; }\n"
                                  "  int Count() const { return 0; } int count = 2; static int create() { return 1; } int repeat() const { return 3; } };\n"
                                  "struct Point { double x = 0; Point operator+(const Point&) const { return {}; } bool operator==(const Point&) const { return true; }\n"
                                  "  double operator[](int) const { return 0; } std::string to_string() const { return \"\"; } };\n"
                                  "struct NativeObject { int n = 0; };\n"
                                  "struct Base { virtual ~Base() = default; virtual int area() const { return 0; } };\n"
                                  "struct Other { virtual ~Other() = default; int other() const { return 2; } };\n"
                                  "struct Derived final : Base, Other { int area() const override { return 1; } };\n"
                                  "inline int twice(int value = 21) { return 2 * value; }\n"
                                  "inline int length(int x) { return x; }\n"
                                  "inline void bump(int& value) { ++value; }\n"
                                  "inline std::vector<double> halves(const std::vector<double>& v) { return v; }\n"
                                  "inline std::uint64_t biggest() noexcept { return UINT64_MAX; }\n"
                                  "constexpr double golden_ratio = 1.618;\n");
        const auto generated = rosetta::generate_pascal(module, "api", false, policy);
        const auto& pascal = generated.pascal;
        require(contains(pascal, "// Code generated by Rosetta from pascal api.hpp; DO NOT EDIT.") && contains(pascal, "unit api;") &&
                contains(pascal, "{$mode objfpc}{$H+}") && contains(pascal, "\ninterface\n") && contains(pascal, "\nimplementation\n") &&
                contains(pascal, "function RosettaDispatch(Obj: TNativeObject; Generic: LongWord;") && contains(pascal, "initialization\n  RosettaRegisterClasses;"),
                "unit layout");
        require(contains(pascal, "external 'api' name 'rosetta_api_call'") && !contains(pascal, "@C@") && !contains(pascal, "@LIB@"), "runtime placeholders");
        require(contains(pascal, "TMode = (") && contains(pascal, "&On = 0") && contains(pascal, "On2 = 1") && contains(pascal, "&Begin = 2") &&
                contains(pascal, "Self_ = 3") && contains(pascal, "TModeHelper = type helper for TMode"), "enum cases");
        require(contains(pascal, "TCursor = class(TNativeObject)") && contains(pascal, "function Close2: Int32; overload;") &&
                contains(pascal, "function GetName: Int32; overload;") && contains(pascal, "function GetName2(A1: Int32): Int32; overload;"), "member names");
        require(contains(pascal, "function Count: Int32; overload;") && contains(pascal, "property Count2: Int32") &&
                contains(pascal, "class function Create2: Int32; overload; static;") && contains(pascal, "function &Repeat: Int32; overload;"), "more member names");
        require(contains(pascal, "TNativeObject_ = class(TNativeObject)") && contains(pascal, "function Length2(AX: Int32): Int32; overload;") &&
                contains(pascal, "function GoldenRatio: Double;"), "reserved names");
        require(contains(pascal, "function Add(A1: TPoint): TPoint; overload;") && contains(pascal, "function IsEqual(A1: TPoint): Boolean; overload;") &&
                contains(pascal, "property Items[A1: Int32]: Double read At; default;") && contains(pascal, "function ToString: AnsiString; override;"),
                "operators");
        require(contains(pascal, "TDerived = class sealed(TBase)") && contains(pascal, "function AsOther: TOther;") &&
                contains(pascal, "function Area: Int32; overload; override;") && contains(pascal, "function Other: Int32; overload;") &&
                contains(pascal, "ClassType <> TBase"), "multiple inheritance and directors");
        require(contains(pascal, "if (Generic = 0) and (System.Length(Args) = 0) and (Obj is TBase) then"), "virtual method dispatch");
        require(contains(pascal, "function Twice: Int32; overload;") && contains(pascal, "function Twice(AValue: Int32): Int32; overload;") &&
                contains(pascal, "<c>AValue = 21</c>"), "default arguments: one overload per argument count");
        require(contains(pascal, "procedure Bump(var AValue: Int32); overload;") && contains(pascal, "_c.Slot(0);") &&
                contains(pascal, "if _r.Find(0, _v) then AValue := RosettaToInt32(_v);"), "var parameters");
        require(contains(pascal, "TArrayOfDouble = array of Double;") && contains(pascal, "function Halves(const AV: TArrayOfDouble): TArrayOfDouble; overload;"),
                "arrays");
        require(contains(pascal, "function Biggest: UInt64; overload;") && contains(pascal, "RosettaToUInt64(_r.Value)"), "64-bit values");
        require(contains(generated.source, "#define ROSETTA_FULL_PASCAL") && contains(generated.source, "rosetta_api_call"), "C++ library");
        const auto again = rosetta::generate_pascal(module, "api", false, policy);
        require(generated.source == again.source && generated.pascal == again.pascal, "nondeterministic output");
        std::cout << "PASS Pascal output, names and determinism\n";

        // Options.
        rosetta::PascalOptions options;
        options.unit = "VendorApi";
        options.library = "api_native";
        options.parts = 3;
        const auto custom = rosetta::generate_pascal(module, "api", false, policy, options);
        require(contains(custom.pascal, "unit VendorApi;") && contains(custom.pascal, "external 'api_native' name 'rosetta_api_call'") &&
                custom.parts.size() == 2, "options");
        options = {}; options.unit = "begin";
        rejects([&] { rosetta::generate_pascal(module, "api", false, policy, options); }, "Pascal unit name");
        options = {}; options.unit = "Bad-Name";
        rejects([&] { rosetta::generate_pascal(module, "api", false, policy, options); }, "Pascal unit name");
        options = {}; options.unit = "SysUtils";
        rejects([&] { rosetta::generate_pascal(module, "api", false, policy, options); }, "Pascal unit name");
        options = {}; options.library = "lib/api";
        rejects([&] { rosetta::generate_pascal(module, "api", false, policy, options); }, "library name");
        options = {}; options.parts = 0;
        rejects([&] { rosetta::generate_pascal(module, "api", false, policy, options); }, "parts");
        rejects([&] { rosetta::generate_pascal(module, "bad-name", false, policy); }, "module name");
        std::cout << "PASS Pascal options\n";

        // CLI.
        parse("inline int value(int x = 42) { return x; }");
        const auto output = temporary.path() / "pascal bindings.cpp";
        const auto dep = temporary.path() / "pascal bindings.d";
        const std::vector<std::string> args{header.string(), "--language", "pascal", "--module", "api", "--clang", argv[1],
            "-o", output.string(), "--depfile", dep.string()};
        std::ostringstream out, error;
        require(rosetta::run_cli(args, out, error) == 0, error.str());
        require(contains(rosetta::detail::read_file(output), "rosetta_api_call") &&
                contains(rosetta::detail::read_file(temporary.path() / "api.pas"), "function Value(AX: Int32): Int32; overload;"), "Pascal CLI artifacts missing");
        require(contains(rosetta::detail::read_file(dep), "api.pas"), "Pascal interface dependency missing");
        auto custom_args = args;
        const auto other = temporary.path() / "other unit.pas";
        custom_args.insert(custom_args.end(), {"--pascal-output", other.string(), "--pascal-unit", "MyApi", "--pascal-library", "native", "--parts", "2"});
        require(rosetta::run_cli(custom_args, out, error) == 0 && contains(rosetta::detail::read_file(other), "unit MyApi;") &&
                contains(rosetta::detail::read_file(other), "external 'native'") && std::filesystem::exists(temporary.path() / "pascal bindings_1.cpp"),
                "Pascal options and parts");
        auto unit_default = args;
        unit_default.insert(unit_default.end(), {"--pascal-unit", "Shapes"});
        require(rosetta::run_cli(unit_default, out, error) == 0 && std::filesystem::exists(temporary.path() / "Shapes.pas"), "unit name gives the default file");
        auto invalid = args;
        invalid.insert(invalid.end(), {"--pascal-unit", "begin"});
        require(rosetta::run_cli(invalid, out, error) == 1, "keyword unit accepted");
        const std::vector<std::string> lua{header.string(), "--language", "lua", "--module", "api", "-o", output.string(), "--pascal-output", "x"};
        require(rosetta::run_cli(lua, out, error) == 1 && contains(error.str(), "require --language pascal"), "Pascal-only option accepted for Lua");
        std::cout << "PASS Pascal CLI\n";
        return 0;
    } catch (const std::exception& error) { std::cerr << error.what() << '\n'; return 1; }
}
