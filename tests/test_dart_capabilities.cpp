// Generator and CLI checks of the Dart backend (--language dart) that need no Dart SDK: output
// shape, names, merged overloads, options and the CLI artifacts.
#include "rosetta/frontend.hpp"
#include "rosetta/dart.hpp"
#include "rosetta/cli.hpp"
#include "process.hpp"
#include <functional>
#include <iostream>
#include <sstream>

namespace {
void require(bool value, const std::string& message) { if (!value) throw std::runtime_error(message); }
bool contains(const std::string& text, const std::string& part) { return text.find(part) != std::string::npos; }
void rejects(const std::function<void()>& action, const std::string& expected) {
    try { action(); }
    catch (const rosetta::BindingError& error) {
        require(contains(error.what(), expected), "expected '" + expected + "', got: " + error.what());
        return;
    }
    throw std::runtime_error("expected rejection: " + expected);
}
std::string file(const rosetta::GeneratedDartSource& generated, const std::string& path) {
    for (const auto& [relative, text] : generated.files)
        if (relative == path) return text;
    throw std::runtime_error("no package file " + path);
}
}
int main(int argc, char** argv) {
    if (argc != 2) return 1;
    try {
        rosetta::detail::TemporaryDirectory temporary;
        const auto header = temporary.path() / "dart api.hpp";
        auto parse = [&](const std::string& source) {
            rosetta::detail::write_file(header, source);
            return rosetta::parse(header, argv[1], {"-std=c++17"});
        };
        const auto policy_file = temporary.path() / "policy.json";
        rosetta::detail::write_file(policy_file, "{\"version\": 1, \"select\": \"all\", \"names\": \"flat\"}\n");
        const auto policy = rosetta::load_policy(policy_file);

        // Output shape, names and determinism.
        const auto module = parse("#include <cstdint>\n#include <string>\n#include <vector>\nenum class Mode { in, value, name, off };\n"
                                  "struct Cursor { int close() { return 0; } int getName() const { return 0; } int get_name(int) const { return 1; }\n"
                                  "  int Count() const { return 0; } int count = 2; static int create() { return 1; } int hash_code() const { return 3; } };\n"
                                  "struct Point { double x = 0; Point operator+(const Point&) const { return {}; } bool operator==(const Point&) const { return true; }\n"
                                  "  double operator[](int) const { return 0; } std::string to_string() const { return \"\"; } };\n"
                                  "struct String { int n = 0; };\n"
                                  "struct Base { virtual ~Base() = default; virtual int area() const { return 0; } };\n"
                                  "struct Other { virtual ~Other() = default; int other() const { return 2; } };\n"
                                  "struct Derived final : Base, Other { int area() const override { return 1; } };\n"
                                  "inline int twice(int value = 21) { return 2 * value; }\n"
                                  "inline std::string pick(int) { return \"i\"; }\n"
                                  "inline std::string pick(const std::string&) { return \"s\"; }\n"
                                  "inline int print(int x) { return x; }\n"
                                  "inline void bump(int& value) { ++value; }\n"
                                  "inline std::vector<double> halves(const std::vector<double>& v) { return v; }\n"
                                  "inline std::uint64_t biggest() noexcept { return UINT64_MAX; }\n"
                                  "constexpr double golden_ratio = 1.618;\n");
        const auto generated = rosetta::generate_dart(module, "api", false, policy);
        const auto& dart = generated.dart;
        require(contains(dart, "// Code generated by Rosetta from dart api.hpp; DO NOT EDIT.") && contains(dart, "\nlibrary;\n") &&
                contains(dart, "import 'dart:ffi' as ffi;") && contains(dart, "part 'src/rosetta.dart';") &&
                contains(dart, "Object? _rosettaDispatch(NativeObject object, int generic, List<Object?> arguments) {") &&
                contains(dart, "final _classes = <_ClassInfo>["), "library layout");
        const auto runtime = file(generated, "lib/src/rosetta.dart");
        require(contains(runtime, "part of '../api.dart';") && contains(runtime, "rosetta_api_call") && contains(runtime, "API_DART_LIBRARY") &&
                !contains(runtime, "@C@") && !contains(runtime, "@LIB@") && !contains(runtime, "@ENV@") && !contains(runtime, "@LIBFILE@"),
                "runtime placeholders");
        require(contains(file(generated, "pubspec.yaml"), "name: api\n") && contains(file(generated, "pubspec.yaml"), "sdk: ^3.3.0"), "pubspec");
        require(contains(dart, "extension type const Mode(int value) {") && contains(dart, "static const in_ = Mode(0);") &&
                contains(dart, "static const value2 = Mode(1);") && contains(dart, "static const name2 = Mode(2);") &&
                contains(dart, "static const values = <Mode>[in_, value2, name2, off];"), "enum cases");
        require(contains(dart, "class Cursor extends NativeObject {") && contains(dart, "  int close2() {") && contains(dart, "  int getName() {") &&
                contains(dart, "  int getName2(int arg1) {") && contains(dart, "  int hashCode_() {"), "member names");
        require(contains(dart, "  int count() {") && contains(dart, "  int get count2 =>") && contains(dart, "  static int create() {"), "more member names");
        require(contains(dart, "class String_ extends NativeObject {") && contains(dart, "int print_(int x) {") && contains(dart, "double get goldenRatio =>"),
                "reserved names");
        require(contains(dart, "  Point operator +(Point other) {") && contains(dart, "  bool equals(Point arg1) {") &&
                contains(dart, "  double operator [](int other) {") && contains(dart, "  double at(int arg1) {") &&
                contains(dart, "  String toString() {") && contains(dart, "if (isClosed) return super.toString();"), "operators");
        require(contains(dart, "final class Derived extends Base {") && contains(dart, "Other get asOther => cast<Other>()!;") &&
                contains(dart, "  int other() {") && contains(dart, "runtimeType != Base"), "multiple inheritance and directors");
        require(contains(dart, "if (generic == 0 && arguments.length == 0 && object is Base) {"), "virtual method dispatch");
        require(contains(dart, "int twice([int? value]) {") && contains(dart, "final $n = value != null ? 1 : 0;") &&
                contains(dart, "`value = 21`"), "default arguments: optional parameters");
        require(contains(dart, "String pick(Object? arg1) {") && contains(dart, "$c.any(arg1);"), "merged overloads");
        require(contains(dart, "void bump(Ref<int> value) {") && contains(dart, "$r.writeBack($s0, value, "), "Ref parameters");
        require(contains(dart, "List<double> halves(List<double> v) {") && contains(dart, "_Codecs.list(_Codecs.real)"), "lists");
        require(contains(dart, "int biggest() {") && contains(dart, "_Codecs.uint64"), "64-bit values");
        require(contains(generated.source, "#define ROSETTA_FULL_DART") && contains(generated.source, "rosetta_api_call"), "C++ library");
        const auto again = rosetta::generate_dart(module, "api", false, policy);
        require(generated.source == again.source && generated.dart == again.dart, "nondeterministic output");
        std::cout << "PASS Dart output, names and determinism\n";

        // Options.
        rosetta::DartOptions options;
        options.package = "vendor_api";
        options.library = "api_native";
        options.parts = 3;
        const auto custom = rosetta::generate_dart(module, "api", false, policy, options);
        require(contains(file(custom, "pubspec.yaml"), "name: vendor_api\n") && contains(file(custom, "lib/src/rosetta.dart"), "part of '../vendor_api.dart';") &&
                contains(file(custom, "lib/src/rosetta.dart"), "api_native") && custom.parts.size() == 2, "options");
        require(rosetta::dart_package_name("ShapeKit") == "shape_kit" && rosetta::dart_package_name("features") == "features", "package names");
        options = {}; options.package = "switch";
        rejects([&] { rosetta::generate_dart(module, "api", false, policy, options); }, "Dart package name");
        options = {}; options.package = "Bad-Name";
        rejects([&] { rosetta::generate_dart(module, "api", false, policy, options); }, "Dart package name");
        options = {}; options.library = "lib/api";
        rejects([&] { rosetta::generate_dart(module, "api", false, policy, options); }, "library name");
        options = {}; options.parts = 0;
        rejects([&] { rosetta::generate_dart(module, "api", false, policy, options); }, "parts");
        rejects([&] { rosetta::generate_dart(module, "bad-name", false, policy); }, "module name");
        std::cout << "PASS Dart options\n";

        // CLI.
        parse("inline int value(int x = 42) { return x; }");
        const auto output = temporary.path() / "dart bindings.cpp";
        const auto dep = temporary.path() / "dart bindings.d";
        const std::vector<std::string> args{header.string(), "--language", "dart", "--module", "api", "--clang", argv[1],
            "-o", output.string(), "--depfile", dep.string()};
        std::ostringstream out, error;
        require(rosetta::run_cli(args, out, error) == 0, error.str());
        const auto api = temporary.path() / "api" / "lib" / "api.dart";
        require(contains(rosetta::detail::read_file(output), "rosetta_api_call") && contains(rosetta::detail::read_file(api), "int value([int? x]) {") &&
                std::filesystem::exists(temporary.path() / "api" / "pubspec.yaml") &&
                std::filesystem::exists(temporary.path() / "api" / "lib" / "src" / "rosetta.dart"), "Dart CLI artifacts missing");
        require(contains(rosetta::detail::read_file(dep), "api.dart"), "Dart interface dependency missing");
        auto custom_args = args;
        const auto other = temporary.path() / "other package";
        custom_args.insert(custom_args.end(), {"--dart-output", other.string(), "--dart-package", "my_api", "--dart-library", "native", "--parts", "2"});
        require(rosetta::run_cli(custom_args, out, error) == 0 && std::filesystem::exists(other / "lib" / "my_api.dart") &&
                contains(rosetta::detail::read_file(other / "lib" / "src" / "rosetta.dart"), "native") &&
                std::filesystem::exists(temporary.path() / "dart bindings_1.cpp"), "Dart options and parts");
        auto invalid = args;
        invalid.insert(invalid.end(), {"--dart-package", "class"});
        require(rosetta::run_cli(invalid, out, error) == 1, "keyword package accepted");
        const std::vector<std::string> lua{header.string(), "--language", "lua", "--module", "api", "-o", output.string(), "--dart-output", "x"};
        require(rosetta::run_cli(lua, out, error) == 1 && contains(error.str(), "require --language dart"), "Dart-only option accepted for Lua");
        std::cout << "PASS Dart CLI\n";
        return 0;
    } catch (const std::exception& error) { std::cerr << error.what() << '\n'; return 1; }
}
