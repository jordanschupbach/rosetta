if arg and arg[1] then package.preload.demo = assert(package.loadlib(arg[1], 'luaopen_demo')) end
local demo = require('demo')
local S = demo.demo__NativeStationary
local function rejects(fn, expected)
    local ok, err = pcall(fn)
    assert(not ok, 'expected rejection')
    if expected then assert(tostring(err):find(expected, 1, true), tostring(err)) end
end
local traits = demo.demo__native_storage_traits()
assert(not traits.copy_constructible and not traits.move_constructible)
assert(not traits.copy_assignable and not traits.move_assignable)
assert(traits.aggregate and traits.standard_layout and traits.trivial and traits.empty_marker and traits.compact_standard_layout)
do
    local a <close> = S.new('immovable\0text', false)
    local b <close> = a:share()
    local c <close> = S.new('immovable\0text', false)
    local view <close> = a:readonly()
    assert(S.live() == 2 and a:same(b) and b:same(view) and not a:same(c))
    assert(a:inspections() == 0 and view:text() == 'immovable\0text' and b:inspections() == 1)
    assert(a:text() == c:text() and a:inspections() == 2 and c:inspections() == 1)
    a:close()
    rejects(function() view:text() end)
    assert(b:text() == 'immovable\0text' and b:inspections() == 3)
    assert(S.live() == 2)
    b:close()
    assert(S.live() == 1)
    rejects(function() b:same(c) end)
end
rejects(function() S.new(string.rep('partial',1000), true) end, 'stationary construction failed')
assert(S.live() == 0)
local setting = S.setting()
S.set_setting(7)
assert(S.setting() == 7)
S.set_setting(setting)
assert(demo.demo__native_internal_add(20,22) == 42)
assert(demo.demo__native_internal_add(-2147483648,0) == -2147483648)
rejects(function() demo.demo__native_internal_add(2147483647,1) end, 'arithmetic overflow')
local input = {{1,2,3},{4,5,6}}
local output = demo.demo__native_matrix_shift(input, 40)
assert(output[1][1] == 41 and output[1][2] == 42 and output[2][3] == 46)
assert(input[1][1] == 1 and input[2][3] == 6)
input[2][3] = 2147483647
rejects(function() demo.demo__native_matrix_shift(input,1) end, 'arithmetic overflow')
assert(input[1][1] == 1 and input[2][3] == 2147483647)
rejects(function() demo.demo__native_matrix_shift({{1,2},{3,4,5}},1) end)
rejects(function() demo.demo__native_matrix_shift({{1,2,3},{4,5,6}, extra=true},1) end)
assert(demo.demo__native_matrix_shift({{0,0,0},{0,0,0}},42)[2][3] == 42)
collectgarbage('collect')
assert(S.live() == 0)
print('Native declaration/storage form tests passed')
