// Generator and CLI checks of the Objective-C backend (--language objective-c) that need no
// Objective-C toolchain: output shape, names, selectors, options and the CLI artifacts.
#include "rosetta/frontend.hpp"
#include "rosetta/objc.hpp"
#include "rosetta/cli.hpp"
#include "process.hpp"
#include <functional>
#include <iostream>
#include <sstream>

namespace {
void require(bool value, const std::string& message) { if (!value) throw std::runtime_error(message); }
bool contains(const std::string& text, const std::string& part) { return text.find(part) != std::string::npos; }
void rejects(const std::function<void()>& action, const std::string& expected) {
    try { action(); }
    catch (const rosetta::BindingError& error) {
        require(contains(error.what(), expected), "expected '" + expected + "', got: " + error.what());
        return;
    }
    throw std::runtime_error("expected rejection: " + expected);
}
std::string file(const rosetta::GeneratedObjcSource& generated, const std::string& path) {
    for (const auto& [relative, text] : generated.files)
        if (relative == path) return text;
    throw std::runtime_error("no file " + path);
}
}
int main(int argc, char** argv) {
    if (argc != 2) return 1;
    try {
        rosetta::detail::TemporaryDirectory temporary;
        const auto header = temporary.path() / "objc api.hpp";
        auto parse = [&](const std::string& source) {
            rosetta::detail::write_file(header, source);
            return rosetta::parse(header, argv[1], {"-std=c++17"});
        };
        const auto policy_file = temporary.path() / "policy.json";
        rosetta::detail::write_file(policy_file, "{\"version\": 1, \"select\": \"all\", \"names\": \"flat\"}\n");
        const auto policy = rosetta::load_policy(policy_file);

        // Output shape, names and determinism.
        const auto module = parse("#include <cstdint>\n#include <functional>\n#include <optional>\n#include <string>\n#include <vector>\n"
                                  "enum class Mode { on, On, self, off };\n"
                                  "struct Cursor { int close() { return 0; } int getName() const { return 0; } int get_name(int) const { return 1; }\n"
                                  "  int count = 2; int Count() const { return 0; } static int create() { return 1; } int hash() const { return 3; }\n"
                                  "  int new_value() const { return 4; } int x = 0; Cursor& set_x(int) { return *this; } };\n"
                                  "struct Point { double x = 0; Point operator+(const Point&) const { return {}; } bool operator==(const Point&) const { return true; }\n"
                                  "  double operator[](int) const { return 0; } std::string to_string() const { return \"\"; } };\n"
                                  "struct Object { int n = 0; };\n"
                                  "struct Base { virtual ~Base() = default; virtual int area() const { return 0; } };\n"
                                  "struct Other { virtual ~Other() = default; int other() const { return 2; } };\n"
                                  "struct Derived final : Base, Other { Derived(double, double) {} int area() const override { return 1; } };\n"
                                  "inline int twice(int value = 21) { return 2 * value; }\n"
                                  "inline std::string pick(int) { return \"i\"; }\n"
                                  "inline std::string pick(const std::string&) { return \"s\"; }\n"
                                  "inline void bump(int& value, std::string& text) { ++value; }\n"
                                  "inline int apply(const std::function<int(int)>& f) { return f(1); }\n"
                                  "inline std::function<int(int)> adder(int n) { return [n](int x) { return x + n; }; }\n"
                                  "inline int maybe(std::optional<int> v) { return v ? *v : 0; }\n"
                                  "inline std::vector<double> halves(const std::vector<double>& v) { return v; }\n"
                                  "inline std::uint64_t biggest() noexcept { return UINT64_MAX; }\n"
                                  "constexpr double golden_ratio = 1.618;\n");
        const auto generated = rosetta::generate_objc(module, "api", false, policy);
        const auto& h = generated.header;
        const auto m = file(generated, "Api.m");
        require(contains(h, "// Code generated by Rosetta from objc api.hpp; DO NOT EDIT.") && contains(h, "#import <Foundation/Foundation.h>") &&
                contains(h, "NS_ASSUME_NONNULL_BEGIN") && contains(h, "@interface ApiObject : NSObject") && contains(h, "@interface ApiError : NSException") &&
                contains(h, "@interface Api : NSObject") && !contains(h, "@P@"), "header layout");
        require(contains(m, "#import \"Api.h\"") && contains(m, "extern int rosetta_api_call(") && contains(m, "-fobjc-arc") && !contains(m, "@C@") &&
                !contains(m, "@LIB@") && contains(m, "static id rosetta_dispatch(ApiObject* object"), "implementation layout");
        require(contains(h, "typedef NS_ENUM(int64_t, ApiMode) {") && contains(h, "ApiModeOn = 0LL,") && contains(h, "ApiModeOn_ = 1LL,") &&
                contains(h, "ApiModeSelf = 2LL,"), "enumerations");
        require(contains(h, "@interface ApiCursor : ApiObject") && contains(h, "- (int)close_;") && contains(h, "- (int)getName;") &&
                contains(h, "- (int)getName2:(int)arg1;") && contains(h, "- (int)hash_;") && contains(h, "+ (int)create;") &&
                contains(h, "- (int)newValue __attribute__((objc_method_family(none)));"), "member names");
        require(contains(h, "- (int)count;") && contains(h, "@property (nonatomic) int count2;") && contains(h, "- (ApiCursor *)setX:(int)arg1;") &&
                contains(h, "@property (nonatomic, setter=setXValue:) int x;") && contains(m, "- (void)setXValue:(int)value {"), "fields and setters");
        require(contains(h, "@interface ApiObject_ : ApiObject"), "reserved class names");
        require(contains(h, "- (ApiPoint *)add:(ApiPoint *)arg1;") && contains(h, "- (BOOL)equals:(ApiPoint *)arg1;") && contains(h, "- (double)at:(int)arg1;") &&
                contains(h, "- (NSString *)description;") && contains(m, "if (self.isClosed) return [super description];"), "operators");
        require(contains(h, "__attribute__((objc_subclassing_restricted))\n@interface ApiDerived : ApiBase") && contains(h, "- (int)other;") &&
                contains(h, "@property (nonatomic, readonly) ApiOther *asOther;") && contains(h, "- (instancetype)initWithArg1:(double)arg1 arg2:(double)arg2;") &&
                contains(h, "- (instancetype)init __attribute__((unavailable));") && contains(m, "[self class] != [ApiBase class]"),
                "multiple inheritance, initializers and directors");
        require(contains(m, "if (generic == 0 && arguments.count == 0 && [object isKindOfClass:[ApiBase class]]) {"), "virtual method dispatch");
        require(contains(h, "+ (int)twice;") && contains(h, "+ (int)twice:(int)value;"), "default arguments: one selector per count");
        require(contains(h, "+ (NSString *)pick:(id _Nullable)arg1;"), "overloads disagreeing on a type take id");
        require(contains(h, "+ (void)bump:(int *)value text:(NSString * _Nonnull * _Nonnull)text;") && contains(m, "[_c slot:@(*value) type:\"i\"]"),
                "pointer parameters");
        require(contains(h, "+ (int)apply:(int (^)(int))f;") && contains(m, "+ (int)apply:(__unsafe_unretained int (^)(int))f {") &&
                contains(h, "+ (int (^)(int))adder:(int)n;"), "blocks");
        require(contains(h, "+ (int)maybe:(NSNumber * _Nullable)v;") && contains(h, "+ (NSArray<NSNumber *> *)halves:(NSArray<NSNumber *> *)v;"),
                "optionals and containers");
        require(contains(h, "+ (uint64_t)biggest;") && contains(h, "@property (class, nonatomic, readonly) double goldenRatio;"), "values and constants");
        require(contains(generated.source, "#define ROSETTA_FULL_OBJC") && contains(generated.source, "rosetta_api_call"), "C++ library");
        const auto again = rosetta::generate_objc(module, "api", false, policy);
        require(generated.source == again.source && generated.header == again.header && generated.files == again.files, "nondeterministic output");
        std::cout << "PASS Objective-C output, names and determinism\n";

        // Options.
        rosetta::ObjcOptions options;
        options.prefix = "VND";
        options.library = "api_native";
        options.parts = 3;
        const auto custom = rosetta::generate_objc(module, "api", false, policy, options);
        require(contains(custom.header, "@interface VND : NSObject") && contains(custom.header, "@interface VNDCursor : VNDObject") &&
                contains(custom.header, "Link the native library api_native") && contains(file(custom, "VND.m"), "#import \"VND.h\"") && custom.parts.size() == 2,
                "options");
        require(rosetta::objc_prefix("shape_kit") == "ShapeKit" && rosetta::objc_prefix("shapeKit") == "ShapeKit", "prefixes");
        options = {}; options.prefix = "self";
        rejects([&] { rosetta::generate_objc(module, "api", false, policy, options); }, "Objective-C prefix");
        options = {}; options.prefix = "Bad-Name";
        rejects([&] { rosetta::generate_objc(module, "api", false, policy, options); }, "Objective-C prefix");
        options = {}; options.library = "lib/api";
        rejects([&] { rosetta::generate_objc(module, "api", false, policy, options); }, "library name");
        options = {}; options.parts = 0;
        rejects([&] { rosetta::generate_objc(module, "api", false, policy, options); }, "parts");
        rejects([&] { rosetta::generate_objc(module, "bad-name", false, policy); }, "module name");
        std::cout << "PASS Objective-C options\n";

        // CLI.
        parse("inline int value(int x = 42) { return x; }");
        const auto output = temporary.path() / "objc bindings.cpp";
        const auto dep = temporary.path() / "objc bindings.d";
        const std::vector<std::string> args{header.string(), "--language", "objective-c", "--module", "api", "--clang", argv[1],
            "-o", output.string(), "--depfile", dep.string()};
        std::ostringstream out, error;
        require(rosetta::run_cli(args, out, error) == 0, error.str());
        require(contains(rosetta::detail::read_file(output), "rosetta_api_call") &&
                contains(rosetta::detail::read_file(temporary.path() / "Api.h"), "+ (int)value:(int)x;") &&
                std::filesystem::exists(temporary.path() / "Api.m"), "Objective-C CLI artifacts missing");
        require(contains(rosetta::detail::read_file(dep), "Api.h"), "Objective-C interface dependency missing");
        auto custom_args = args;
        const auto other = temporary.path() / "other files";
        custom_args.insert(custom_args.end(), {"--objc-output", other.string(), "--objc-prefix", "MY", "--objc-library", "native", "--parts", "2"});
        require(rosetta::run_cli(custom_args, out, error) == 0 && std::filesystem::exists(other / "MY.h") && std::filesystem::exists(other / "MY.m") &&
                contains(rosetta::detail::read_file(other / "MY.h"), "Link the native library native") &&
                std::filesystem::exists(temporary.path() / "objc bindings_1.cpp"), "Objective-C options and parts");
        auto invalid = args;
        invalid.insert(invalid.end(), {"--objc-prefix", "int"});
        require(rosetta::run_cli(invalid, out, error) == 1, "keyword prefix accepted");
        const std::vector<std::string> lua{header.string(), "--language", "lua", "--module", "api", "-o", output.string(), "--objc-output", "x"};
        require(rosetta::run_cli(lua, out, error) == 1 && contains(error.str(), "require --language objective-c"), "Objective-C-only option accepted for Lua");
        std::cout << "PASS Objective-C CLI\n";
        return 0;
    } catch (const std::exception& error) { std::cerr << error.what() << '\n'; return 1; }
}
