if arg and arg[1] then package.preload.demo = assert(package.loadlib(arg[1], 'luaopen_demo')) end
local demo = require('demo')
assert(demo.demo_names__imported_count() == 42)
assert(demo.demo_names__imported_count(20) == 20)
assert(demo.demo_names__imported_operation() == demo.demo__Operation.add)
assert(demo.demo_names__imported_operation(demo.demo__Operation.multiply) == demo.demo__Operation.multiply)
assert(not pcall(demo.demo_names__imported_operation, 3))
local values = demo.demo_names__imported_values({demo.demo__Operation.multiply, demo.demo__Operation.add})
assert(values[1] == demo.demo__Operation.multiply and values[2] == demo.demo__Operation.add)
assert(not pcall(demo.demo_names__imported_values, {1,3}))
assert(demo.demo_names__imported_text('binary\0text') == 'binary\0text')
assert(demo.demo_names__imported_nested(demo.demo__NestedOwner__Mode.active) == demo.demo__NestedOwner__Mode.active)
assert(demo.demo_names__using_vector({demo.demo__Operation.multiply})[1] == demo.demo__Operation.multiply)
assert(not pcall(demo.demo_names__using_vector, {3}))
assert(demo.demo_names__using_optional(nil) == nil)
assert(demo.demo_names__using_optional('binary\0') == 'binary\0')
local tuple = demo.demo_names__using_tuple({'text\0', 42})
assert(tuple[1] == 'text\0' and tuple[2] == 42)
do
    local owner <close> = demo.demo__Counter.new(42)
    assert(demo.demo_names__imported_counter(owner) == 42)
    local view <close> = owner:readonly()
    assert(demo.demo_names__imported_counter(view) == 42)
    view:close(); owner:close()
    assert(not pcall(demo.demo_names__imported_counter, owner))
end
-- Imports create neither duplicated enum tables nor a second userdata type.
assert(demo.demo_names__Operation == nil and demo.demo_names__Counter == nil and demo.demo_alias__Counter == nil)
assert(demo.demo__Counter.live() == 0)
print('Namespace aliases, imported scalar/enum/class types, containers and defaults passed')
