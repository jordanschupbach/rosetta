// Generator and CLI checks of the Swift backend (--language swift) that need no Swift: output
// shape, names, the package files, options and the CLI artifacts.
#include "rosetta/frontend.hpp"
#include "rosetta/swift.hpp"
#include "rosetta/cli.hpp"
#include "process.hpp"
#include <functional>
#include <iostream>
#include <sstream>

namespace {
void require(bool value, const std::string& message) { if (!value) throw std::runtime_error(message); }
bool contains(const std::string& text, const std::string& part) { return text.find(part) != std::string::npos; }
void rejects(const std::function<void()>& action, const std::string& expected) {
    try { action(); }
    catch (const rosetta::BindingError& error) {
        require(contains(error.what(), expected), "expected '" + expected + "', got: " + error.what());
        return;
    }
    throw std::runtime_error("expected rejection: " + expected);
}
const std::string& file(const rosetta::GeneratedSwiftSource& generated, const std::string& path) {
    for (const auto& [relative, text] : generated.files) if (relative == path) return text;
    throw std::runtime_error("no generated file " + path);
}
}
int main(int argc, char** argv) {
    if (argc != 2) return 1;
    try {
        rosetta::detail::TemporaryDirectory temporary;
        const auto header = temporary.path() / "swift api.hpp";
        auto parse = [&](const std::string& source) {
            rosetta::detail::write_file(header, source);
            return rosetta::parse(header, argv[1], {"-std=c++17"});
        };
        const auto policy_file = temporary.path() / "policy.json";
        rosetta::detail::write_file(policy_file, "{\"version\": 1, \"select\": \"all\", \"names\": \"flat\"}\n");
        const auto policy = rosetta::load_policy(policy_file);

        // Output shape, names and determinism.
        const auto module = parse("#include <cstdint>\n#include <string>\nenum class Mode { on, On, BEGIN, self };\n"
                                  "struct Cursor { int close() { return 0; } int getName() const { return 0; } int get_name(int) const { return 1; }\n"
                                  "  int Count() const { return 0; } int count = 2; static int make() { return 1; } int repeat() const { return 3; } };\n"
                                  "struct Point { double x = 0; Point operator+(const Point&) const { return {}; } bool operator==(const Point&) const { return true; }\n"
                                  "  double operator[](int) const { return 0; } std::string to_string() const { return \"\"; } };\n"
                                  "struct String { int n = 0; };\n"
                                  "struct Base { virtual ~Base() = default; virtual int area() const { return 0; } };\n"
                                  "struct Other { virtual ~Other() = default; int other() const { return 2; } };\n"
                                  "struct Derived final : Base, Other { int area() const override { return 1; } };\n"
                                  "inline int twice(int value = 21) { return 2 * value; }\n"
                                  "inline int print(int x) { return x; }\n"
                                  "inline void bump(int& value) { ++value; }\n"
                                  "inline std::uint64_t biggest() noexcept { return UINT64_MAX; }\n"
                                  "constexpr double golden_ratio = 1.618;\n");
        const auto generated = rosetta::generate_swift(module, "api", false, policy);
        const auto& swift = generated.swift;
        require(contains(swift, "// Code generated by Rosetta from swift api.hpp; DO NOT EDIT.") && contains(swift, "let rosettaClasses: [Rosetta.ClassInfo] = [") &&
                contains(swift, "func rosettaDispatch(_ object: NativeObject, _ generic: UInt32, _ arguments: [NativeValue]) throws -> NativeValue {"),
                "API layout");
        require(contains(swift, "public static let on = Mode(rawValue: 0)") && contains(swift, "public static let on2 = Mode(rawValue: 1)") &&
                contains(swift, "public static let begin = Mode(rawValue: 2)") && contains(swift, "public static let self_ = Mode(rawValue: 3)"), "enum cases");
        require(contains(swift, "open class Cursor: NativeObject {") && contains(swift, "public func close2() throws -> Int32 {") &&
                contains(swift, "public func getName() throws -> Int32 {") && contains(swift, "public func getName2(_ arg1: Int32) throws -> Int32 {") &&
                contains(swift, "public func count() throws -> Int32 {") && contains(swift, "public var count2: Int32 {") &&
                contains(swift, "public class func make() throws -> Int32 {") && contains(swift, "public func `repeat`() throws -> Int32 {"), "member names");
        require(contains(swift, "open class String_: NativeObject {") && contains(swift, "public func print_(_ x: Int32) throws -> Int32 {") &&
                contains(swift, "public var goldenRatio: Double {"), "reserved names");
        require(contains(swift, "public static func + (lhs: Point, rhs: Point) throws -> Point {") &&
                contains(swift, "public static func == (lhs: Point, rhs: Point) throws -> Bool {") &&
                contains(swift, "public subscript(_ arg1: Int32) -> Double {\n        get throws { try at(arg1) }") &&
                contains(swift, "open override var description: String { (try? toString()) ?? super.description }"), "operators");
        require(contains(swift, "public final class Derived: Base {") && contains(swift, "public var asOther: Other { cast(Other.self)! }") &&
                contains(swift, "public override func area() throws -> Int32 {") && contains(swift, "public func other() throws -> Int32 {") &&
                contains(swift, "director: type(of: self) != Base.self"), "multiple inheritance and directors");
        require(contains(swift, "if generic == 0, arguments.count == 0, let object = object as? Base {"), "virtual method dispatch");
        require(contains(swift, "public func twice() throws -> Int32 {") && contains(swift, "public func twice(_ value: Int32) throws -> Int32 {") &&
                contains(swift, "`value = 21`"), "default arguments: one overload per argument count");
        require(contains(swift, "public func bump(_ value: inout Int32) throws {") && contains(swift, "let slot0 = try rc.slot(value, Rosetta.int32)") &&
                contains(swift, "try reply.writeBack(slot0, &value, Rosetta.int32)"), "inout arguments");
        require(contains(swift, "public func biggest() -> UInt64 {\n    return Rosetta.must {"), "noexcept functions do not throw");
        require(contains(file(generated, "Package.swift"), "// swift-tools-version:5.9") &&
                contains(file(generated, "Package.swift"), ".systemLibrary(name: \"CApi\", path: \"Sources/CApi\")") &&
                contains(file(generated, "Package.swift"), ".target(name: \"Api\", dependencies: [\"CApi\"], path: \"Sources/Api\")"), "Package.swift");
        require(contains(file(generated, "Sources/CApi/module.modulemap"), "module CApi [system] {\n    header \"api.h\"\n    link \"api\"") &&
                contains(file(generated, "Sources/CApi/api.h"), "int rosetta_api_call(unsigned index, const unsigned char* data, size_t size"), "C module");
        const auto& runtime = file(generated, "Sources/Api/Rosetta.swift");
        require(contains(runtime, "import CApi\n") && contains(runtime, "rosetta_api_call(index") && !contains(runtime, "@C@") &&
                !contains(runtime, "@CMOD@") && !contains(runtime, "@LIB@"), "runtime placeholders");
        require(contains(generated.source, "#define ROSETTA_FULL_SWIFT") && contains(generated.source, "rosetta_api_call"), "C++ library");
        const auto again = rosetta::generate_swift(module, "api", false, policy);
        require(generated.source == again.source && generated.swift == again.swift && generated.files == again.files, "nondeterministic output");
        std::cout << "PASS Swift output, names and determinism\n";

        // Options.
        rosetta::SwiftOptions options;
        options.module = "VendorApi";
        options.library = "api_native";
        options.parts = 3;
        const auto custom = rosetta::generate_swift(module, "api", false, policy, options);
        require(contains(file(custom, "Sources/CVendorApi/module.modulemap"), "link \"api_native\"") &&
                contains(file(custom, "Sources/VendorApi/Rosetta.swift"), "import CVendorApi\n") &&
                contains(file(custom, "Package.swift"), "name: \"VendorApi\"") && custom.parts.size() == 2, "options");
        options = {}; options.module = "func";
        rejects([&] { rosetta::generate_swift(module, "api", false, policy, options); }, "Swift module name");
        options = {}; options.module = "Bad-Name";
        rejects([&] { rosetta::generate_swift(module, "api", false, policy, options); }, "Swift module name");
        options = {}; options.library = "lib/api";
        rejects([&] { rosetta::generate_swift(module, "api", false, policy, options); }, "library name");
        options = {}; options.parts = 0;
        rejects([&] { rosetta::generate_swift(module, "api", false, policy, options); }, "parts");
        rejects([&] { rosetta::generate_swift(module, "bad-name", false, policy); }, "module name");
        std::cout << "PASS Swift options\n";

        // CLI.
        parse("inline int value(int x = 42) { return x; }");
        const auto output = temporary.path() / "swift bindings.cpp";
        const auto dep = temporary.path() / "swift bindings.d";
        const std::vector<std::string> args{header.string(), "--language", "swift", "--module", "api", "--clang", argv[1],
            "-o", output.string(), "--depfile", dep.string()};
        std::ostringstream out, error;
        require(rosetta::run_cli(args, out, error) == 0, error.str());
        const auto package = temporary.path() / "api";
        require(contains(rosetta::detail::read_file(output), "rosetta_api_call") &&
                contains(rosetta::detail::read_file(package / "Sources" / "Api" / "Api.swift"), "public func value(") &&
                std::filesystem::exists(package / "Package.swift") && std::filesystem::exists(package / "Sources" / "CApi" / "module.modulemap"),
                "Swift CLI artifacts missing");
        require(contains(rosetta::detail::read_file(dep), "Api.swift"), "Swift interface dependency missing");
        auto custom_args = args;
        const auto other = temporary.path() / "other package";
        custom_args.insert(custom_args.end(), {"--swift-output", other.string(), "--swift-module", "MyApi", "--swift-library", "native", "--parts", "2"});
        require(rosetta::run_cli(custom_args, out, error) == 0 &&
                contains(rosetta::detail::read_file(other / "Sources" / "CMyApi" / "module.modulemap"), "link \"native\"") &&
                std::filesystem::exists(other / "Sources" / "MyApi" / "MyApi.swift") && std::filesystem::exists(temporary.path() / "swift bindings_1.cpp"),
                "Swift options and parts");
        auto invalid = args;
        invalid.insert(invalid.end(), {"--swift-module", "func"});
        require(rosetta::run_cli(invalid, out, error) == 1, "keyword module accepted");
        const std::vector<std::string> lua{header.string(), "--language", "lua", "--module", "api", "-o", output.string(), "--swift-output", "x"};
        require(rosetta::run_cli(lua, out, error) == 1 && contains(error.str(), "require --language swift"), "Swift-only option accepted for Lua");
        std::cout << "PASS Swift CLI\n";
        return 0;
    } catch (const std::exception& error) { std::cerr << error.what() << '\n'; return 1; }
}
