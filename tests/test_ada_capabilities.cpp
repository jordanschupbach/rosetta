// Generator and CLI checks of the Ada backend (--language ada) that need no Ada compiler: output
// shape, names, overloads, options and the CLI artifacts.
#include "rosetta/frontend.hpp"
#include "rosetta/ada.hpp"
#include "rosetta/cli.hpp"
#include "process.hpp"
#include <functional>
#include <iostream>
#include <sstream>

namespace {
void require(bool value, const std::string& message) { if (!value) throw std::runtime_error(message); }
bool contains(const std::string& text, const std::string& part) { return text.find(part) != std::string::npos; }
void rejects(const std::function<void()>& action, const std::string& expected) {
    try { action(); }
    catch (const rosetta::BindingError& error) {
        require(contains(error.what(), expected), "expected '" + expected + "', got: " + error.what());
        return;
    }
    throw std::runtime_error("expected rejection: " + expected);
}
std::string file(const rosetta::GeneratedAdaSource& generated, const std::string& path) {
    for (const auto& [relative, text] : generated.files)
        if (relative == path) return text;
    throw std::runtime_error("no package file " + path);
}
}
int main(int argc, char** argv) {
    if (argc != 2) return 1;
    try {
        rosetta::detail::TemporaryDirectory temporary;
        const auto header = temporary.path() / "ada api.hpp";
        auto parse = [&](const std::string& source) {
            rosetta::detail::write_file(header, source);
            return rosetta::parse(header, argv[1], {"-std=c++17"});
        };
        const auto policy_file = temporary.path() / "policy.json";
        rosetta::detail::write_file(policy_file, "{\"version\": 1, \"select\": \"all\", \"names\": \"flat\"}\n");
        const auto policy = rosetta::load_policy(policy_file);

        // Output shape, names and determinism.
        const auto module = parse("#include <cstdint>\n#include <string>\n#include <vector>\nenum class Mode { in, value, name, off };\n"
                                  "struct Cursor { int close() { return 0; } int getName() const { return 0; } int get_name(int) const { return 1; }\n"
                                  "  int Count() const { return 0; } int count = 2; static int create() { return 1; } int image() const { return 3; } };\n"
                                  "struct Point { double x = 0; Point operator+(const Point&) const { return {}; } bool operator==(const Point&) const { return true; }\n"
                                  "  double operator[](int) const { return 0; } std::string to_string() const { return \"\"; } };\n"
                                  "struct String { int n = 0; };\n"
                                  "struct Base { virtual ~Base() = default; virtual int area() const { return 0; } };\n"
                                  "struct Other { virtual ~Other() = default; int other() const { return 2; } };\n"
                                  "struct Derived final : Base, Other { int area() const override { return 1; } };\n"
                                  "inline int twice(int value = 21) { return 2 * value; }\n"
                                  "inline std::string pick(int) { return \"i\"; }\n"
                                  "inline std::string pick(const std::string&) { return \"s\"; }\n"
                                  "inline int rosetta(int x) { return x; }\n"
                                  "inline int other_of(const Other& o) { return o.other(); }\n"
                                  "inline void bump(int& value) { ++value; }\n"
                                  "inline std::vector<double> halves(const std::vector<double>& v) { return v; }\n"
                                  "inline std::uint64_t biggest() noexcept { return UINT64_MAX; }\n"
                                  "constexpr double golden_ratio = 1.618;\n");
        const auto generated = rosetta::generate_ada(module, "api", false, policy);
        const auto& spec = generated.spec;
        const auto body = file(generated, "api.adb");
        require(contains(spec, "--  Code generated by Rosetta from ada api.hpp; DO NOT EDIT.") && contains(spec, "\npackage Api is\n") &&
                contains(spec, "\nprivate\n") && contains(spec, "\nend Api;\n") && contains(spec, "with Ada.Containers.Vectors;") &&
                !contains(spec, "Ada.Containers.Ordered_Maps") && contains(spec, "pragma Linker_Options (\"-lapi\");"), "spec layout");
        require(contains(body, "\npackage body Api is\n") && contains(body, "   package Rosetta is\n") && contains(body, "External_Name => \"rosetta_api_call\"") &&
                !contains(body, "@C@") && !contains(body, "@LIB@") && contains(body, "   Rosetta.Dispatcher := Rosetta_Dispatch'Access;\n") &&
                contains(body, "pragma Warnings (Off, \"*is not referenced*\");"), "body layout");
        require(contains(file(generated, "api.gpr"), "project Api is") && contains(file(generated, "api.gpr"), "\"-gnat2022\""), "project file");
        require(contains(spec, "type Mode is (In_Mode, Value, Name, Off);") && contains(spec, "for Mode use (In_Mode => 0, Value => 1, Name => 2, Off => 3);") &&
                contains(body, "function Rosetta_Get_Mode"), "enumerations");
        require(contains(spec, "type Cursor_Record is new Native_Object_Record with private;") && contains(spec, "type Cursor is access all Cursor_Record'Class;") &&
                contains(spec, "function Close_2 (Self : in out Cursor_Record) return Integer;") &&
                contains(spec, "function Get_Name (Self : Cursor_Record) return Integer;") &&
                contains(spec, "function Get_Name_2 (Self : Cursor_Record; Arg_1 : Integer) return Integer;") &&
                contains(spec, "function Image_2 (Self : Cursor_Record) return Integer;"), "member names");
        require(contains(spec, "function Count (Self : Cursor_Record) return Integer;") && contains(spec, "function Count_2 (Self : Cursor_Record) return Integer;") &&
                contains(spec, "procedure Set_Count_2 (Self : in out Cursor_Record; Value : Integer);") && contains(spec, "function Cursor_Create return Integer;"),
                "more member names");
        require(contains(spec, "type String_Record is new Native_Object_Record with private;") && contains(spec, "function New_String_Access return String_Access;") &&
                contains(spec, "function Rosetta_2 (X : Integer) return Integer;") && contains(spec, "function Golden_Ratio return Long_Float;"), "reserved names");
        require(contains(spec, "function \"+\" (Left : not null access Point_Record; Right : not null access Point_Record'Class) return Point;") &&
                contains(spec, "function Equals (Self : Point_Record; Arg_1 : not null access Point_Record'Class) return Boolean;") &&
                contains(spec, "function Element (Self : Point_Record; Arg_1 : Integer) return Long_Float;") &&
                contains(spec, "overriding function Image (Self : Point_Record) return String;") &&
                contains(body, "return Native_Object_Record (Self).Image;"), "operators");
        require(contains(spec, "type Derived_Record is new Base_Record with private;") && contains(spec, "function As_Other (Self : Derived_Record) return Other;") &&
                contains(spec, "function Other_2 (Self : Derived_Record) return Integer;") && contains(body, "Self'Tag /= Base_Record'Tag"),
                "multiple inheritance and directors");
        require(contains(body, "if Rosetta_Method = 0 and then Rosetta_Count = 0 and then Rosetta_Obj.all in Base_Record'Class then"), "virtual method dispatch");
        require(contains(spec, "function Twice return Integer;") && contains(spec, "function Twice (Value : Integer) return Integer;") &&
                contains(spec, "Value := 21"), "default arguments: overloads");
        require(contains(spec, "function Pick (Arg_1 : Integer) return String;") && contains(spec, "function Pick (Arg_1 : String) return String;"), "overloads");
        require(contains(spec, "procedure Bump (Value : in out Integer);") && contains(body, "Rosetta.Slot (Rosetta_C, 0);") &&
                contains(body, "when 0 => Value := "), "in out parameters");
        require(contains(spec, "package Long_Float_Vectors is new Ada.Containers.Vectors (Positive, Long_Float);") &&
                contains(spec, "function Halves (V : Long_Float_Vector) return Long_Float_Vector;"), "vectors");
        require(contains(spec, "function Biggest return Interfaces.Unsigned_64;") && contains(body, "Rosetta.Get_Unsigned_64"), "64-bit values");
        require(contains(spec, "function Other_Of_2 (O : not null access Other_Record'Class) return Integer;") == false &&
                contains(spec, "function Other_Of (O : not null access Other_Record'Class) return Integer;"), "functions keep names unlike members");
        require(contains(generated.source, "#define ROSETTA_FULL_ADA") && contains(generated.source, "rosetta_api_call"), "C++ library");
        const auto again = rosetta::generate_ada(module, "api", false, policy);
        require(generated.source == again.source && generated.spec == again.spec && generated.files == again.files, "nondeterministic output");
        std::cout << "PASS Ada output, names and determinism\n";

        // Options.
        rosetta::AdaOptions options;
        options.package = "Vendor_Api";
        options.library = "api_native";
        options.parts = 3;
        const auto custom = rosetta::generate_ada(module, "api", false, policy, options);
        require(contains(custom.spec, "\npackage Vendor_Api is\n") && contains(custom.spec, "pragma Linker_Options (\"-lapi_native\");") &&
                contains(file(custom, "vendor_api.adb"), "package body Vendor_Api is") && custom.parts.size() == 2, "options");
        require(rosetta::ada_package_name("shape_kit") == "Shape_Kit" && rosetta::ada_package_name("ShapeKit") == "Shape_Kit" &&
                rosetta::ada_spec_file("Shape_Kit") == "shape_kit.ads", "package names");
        options = {}; options.package = "Begin";
        rejects([&] { rosetta::generate_ada(module, "api", false, policy, options); }, "Ada package name");
        options = {}; options.package = "Bad-Name";
        rejects([&] { rosetta::generate_ada(module, "api", false, policy, options); }, "Ada package name");
        options = {}; options.package = "Interfaces";
        rejects([&] { rosetta::generate_ada(module, "api", false, policy, options); }, "Ada package name");
        options = {}; options.library = "lib/api";
        rejects([&] { rosetta::generate_ada(module, "api", false, policy, options); }, "library name");
        options = {}; options.parts = 0;
        rejects([&] { rosetta::generate_ada(module, "api", false, policy, options); }, "parts");
        rejects([&] { rosetta::generate_ada(module, "bad-name", false, policy); }, "module name");
        std::cout << "PASS Ada options\n";

        // CLI.
        parse("inline int value(int x = 42) { return x; }");
        const auto output = temporary.path() / "ada bindings.cpp";
        const auto dep = temporary.path() / "ada bindings.d";
        const std::vector<std::string> args{header.string(), "--language", "ada", "--module", "api", "--clang", argv[1],
            "-o", output.string(), "--depfile", dep.string()};
        std::ostringstream out, error;
        require(rosetta::run_cli(args, out, error) == 0, error.str());
        require(contains(rosetta::detail::read_file(output), "rosetta_api_call") &&
                contains(rosetta::detail::read_file(temporary.path() / "api.ads"), "function Value (X : Integer) return Integer;") &&
                std::filesystem::exists(temporary.path() / "api.adb") && std::filesystem::exists(temporary.path() / "api.gpr"), "Ada CLI artifacts missing");
        require(contains(rosetta::detail::read_file(dep), "api.ads"), "Ada interface dependency missing");
        auto custom_args = args;
        const auto other = temporary.path() / "other package";
        custom_args.insert(custom_args.end(), {"--ada-output", other.string(), "--ada-package", "My_Api", "--ada-library", "native", "--parts", "2"});
        require(rosetta::run_cli(custom_args, out, error) == 0 && std::filesystem::exists(other / "my_api.ads") && std::filesystem::exists(other / "my_api.adb") &&
                contains(rosetta::detail::read_file(other / "my_api.ads"), "-lnative") &&
                std::filesystem::exists(temporary.path() / "ada bindings_1.cpp"), "Ada options and parts");
        auto invalid = args;
        invalid.insert(invalid.end(), {"--ada-package", "record"});
        require(rosetta::run_cli(invalid, out, error) == 1, "keyword package accepted");
        const std::vector<std::string> lua{header.string(), "--language", "lua", "--module", "api", "-o", output.string(), "--ada-output", "x"};
        require(rosetta::run_cli(lua, out, error) == 1 && contains(error.str(), "require --language ada"), "Ada-only option accepted for Lua");
        std::cout << "PASS Ada CLI\n";
        return 0;
    } catch (const std::exception& error) { std::cerr << error.what() << '\n'; return 1; }
}
