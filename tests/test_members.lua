if arg and arg[1] then package.preload.demo = assert(package.loadlib(arg[1], 'luaopen_demo')) end
local demo = require('demo')
local Object, Selector, Choice, Kind = demo.demo__MemberObject, demo.demo__MemberSelector, demo.demo__MemberChoice, demo.demo__MemberKind
local function rejects(fn, expected)
    local ok, message = pcall(fn)
    assert(not ok and tostring(message):find(expected, 1, true), tostring(message))
end
do
    local left <close> = Selector.new(Choice.left)
    local right <close> = Selector.new(Choice.right)
    local text <close> = Selector.new(Choice.label)
    local read <close> = Selector.new(Choice.measure)
    local write <close> = Selector.new(Choice.add)
    local none <close> = Selector.new(Choice.none)
    local null_method <close> = Selector.new(Choice.null_method)
    assert(none:null() and none:kind() == Kind.none)
    assert(null_method:null() and null_method:kind() == Kind.none)
    assert(not left:null() and left:kind() == Kind.integer and right:kind() == Kind.integer)
    assert(text:kind() == Kind.text and read:kind() == Kind.const_method and write:kind() == Kind.mutable_method)
    for _, derived in ipairs({false, true}) do
        local object <close> = Object.new(20, 21, 'binary\0label', derived)
        assert(left:read_integer(object) == 20 and right:read_integer(object) == 21)
        assert(read:invoke_read(object, 0) == (derived and 42 or 41))
        local method_copy <close> = read:copy()
        assert(method_copy:invoke_read(object, 0) == (derived and 42 or 41))
        right:write_integer(object, 22)
        assert(left:read_integer(object) == 20 and right:read_integer(object) == 22)
        assert(write:invoke_write(object, 1) == 21)
        assert(text:read_text(object) == 'binary\0label')
        text:write_text(object, 'replacement\0')
        assert(text:read_text(object) == 'replacement\0')
        local view <close> = object:readonly()
        assert(left:read_integer(view) == 21 and text:read_text(view) == 'replacement\0')
        assert(read:invoke_read(view, 0) == (derived and 44 or 43))
        assert(not pcall(function() left:write_integer(view, 0) end))
        assert(not pcall(function() write:invoke_write(view, 0) end))
        assert(not pcall(function() text:write_text(view, 'forbidden') end))
        rejects(function() text:read_integer(object) end, 'integer member selector expected')
        rejects(function() left:read_text(object) end, 'text member selector expected')
        rejects(function() left:write_text(object, string.rep('wrong kind',1000)) end, 'text member selector expected')
        assert(text:read_text(object) == 'replacement\0')
        rejects(function() write:invoke_read(object, 0) end, 'const method selector expected')
        rejects(function() read:invoke_write(object, 0) end, 'mutable method selector expected')
        rejects(function() none:read_integer(object) end, 'null member selector')
        rejects(function() null_method:invoke_read(object, 0) end, 'null member selector')
        local copy <close> = right:copy()
        assert(copy:read_integer(object) == 22)
        local shared <close> = object:share()
        view:close(); object:close()
        assert(copy:read_integer(shared) == 22)
        rejects(function() copy:read_integer(object) end, 'closed')
        local maximum = demo.demo__call_int_max()
        left:write_integer(shared, maximum)
        rejects(function() write:invoke_write(shared, 1) end, 'member arithmetic overflow')
        assert(left:read_integer(shared) == maximum)
        rejects(function() read:invoke_read(shared, 0) end, 'member arithmetic overflow')
        right:write_integer(shared, 0)
        if derived then rejects(function() method_copy:invoke_read(shared, 0) end, 'member arithmetic overflow')
        else assert(method_copy:invoke_read(shared, 0) == maximum) end
    end
    local copy <close> = left:copy()
    left:close()
    local object <close> = Object.new(42, 0, '', false)
    assert(copy:read_integer(object) == 42)
    assert(not pcall(function() copy:read_integer(read) end))
    local view <close> = object:readonly()
    object:close()
    rejects(function() copy:read_integer(view) end, 'closed')
end
assert(not pcall(Selector.new, 7))
do local object = Object.new(1, 2, string.rep('gc',1000), true); local selector = Selector.new(Choice.label) end
collectgarbage('collect')
assert(Object.live() == 0 and Selector.live() == 0)
print('Typed member selections, base adjustment, virtual/ref-qualified calls, const access and cleanup passed')
