if arg and arg[1] then package.preload.demo = assert(package.loadlib(arg[1], 'luaopen_demo')) end
local demo = require('demo')
local Op, Byte, Signed = demo.demo__Operation, demo.demo__ByteFlags, demo.demo__SignedFlags
local function rejects(fn, expected)
    local ok, message = pcall(fn)
    assert(not ok and tostring(message):find(expected, 1, true), tostring(message))
end
local operations = demo.demo__operation_vector({Op.add, Op.multiply, Op.plus})
assert(#operations == 3 and operations[1] == 1 and operations[2] == 2 and operations[3] == 1)
assert(#demo.demo__operation_vector({}) == 0)
rejects(function() demo.demo__operation_vector({Op.add, 3}) end, 'unknown enum value')
rejects(function() demo.demo__operation_vector({Op.add, 256}) end, 'range')
local flags = demo.demo__byte_flag_array({0, Byte.high, Byte.high | Byte.low})
assert(#flags == 3 and flags[1] == 0 and flags[2] == 128 and flags[3] == 129)
rejects(function() demo.demo__byte_flag_array({0, Byte.reserved, Byte.high}) end, 'unknown enum flag bits')
rejects(function() demo.demo__byte_flag_array({Byte.low}) end, 'fixed array length')
assert(demo.demo__optional_operation(nil) == nil and demo.demo__optional_operation(Op.multiply) == Op.multiply)
rejects(function() demo.demo__optional_operation(3) end, 'unknown enum value')
local binary = string.rep('enum\0', 512)
local input = {binary, Op.add, Byte.high | Byte.low, {0, Signed.first | Signed.second}}
local value = demo.demo__enum_product(input)
assert(value ~= input and value[1] == binary and value[2] == 1 and value[3] == 129 and value[4][2] == 3)
assert(demo.demo__enum_product({binary, Op.multiply, nil, {}})[3] == nil)
rejects(function() demo.demo__enum_product({binary, 3, nil, {}}) end, 'unknown enum value')
rejects(function() demo.demo__enum_product({binary, Op.add, 2, {}}) end, 'unknown enum flag bits')
rejects(function() demo.demo__enum_product({binary, Op.add, nil, {Signed.invalid}}) end, 'unknown enum flag bits')
local widths = demo.demo__enum_widths({0, demo.demo__WideFlags.high | 1})
assert(widths[1] == 0 and math.type(widths[1]) == 'integer' and widths[2] == (1 << 62 | 1))
assert(demo.demo__enum_widths({1, 0})[1] == 1)
rejects(function() demo.demo__enum_widths({true, 0}) end, 'number expected')
assert(demo.demo__enum_callback(function(operation) assert(operation == Op.add); return Op.multiply end, Op.add) == Op.multiply)
rejects(function() demo.demo__enum_callback(function() return 3 end, Op.add) end, 'unknown enum value')
rejects(function() demo.demo__enum_callback(function() return '1' end, Op.add) end, 'number expected')
local output = demo.demo__enum_product_callback(function(product)
    assert(product[1] == binary and product[3] == 129 and product[4][2] == 3)
    product[2] = Op.multiply; product[3] = nil
    return product
end, input)
assert(output[1] == binary and output[2] == Op.multiply and output[3] == nil and input[2] == Op.add)
rejects(function() demo.demo__enum_product_callback(function(product) product[2] = 3; return product end, input) end, 'unknown enum value')
rejects(function() demo.demo__enum_product_callback(function(product) product[3] = 2; return product end, input) end, 'unknown enum flag bits')
rejects(function() demo.demo__enum_product_callback(function() error('enum callback failure') end, input) end, 'enum callback failure')
rejects(function() demo.demo__enum_product_callback(function() coroutine.yield() end, input) end, 'yield')
rejects(function() demo.demo__enum_product_failure(input) end, 'enum product failure')
rejects(function() demo.demo__enum_oversized_result(input) end, 'Lua integer range')
-- Native output bits remain inspectable; Lua-to-C++ decoding validates membership.
local native = demo.demo__enum_native_values()
assert(native[1] == 3 and native[2] == Byte.reserved)
rejects(function() demo.demo__operation_vector({native[1]}) end, 'unknown enum value')
assert(demo.demo__enum_product(input)[2] == Op.add)
print('Enum codecs in sequences, products, optionals and copied callbacks passed')
