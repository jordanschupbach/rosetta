if arg and arg[1] then package.preload.demo = assert(package.loadlib(arg[1], "luaopen_demo")) end
local demo = require("demo")
local Buffer, Slice = demo.demo__ByteBuffer, demo.demo__ByteSlice
local function collect() collectgarbage("collect"); collectgarbage("collect") end
local function rejects(fn, expected)
    local ok, message = pcall(fn)
    assert(not ok and tostring(message):find(expected, 1, true), tostring(message))
end
assert(Buffer.live() == 0 and Slice.live() == 0 and Slice.new == nil)
do
    local buffer <close> = Buffer.new("a\0b\255")
    local view <close> = buffer:slice(1, 2, false)
    local readonly <close> = buffer:slice(0, 4, true)
    assert(buffer:size() == 4 and buffer:read() == "a\0b\255")
    assert(view:size() == 2 and view:read() == "\0b" and not view:readonly())
    assert(readonly:readonly())
    view:write(0, "xy")
    assert(buffer:read() == "axy\255" and readonly:read() == buffer:read())
    view:xor_bytes(255)
    assert(view:read() == string.char(135, 134))
    view:xor_bytes(255)
    assert(view:read() == "xy")
    buffer:write(1, "42")
    assert(view:read() == "42")
    rejects(function() readonly:write(0, "!") end, "readonly")
    rejects(function() readonly:xor_bytes(0) end, "readonly")
    rejects(function() buffer:write(-2147483648, "") end, "nonnegative")
    rejects(function() buffer:write(5, "") end, "out of bounds")
    rejects(function() view:write(1, "too big") end, "out of bounds")
    rejects(function() buffer:slice(3, 2147483647, false) end, "out of bounds")
    rejects(function() buffer:slice(-1, 0, false) end, "nonnegative")
    rejects(function() buffer:slice(0, -1, false) end, "nonnegative")
    rejects(function() buffer:resize(-1, 0) end, "nonnegative")
    rejects(function() view:xor_bytes(256) end, "range")
    rejects(function() buffer:write(1.5, "a") end, "integer")
    assert(view:read() == "42") -- rejected operations preserve the generation
    buffer:append(""); buffer:resize(4, 0)
    assert(view:read() == "42") -- no-op structural calls preserve views
    buffer:append("!")
    rejects(function() view:read() end, "invalidated")
    rejects(function() view:size() end, "invalidated")
    rejects(function() readonly:readonly() end, "invalidated")
    local current <close> = buffer:slice(0, 5, false)
    buffer:resize(2, 0)
    rejects(function() current:xor_bytes(0) end, "invalidated")
    buffer:resize(5, 255)
    assert(buffer:read() == "a4\255\255\255")
end
do
    local buffer = Buffer.new("data")
    local shared <close> = buffer:share()
    local view <close> = buffer:slice(0, 4, false)
    buffer:close(); buffer = nil
    collect()
    assert(view:read() == "data" and Buffer.live() == 1)
    shared:close()
    assert(Buffer.live() == 0)
    rejects(function() view:read() end, "owner expired")
    view:close(); view:close()
    rejects(function() view:read() end, "closed")
end
do
    local buffer = Buffer.new("GC")
    local view <close> = buffer:slice(0, 2, true)
    buffer = nil
    collect()
    rejects(function() view:read() end, "owner expired")
end
do
    local buffer <close> = Buffer.new("")
    local empty <close> = buffer:slice(0, 0, false)
    assert(empty:size() == 0 and empty:read() == "")
    empty:write(0, ""); empty:xor_bytes(255)
    buffer:append(""); buffer:resize(0, 0)
    assert(empty:read() == "")
    buffer:resize(1, 42)
    rejects(function() empty:read() end, "invalidated")
    local end_view <close> = buffer:slice(1, 0, true)
    assert(end_view:read() == "")
end
assert(demo.demo__decode_u16("") == nil and demo.demo__decode_u16("a") == nil)
assert(demo.demo__decode_u16("\42\0trailing") == 42)
assert(demo.demo__decode_u16("\255\255") == 65535)
assert(demo.demo__decode_u16("\0\0") == 0)
assert(#demo.demo__decode_u16_with_count("x") == 0)
local decoded = demo.demo__decode_u16_with_count("\42\0rest")
assert(#decoded == 2 and decoded[1] == 42 and decoded[2] == 2)
assert(demo.demo__out_buffer(4, 255) == "\255\255\255\255")
assert(demo.demo__out_buffer(0, 0) == "")
assert(demo.demo__inout_increment(41) == 42)
rejects(function() demo.demo__out_buffer(-1, 0) end, "nonnegative")
rejects(function() demo.demo__out_buffer(1, -1) end, "range")
rejects(function() demo.demo__decode_u16(42) end, "string expected")
rejects(function() demo.demo__inout_increment(2147483647) end, "overflow")
collect()
assert(Buffer.live() == 0 and Slice.live() == 0)
print("Lua buffers and out-parameter adapters passed")
