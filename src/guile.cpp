GeneratedGuileSource generate_guile(const Module& module, const std::string& name, bool skip, const BindingPolicy& policy) {
    // Core modules and the first element of the standard module namespaces.
    static const std::set<std::string> reserved_modules = {"guile", "srfi", "rnrs", "scheme", "system",
        "oop", "language", "web", "sxml", "texinfo"};
    if (!identifier(name)) throw BindingError("module name must be a simple ASCII identifier starting with a letter");
    if (reserved_modules.count(name)) throw BindingError("module name is a reserved Guile module name");
    if (!policy.callbacks.empty() || !policy.enum_flags.empty())
        throw BindingError("Guile backend does not yet support callback or enum flag policies");
    GeneratedGuileSource result{{}, {}, module.diagnostics};
    auto reject = [&](const std::string& context, const std::string& reason) { result.diagnostics.push_back(context + ": " + reason); };
    std::ostringstream out, types, definitions;
    // libguile's SCM_UNPACK assigns through a volatile pointer in dead code
    // for type checking, which C++20 deprecates.
    out << "// Generated by Rosetta: Guile extension, loaded by " << name << ".scm.\n"
        << "#if defined(__clang__)\n#if __has_warning(\"-Wdeprecated-volatile\")\n#pragma clang diagnostic ignored \"-Wdeprecated-volatile\"\n#endif\n"
        << "#elif defined(__GNUC__) && __GNUC__ >= 10\n#pragma GCC diagnostic ignored \"-Wvolatile\"\n#endif\n#include <libguile.h>\n"
        << "#include <cmath>\n#include <cstdint>\n#include <cstdlib>\n#include <initializer_list>\n#include <limits>\n#include <memory>\n"
        << "#include <mutex>\n#include <new>\n#include <stdexcept>\n#include <string>\n#include <type_traits>\n#include <unordered_map>\n"
        << "#include <utility>\n#include " << quote(module.header) << '\n' << detail::guile_runtime;
    // Free functions keep their C++ spelling (`::` becomes `__`). Names the
    // backend adds use `-`, `?` or `!`, which C++ names cannot contain.
    std::vector<std::string> exports;
    std::set<std::string> taken;
    auto reserve = [&](const std::string& symbol) {
        if (!taken.insert(symbol).second) throw BindingError("Guile export name collision: " + symbol);
        exports.push_back(symbol);
    };
    std::size_t next = 0;
    // Emits a primitive taking SELF (when given) and the function's
    // parameters, with defaulted parameters optional.
    auto primitive = [&](const Function& fn, const std::string& symbol, const std::string& self, const std::string& call) {
        const auto required = fn.parameters.size() - fn.default_arguments;
        const auto procedure = "rosetta_procedure_" + std::to_string(next++);
        std::vector<std::string> formals;
        if (!self.empty()) formals.push_back("SCM self");
        std::string arguments;
        for (std::size_t i = 0; i < fn.parameters.size(); ++i) {
            formals.push_back("SCM a" + std::to_string(i));
            arguments += (i ? ", a" : "a") + std::to_string(i);
        }
        std::string signature;
        for (const auto& formal : formals) signature += (signature.empty() ? "" : ", ") + formal;
        out << "static SCM " << procedure << '(' << signature << ") {\n"
            << "return rosetta_guile::guard(" << quote(symbol) << ", [&]() -> SCM {\n" << self;
        out << "switch (rosetta_guile::count({" << arguments << "}, " << required << ")) {\n";
        for (std::size_t present = required; present <= fn.parameters.size(); ++present) {
            out << "case " << present << ": {\n";
            std::string actuals;
            for (std::size_t i = 0; i < present; ++i) {
                out << "auto value" << i << " = rosetta_guile::from<" << scalar(fn.parameters[i]) << ">(a" << i << ");\n";
                actuals += (i ? ", value" : "value") + std::to_string(i);
            }
            out << replace_all(call, "@ARGS@", actuals) << "}\n";
        }
        out << "}\nrosetta_guile::fail(\"native\", \"invalid argument dispatch\");\n});\n}\n";
        definitions << "scm_c_define_gsubr(" << quote(symbol) << ", " << required + (self.empty() ? 0 : 1) << ", " << fn.default_arguments
                    << ", 0, reinterpret_cast<scm_t_subr>(&" << procedure << "));\n";
        reserve(symbol);
    };
    auto returning = [](const Function& fn, const std::string& target) {
        if (fn.result.canonical == "void") return target + "(@ARGS@);\nreturn SCM_UNSPECIFIED;\n";
        return "auto result = " + target + "(@ARGS@);\nreturn rosetta_guile::to(result);\n";
    };
    std::map<std::string, std::size_t> counts;
    for (const auto& fn : module.functions) ++counts[fn.qualified_name()];
    for (const auto& fn : module.functions) {
        auto why = problem(fn, false);
        if (counts[fn.qualified_name()] > 1) why = "overloads require an explicit facade";
        if (!why.empty()) { reject(fn.qualified_name(), why); continue; }
        primitive(fn, exported(fn.qualified_name()), {}, returning(fn, "::" + fn.qualified_name()));
    }
    for (const auto& selection : policy.classes)
        if (std::none_of(module.records.begin(), module.records.end(), [&](const Record& r) { return r.qualified_name() == selection.first; }))
            throw BindingError("unknown class in Guile policy: " + selection.first);
    for (const auto& rec : module.records) {
        const auto owner = rec.qualified_name();
        const auto selected = policy.classes.find(owner);
        if (selected == policy.classes.end()) {
            if (!policy.explicit_class_selection && policy.classes.empty()) reject(owner, "class requires an owned class policy");
            continue;
        }
        const auto& config = selected->second;
        for (const auto& requested : config.methods) {
            const auto found = std::find_if(rec.methods.begin(), rec.methods.end(), [&](const Function& f) { return f.name == requested; });
            if (found == rec.methods.end()) throw BindingError("unknown Guile policy method: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Guile policy method is not public: " + owner + "::" + requested);
        }
        for (const auto& requested : config.fields) {
            const auto found = std::find_if(rec.fields.begin(), rec.fields.end(), [&](const Field& f) { return f.name == requested; });
            if (found == rec.fields.end()) throw BindingError("unknown Guile policy field: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Guile policy field is not public: " + owner + "::" + requested);
        }
        if (!rec.complete || rec.abstract || rec.has_bases || !rec.public_destructor || !rec.unsupported_reason.empty()) {
            reject(owner, "Guile requires a complete, concrete class without bases and a public nonthrowing destructor"); continue;
        }
        if (!config.borrow_self.empty()) { reject(owner, "borrowed Guile results are not yet supported"); continue; }
        // SRFI-9 style names: make-K, K?, K-close!, K-method, K-field, set-K-field!.
        const auto key = exported(owner);
        const auto type = "rosetta_type_" + std::to_string(next++);
        const auto native = "::" + owner;
        const auto self = "auto* object = rosetta_guile::self<" + native + ">(" + type + ", self, " + quote(key) + ");\n(void)object;\n";
        out << "static_assert(std::is_nothrow_destructible_v<" << native << ">, \"native owners require nonthrowing destruction\");\n"
            << "static SCM " << type << " = SCM_BOOL_F;\n";
        types << type << " = rosetta_guile::type(" << quote(key) << ", &rosetta_guile::finalize<" << native << ">);\n";
        std::vector<const Function*> constructors;
        for (const auto& ctor : rec.constructors) if (!ctor.is_deleted) constructors.push_back(&ctor);
        if (config.constructors) {
            if (constructors.size() != 1) reject(owner, "constructor overloads require an explicit facade");
            else {
                const auto& ctor = *constructors.front();
                auto why = problem(ctor, false);
                if (ctor.access != "public") why = "constructor is not public";
                if (!why.empty()) reject(owner, why);
                else primitive(ctor, "make-" + key, {}, "return rosetta_guile::adopt(" + type + ", std::make_unique<" + native + ">(@ARGS@));\n");
            }
        }
        const auto helper = "rosetta_procedure_" + std::to_string(next++);
        out << "static SCM " << helper << "_p(SCM self) { return scm_from_bool(rosetta_guile::instance(" << type << ", self)); }\n"
            << "static SCM " << helper << "_close(SCM self) {\nreturn rosetta_guile::guard(" << quote(key + "-close!")
            << ", [&]() -> SCM { return rosetta_guile::close<" << native << ">(" << type << ", self, " << quote(key) << "); });\n}\n";
        definitions << "scm_c_define_gsubr(" << quote(key + "?") << ", 1, 0, 0, reinterpret_cast<scm_t_subr>(&" << helper << "_p));\n"
                    << "scm_c_define_gsubr(" << quote(key + "-close!") << ", 1, 0, 0, reinterpret_cast<scm_t_subr>(&" << helper << "_close));\n";
        reserve(key + "?");
        reserve(key + "-close!");
        counts.clear();
        for (const auto& fn : rec.methods) ++counts[fn.name];
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            auto why = problem(fn, !fn.is_static);
            if (counts[fn.name] > 1) why = "method overloads require an explicit facade";
            if (!why.empty()) { reject(owner + "::" + fn.name, why); continue; }
            if (fn.is_static) primitive(fn, key + "-" + fn.name, {}, returning(fn, native + "::" + fn.name));
            else primitive(fn, key + "-" + fn.name, self, returning(fn, "object->" + fn.name));
        }
        for (const auto& field : rec.fields) {
            if (field.access != "public" || (config.restrict_fields && !config.fields.count(field.name))) continue;
            const auto value = scalar(field.type);
            if (value.empty() || field.bitfield || field.type.is_volatile) { reject(owner + "::" + field.name, "unsupported Guile field type"); continue; }
            const auto getter = key + "-" + field.name, procedure = "rosetta_procedure_" + std::to_string(next++);
            out << "static SCM " << procedure << "_get(SCM self) {\nreturn rosetta_guile::guard(" << quote(getter) << ", [&]() -> SCM {\n"
                << self << "return rosetta_guile::to(object->" << field.name << ");\n});\n}\n";
            definitions << "scm_c_define_gsubr(" << quote(getter) << ", 1, 0, 0, reinterpret_cast<scm_t_subr>(&" << procedure << "_get));\n";
            reserve(getter);
            // Const fields have no setter.
            if (field.type.is_const) continue;
            const auto setter = "set-" + key + "-" + field.name + "!";
            out << "static SCM " << procedure << "_set(SCM self, SCM a0) {\nreturn rosetta_guile::guard(" << quote(setter) << ", [&]() -> SCM {\n"
                << self << "auto value = rosetta_guile::from<" << value << ">(a0);\nobject->" << field.name << " = value;\nreturn SCM_UNSPECIFIED;\n});\n}\n";
            definitions << "scm_c_define_gsubr(" << quote(setter) << ", 2, 0, 0, reinterpret_cast<scm_t_subr>(&" << procedure << "_set));\n";
            reserve(setter);
        }
    }
    for (const auto& enumeration : module.enumerations)
        if (enumeration.selected) reject(enumeration.qualified_name(), "Guile enum bindings are not yet supported");
    if (!skip && !result.diagnostics.empty()) {
        std::string error = "unsupported declaration for Guile";
        for (const auto& entry : result.diagnostics) error += "\n  " + entry;
        throw BindingError(error);
    }
    const auto init = "rosetta_init_" + name;
    out << "extern \"C\" {\n#if defined(_WIN32)\n__declspec(dllexport)\n#else\n__attribute__((visibility(\"default\")))\n#endif\n"
        << "void " << init << "(void) {\n" << types.str() << definitions.str()
        << "std::atexit(&rosetta_guile::shutdown);\n}\n}\n";
    result.source = out.str();

    std::ostringstream interface;
    interface << ";;; Generated by Rosetta; keep beside the " << name << " extension (" << name << ".so, .dylib or .dll).\n"
              << ";;; Load with (use-modules (" << name << ")).\n(define-module (" << name << ")\n  #:export (";
    for (std::size_t i = 0; i < exports.size(); ++i) interface << (i ? "\n            " : "") << exports[i];
    interface << "))\n" << replace_all(replace_all(detail::guile_interface_runtime, "@MODULE@", name), "@INIT@", init);
    result.interface = interface.str();
    return result;
}
