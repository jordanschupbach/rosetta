bool identifier(const std::string& name) {
    auto letter = [](char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'); };
    return !name.empty() && letter(name[0]) && std::all_of(name.begin(), name.end(), [&](char c) {
        return letter(c) || (c >= '0' && c <= '9') || c == '_';
    });
}
std::string quote(const std::string& text) {
    std::string result = "\"";
    for (char c : text) {
        if (c == '\\' || c == '"') result += '\\';
        if (c == '\n') result += "\\n";
        else if (c == '\r') result += "\\r";
        else result += c;
    }
    return result + '"';
}
std::string exported(std::string name) {
    for (std::size_t p = 0; (p = name.find("::", p)) != std::string::npos; p += 2) name.replace(p, 2, "__");
    return name;
}
std::string scalar(const Type& type) {
    auto text = detail::trim_type(type.canonical);
    // Only const string references are copied; mutable references need an adapter.
    const bool const_reference = text.rfind("const ", 0) == 0 && !text.empty() && text.back() == '&' &&
        (text.size() < 2 || text[text.size() - 2] != '&');
    if (const_reference) text = detail::trim_type(text.substr(0, text.size() - 1));
    if (text.rfind("const ", 0) == 0) text = text.substr(6);
    if (text == "std::__cxx11::basic_string<char>" || text == "std::__1::basic_string<char>" || text == "std::basic_string<char>")
        text = "std::string";
    if (const_reference && text != "std::string") return {};
    static const std::set<std::string> supported = {"bool", "char", "signed char", "unsigned char", "short", "unsigned short",
        "int", "unsigned int", "long", "unsigned long", "long long", "unsigned long long", "float", "double", "std::string"};
    return supported.count(text) ? text : "";
}
std::string function_problem(const Function& fn) {
    if (!fn.unsupported_reason.empty()) return fn.unsupported_reason;
    if (fn.is_deleted) return "deleted function";
    if (!fn.is_constructor && fn.result.canonical != "void" && scalar(fn.result).empty())
        return "unsupported R result type " + fn.result.canonical;
    for (const auto& type : fn.parameters)
        if (scalar(type).empty()) return "unsupported R parameter type " + type.canonical;
    return {};
}
