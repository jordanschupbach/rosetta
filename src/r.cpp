GeneratedRSource generate_r(const Module& module, const std::string& name, RObjectSystem object_system,
                            bool skip_unsupported, const BindingPolicy& policy) {
    if (object_system != RObjectSystem::r6 && object_system != RObjectSystem::s3 && object_system != RObjectSystem::s4)
        throw BindingError("unsupported R object system");
    const bool r6 = object_system == RObjectSystem::r6;
    const std::string system_name = r6 ? "R6" : object_system == RObjectSystem::s3 ? "S3" : "S4";
    if (!identifier(name)) throw BindingError("module name must be a simple ASCII identifier starting with a letter");
    GeneratedRSource result{{}, {}, module.diagnostics};
    auto reject = [&](const std::string& context, const std::string& reason) {
        result.diagnostics.push_back(context + ": " + reason);
    };
    if (!policy.callbacks.empty() || !policy.enum_flags.empty())
        throw BindingError("R backend does not yet support callback or enum flag policies");
    std::ostringstream cpp, r, registration;
    cpp << "// Generated by Rosetta: R native bridge.\n#define R_NO_REMAP\n#include <R.h>\n#include <Rinternals.h>\n"
        << "#include <R_ext/Rdynload.h>\n#include <R_ext/Visibility.h>\n#include <climits>\n#include <cmath>\n#include <cstdio>\n"
        << "#include <limits>\n#include <stdexcept>\n#include <string>\n#include <type_traits>\n#include " << quote(module.header) << "\n"
        << detail::r_runtime;
    r << "# Generated by Rosetta. Load " << name << " shared library with dyn.load() before sourcing.\n"
      << '`' << name << "` <- local({\n"
      << (r6 ? "  if (!requireNamespace(\"R6\", quietly = TRUE)) stop(\"Install the R6 package\")\n" :
          object_system == RObjectSystem::s4 ? "  if (!requireNamespace(\"methods\", quietly = TRUE)) stop(\"The methods package is required\")\n" : "")
      << "  if (is.null(getLoadedDLLs()[[" << quote(name) << "]])) stop(\"Load the " << name << " shared library with dyn.load() first\")\n"
      << "  call <- function(symbol, ...) {\n"
      << "    dll <- getLoadedDLLs()[[" << quote(name) << "]]\n"
      << "    if (is.null(dll)) stop(\"Native library is not loaded\")\n"
      << "    .Call(getNativeSymbolInfo(symbol, PACKAGE = dll)$address, ...)\n  }\n"
      << "  exports <- list()\n";
    if (!r6) r << (object_system == RObjectSystem::s3 ? detail::r_s3_interface : detail::r_s4_interface);
    std::set<std::string> exports;
    auto reserve = [&](const std::string& text) {
        if (!exports.insert(text).second) throw BindingError("R export name collision: " + text);
    };
    std::size_t next = 0;
    // Every bridge entry uses an exception boundary, including accessors and close.
    auto wrapper = [&](const std::vector<std::string>& parameters, const std::string& body) {
        const auto symbol = "rosetta_" + name + "_" + std::to_string(next++);
        cpp << "static SEXP " << symbol << '(';
        for (std::size_t i = 0; i < parameters.size(); ++i) cpp << (i ? ", " : "") << "SEXP " << parameters[i];
        cpp << ") { return rosetta_r::boundary([&](SEXP token) -> SEXP {\n(void)token;\n" << body << "\n}); }\n";
        registration << "    {" << quote(symbol) << ", reinterpret_cast<DL_FUNC>(&" << symbol << "), " << parameters.size() << "},\n";
        return symbol;
    };
    std::string constructor_class;
    auto emit_function = [&](const Function& fn, const std::string& receiver, const std::string& target) {
        std::vector<std::string> parameters;
        if (!receiver.empty()) parameters.push_back("ptr");
        std::string body = receiver;
        std::string formals, actuals, native_args;
        for (std::size_t i = 0; i < fn.parameters.size(); ++i) {
            const auto arg = "arg" + std::to_string(i + 1);
            parameters.push_back(arg);
            if (i) { formals += ", "; actuals += ", "; native_args += ", "; }
            formals += arg; actuals += arg; native_args += "value" + std::to_string(i);
            body += "auto value" + std::to_string(i) + " = rosetta_r::from<" + scalar(fn.parameters[i]) + ">(" + arg + ");\n";
        }
        if (fn.is_constructor) {
            body += "SEXP result = PROTECT(R_MakeExternalPtr(nullptr, "
                "Rf_install(" + quote(name + ":" + fn.owner) + "), R_NilValue));\n";
            body += "R_RegisterCFinalizerEx(result, rosetta_r::finalize<::" + fn.owner + ">, TRUE);\n";
            body += "try { R_SetExternalPtrAddr(result, new ::" + fn.owner + "(" + native_args + ")); }\n"
                "catch (...) { UNPROTECT(1); throw; }\nUNPROTECT(1);\nreturn result;";
        } else if (fn.result.canonical == "void") body += target + "(" + native_args + ");\nreturn R_NilValue;";
        else body += "auto result = " + target + "(" + native_args + ");\nreturn rosetta_r::to(result, token);";
        const auto symbol = wrapper(parameters, body);
        if (!r6 && !receiver.empty()) formals = "object" + (formals.empty() ? "" : ", " + formals);
        const auto invocation = "call(" + quote(symbol) + (receiver.empty() ? "" : r6 ? ", private$.ptr" : ", pointer(object)") +
            (actuals.empty() ? "" : ", " + actuals) + ")";
        return "function(" + formals + ") " + (fn.is_constructor ?
            (r6 ? "private$.ptr <- " + invocation : "construct(" + invocation + ", " + quote(constructor_class) + ")") : invocation);
    };
    std::map<std::string, std::size_t> function_counts;
    for (const auto& fn : module.functions) ++function_counts[fn.qualified_name()];
    for (const auto& fn : module.functions) {
        auto problem = function_problem(fn);
        if (function_counts[fn.qualified_name()] > 1) problem = "overloads require an explicit facade";
        if (!problem.empty()) { reject(fn.qualified_name(), problem); continue; }
        const auto key = exported(fn.qualified_name()); reserve(key);
        r << "  exports[[" << quote(key) << "]] <- " << emit_function(fn, {}, "::" + fn.qualified_name()) << '\n';
    }
    for (const auto& config : policy.classes)
        if (std::none_of(module.records.begin(), module.records.end(), [&](const Record& rec) { return rec.qualified_name() == config.first; }))
            throw BindingError("unknown class in R policy: " + config.first);
    for (const auto& rec : module.records) {
        const auto identity = rec.qualified_name();
        const auto selected = policy.classes.find(identity);
        if (selected == policy.classes.end()) {
            if (!policy.explicit_class_selection && policy.classes.empty()) reject(identity, "class requires an owned class policy");
            continue;
        }
        const auto& config = selected->second;
        for (const auto& requested : config.methods) {
            const auto found = std::find_if(rec.methods.begin(), rec.methods.end(), [&](const Function& fn) { return fn.name == requested; });
            if (found == rec.methods.end()) throw BindingError("unknown " + system_name + " policy method: " + identity + "::" + requested);
            if (found->access != "public") throw BindingError(system_name + " policy method is not public: " + identity + "::" + requested);
        }
        for (const auto& requested : config.fields) {
            const auto found = std::find_if(rec.fields.begin(), rec.fields.end(), [&](const Field& field) { return field.name == requested; });
            if (found == rec.fields.end()) throw BindingError("unknown " + system_name + " policy field: " + identity + "::" + requested);
            if (found->access != "public") throw BindingError(system_name + " policy field is not public: " + identity + "::" + requested);
        }
        if (!rec.complete || rec.abstract || rec.has_bases || !rec.public_destructor || !rec.unsupported_reason.empty()) {
            reject(identity, system_name + " requires a complete, concrete class without bases and a public nonthrowing destructor"); continue;
        }
        if (!config.borrow_self.empty()) { reject(identity, "borrowed " + system_name + " results are not yet supported"); continue; }
        const auto key = exported(identity); reserve(key);
        constructor_class = "rosetta_" + name + "_" + key + "_" + system_name;
        auto functional_member = [&](const std::string& member, const std::string& function, bool generic = true) {
            const auto export_key = key + "__" + member;
            reserve(export_key);
            r << "  exports[[" << quote(export_key) << "]] <- ";
            if (generic) r << "define(" << quote(name + "__" + export_key) << ", " << quote(constructor_class) << ", ";
            r << function << (generic ? ")" : "") << '\n';
            r << "  exports[[" << quote(key) << "]][[" << quote(member) << "]] <- exports[[" << quote(export_key) << "]]\n";
        };
        const auto tag = "Rf_install(" + quote(name + ":" + identity) + ")";
        const auto receiver = "auto* self = rosetta_r::object<::" + identity + ">(ptr, " + tag + ");\n";
        const auto close = wrapper({"ptr"}, "if (ptr == R_NilValue) return R_NilValue;\n"
            "if (TYPEOF(ptr) != EXTPTRSXP || R_ExternalPtrTag(ptr) != " + tag + ") throw std::runtime_error(\"wrong native object type\");\n"
            "rosetta_r::finalize<::" + identity + ">(ptr);\nreturn R_NilValue;");
        std::string initialize = "function(...) stop(\"No supported constructor exported\")";
        if (config.constructors) {
            if (rec.constructors.size() != 1) reject(identity, "constructor overloads require an explicit facade");
            else {
                const auto& ctor = rec.constructors.front();
                auto problem = function_problem(ctor);
                if (ctor.access != "public") problem = "constructor is not public";
                if (!problem.empty()) reject(identity, problem);
                else {
                    initialize = emit_function(ctor, {}, {});
                    if (r6) {
                        // R6 allows initialize() to be called again; never replace a live owner.
                        const auto pos = initialize.find(") ");
                        initialize.insert(pos + 2, "{ if (!is.null(private$.ptr)) stop(\"Object already initialized\"); ");
                        initialize += " }";
                    }
                }
            }
        }
        if (r6) r << "  exports[[" << quote(key) << "]] <- R6::R6Class(" << quote(key) << ", cloneable = FALSE,\n"
          << "    private = list(.ptr = NULL, finalize = function() { call(" << quote(close) << ", private$.ptr); private$.ptr <- NULL }),\n"
          << "    public = list(initialize = " << initialize << ",\n"
          << "      close = function() { call(" << quote(close) << ", private$.ptr); private$.ptr <- NULL; invisible(self) }";
        else {
            if (object_system == RObjectSystem::s4)
                r << "  definitions[[" << quote(constructor_class) << "]] <- methods::setClass(" << quote(constructor_class)
                  << ", slots = c(.ptr = \"externalptr\"), where = api)\n";
            r << "  exports[[" << quote(key) << "]] <- list(new = " << initialize << ", class = " << quote(constructor_class) << ")\n";
            functional_member("close", "function(object) { call(" + quote(close) + ", pointer(object)); invisible(object) }");
        }
        std::set<std::string> members = {"initialize", "finalize", "close", "clone", "self", "private", "super", ".ptr", ".__enclos_env__"};
        std::map<std::string, std::size_t> method_counts;
        for (const auto& fn : rec.methods) ++method_counts[fn.name];
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            auto problem = function_problem(fn);
            if (method_counts[fn.name] > 1) problem = "method overloads require an explicit facade";
            if (!problem.empty()) { reject(identity + "::" + fn.name, problem); continue; }
            if (!members.insert(fn.name).second) throw BindingError("reserved or duplicate " + system_name + " member: " + fn.name);
            const auto function = emit_function(fn, fn.is_static ? "" : receiver,
                fn.is_static ? "::" + identity + "::" + fn.name : "self->" + fn.name);
            if (r6) r << ",\n      " << quote(fn.name) << " = " << function;
            else functional_member(fn.name, function, !fn.is_static);
        }
        if (r6) r << "),\n    active = list(";
        bool first = true;
        for (const auto& field : rec.fields) {
            if (field.access != "public" || (config.restrict_fields && !config.fields.count(field.name))) continue;
            const auto type = scalar(field.type);
            if (type.empty() || field.bitfield || field.type.is_volatile) { reject(identity + "::" + field.name, "unsupported R field type"); continue; }
            if (!members.insert(field.name).second) throw BindingError("reserved or duplicate " + system_name + " member: " + field.name);
            const auto get = wrapper({"ptr"}, receiver + "return rosetta_r::to(self->" + field.name + ", token);");
            if (r6) r << (first ? "" : ", ") << quote(field.name) << " = function(value) { if (missing(value)) return(call(" << quote(get) << ", private$.ptr)); ";
            else functional_member("get_" + field.name, "function(object) call(" + quote(get) + ", pointer(object))");
            first = false;
            if (field.type.is_const) {
                if (r6) r << "stop(\"Readonly field\")";
                else functional_member("set_" + field.name, "function(object, value) stop(\"Readonly field\")");
            }
            else {
                const auto set = wrapper({"ptr", "value"}, receiver + "self->" + field.name + " = rosetta_r::from<" + type + ">(value);\nreturn R_NilValue;");
                if (r6) r << "call(" << quote(set) << ", private$.ptr, value); invisible(value)";
                else functional_member("set_" + field.name, "function(object, value) { call(" + quote(set) + ", pointer(object), value); invisible(object) }");
            }
            if (r6) r << " }";
        }
        if (r6) r << "))\n";
    }
    for (const auto& enumeration : module.enumerations)
        if (enumeration.selected) reject(enumeration.qualified_name(), "R enum bindings are not yet supported");
    if (!skip_unsupported && !result.diagnostics.empty()) {
        std::string error = "unsupported declaration for " + system_name;
        for (const auto& diagnostic : result.diagnostics) error += "\n  " + diagnostic;
        throw BindingError(error);
    }
    cpp << "static const R_CallMethodDef rosetta_calls[] = {\n" << registration.str() << "    {nullptr, nullptr, 0}\n};\n"
        << "extern \"C\" void attribute_visible R_init_" << name << "(DllInfo* dll) {\n"
        << "    R_registerRoutines(dll, nullptr, rosetta_calls, nullptr, nullptr);\n"
        << "    R_useDynamicSymbols(dll, FALSE);\n    R_forceSymbols(dll, TRUE);\n}\n";
    r << "  exports\n})\n";
    result.source = cpp.str(); result.interface = r.str();
    return result;
}
