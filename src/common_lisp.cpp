GeneratedCommonLispSource generate_common_lisp(const Module& module, const std::string& name, bool skip, const BindingPolicy& policy) {
    // Package names the generated file loads or that every image has.
    static const std::set<std::string> reserved_packages = {"CL", "KEYWORD", "CFFI", "ASDF", "UIOP", "TG", "BABEL", "ALEXANDRIA"};
    if (!identifier(name)) throw BindingError("module name must be a simple ASCII identifier starting with a letter");
    const auto package = upper(name);
    if (reserved_packages.count(package)) throw BindingError("module name is a reserved Common Lisp package name");
    if (!policy.callbacks.empty() || !policy.enum_flags.empty())
        throw BindingError("Common Lisp backend does not yet support callback or enum flag policies");
    GeneratedCommonLispSource result{{}, {}, module.diagnostics};
    auto reject = [&](const std::string& context, const std::string& reason) { result.diagnostics.push_back(context + ": " + reason); };
    std::ostringstream out, dispatch, lisp;
    out << "// Generated by Rosetta: private C ABI for Common Lisp CFFI.\n"
        << "#include <cmath>\n#include <cstdint>\n#include <cstdlib>\n#include <cstring>\n#include <limits>\n#include <memory>\n#include <mutex>\n"
        << "#include <new>\n#include <stdexcept>\n#include <string>\n#include <type_traits>\n#include <unordered_map>\n"
        << "#include " << quote(module.header) << '\n' << detail::common_lisp_runtime;
    // C++ names are case-sensitive and Lisp's reader upcases, so exports are
    // upcased symbols, unique ignoring case. They contain no hyphen, unlike
    // every runtime export, and the public package uses no other package, so
    // C++ names such as `list` never touch COMMON-LISP.
    const std::string prefix = "|" + package + "|:";
    std::vector<std::string> exports;
    std::set<std::string> taken;
    auto reserve = [&](const std::string& key) {
        const auto symbol = upper(key);
        if (!taken.insert(symbol).second) throw BindingError("Common Lisp export name collision (ignoring case): " + key);
        exports.push_back(symbol);
        return prefix + "|" + symbol + "|";
    };
    auto body = [&](const Function& fn, const std::string& target, const std::string& owner) {
        std::ostringstream code;
        code << "rosetta_abi::arity(count, " << fn.parameters.size() - fn.default_arguments << ", " << fn.parameters.size() << ");\nswitch (count) {\n";
        for (std::size_t count = fn.parameters.size() - fn.default_arguments; count <= fn.parameters.size(); ++count) {
            code << "case " << count << ": {\n";
            std::string actuals;
            for (std::size_t i = 0; i < count; ++i) {
                code << "auto value" << i << " = rosetta_abi::from<" << scalar(fn.parameters[i]) << ">(args[" << i << "]);\n";
                if (i) actuals += ", ";
                actuals += "value" + std::to_string(i);
            }
            if (fn.is_constructor)
                code << "return rosetta_abi::to(rosetta_abi::own(std::make_unique<::" << owner << ">(" << actuals << ")));\n";
            else if (fn.result.canonical == "void") code << target << '(' << actuals << "); return {};\n";
            else code << "auto result = " << target << '(' << actuals << "); return rosetta_abi::to(result);\n";
            code << "}\n";
        }
        code << "}\nthrow rosetta_abi::conversion_error(\"invalid argument dispatch\");\n";
        return code.str();
    };
    auto entry = [&](const std::string& key, const std::string& code) {
        dispatch << "if (operation == " << quote(key) << ") {\n" << code << "}\n";
    };
    std::map<std::string, std::size_t> counts;
    for (const auto& fn : module.functions) ++counts[fn.qualified_name()];
    for (const auto& fn : module.functions) {
        auto why = problem(fn);
        if (counts[fn.qualified_name()] > 1) why = "overloads require an explicit facade";
        if (!why.empty()) { reject(fn.qualified_name(), why); continue; }
        const auto key = exported(fn.qualified_name());
        const auto symbol = reserve(key);
        entry(key, body(fn, "::" + fn.qualified_name(), {}));
        lisp << "(defun " << symbol << " (&rest arguments) (invoke " << lisp_string(key) << " 0 arguments))\n";
    }
    for (const auto& selection : policy.classes)
        if (std::none_of(module.records.begin(), module.records.end(), [&](const Record& r) { return r.qualified_name() == selection.first; }))
            throw BindingError("unknown class in Common Lisp policy: " + selection.first);
    for (const auto& rec : module.records) {
        const auto owner = rec.qualified_name();
        const auto selected = policy.classes.find(owner);
        if (selected == policy.classes.end()) {
            if (!policy.explicit_class_selection && policy.classes.empty()) reject(owner, "class requires an owned class policy");
            continue;
        }
        const auto& config = selected->second;
        for (const auto& requested : config.methods) {
            const auto found = std::find_if(rec.methods.begin(), rec.methods.end(), [&](const Function& f) { return f.name == requested; });
            if (found == rec.methods.end()) throw BindingError("unknown Common Lisp policy method: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Common Lisp policy method is not public: " + owner + "::" + requested);
        }
        for (const auto& requested : config.fields) {
            const auto found = std::find_if(rec.fields.begin(), rec.fields.end(), [&](const Field& f) { return f.name == requested; });
            if (found == rec.fields.end()) throw BindingError("unknown Common Lisp policy field: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Common Lisp policy field is not public: " + owner + "::" + requested);
        }
        if (!rec.complete || rec.abstract || rec.has_bases || !rec.public_destructor || !rec.unsupported_reason.empty()) {
            reject(owner, "Common Lisp requires a complete, concrete class without bases and a public nonthrowing destructor"); continue;
        }
        if (!config.borrow_self.empty()) { reject(owner, "borrowed Common Lisp results are not yet supported"); continue; }
        const auto key = exported(owner);
        const auto klass = reserve(key);
        out << "static_assert(std::is_nothrow_destructible_v<::" << owner << ">, \"native owners require nonthrowing destruction\");\n";
        // The class and its constructor function share one symbol.
        lisp << "(defclass " << klass << " (" << prefix << "native-owner) ())\n"
             << "(defun " << klass << " (&rest arguments)\n";
        std::vector<const Function*> constructors;
        for (const auto& ctor : rec.constructors) if (!ctor.is_deleted) constructors.push_back(&ctor);
        bool constructor = false;
        if (config.constructors) {
            if (constructors.size() != 1) reject(owner, "constructor overloads require an explicit facade");
            else {
                const auto& ctor = *constructors.front();
                auto why = problem(ctor);
                if (ctor.access != "public") why = "constructor is not public";
                if (!why.empty()) reject(owner, why);
                else {
                    entry(key + ".new", body(ctor, {}, owner));
                    lisp << "  (adopt '" << klass << " (invoke " << lisp_string(key + ".new") << " 0 arguments)))\n";
                    constructor = true;
                }
            }
        }
        if (!constructor) lisp << "  (declare (ignore arguments))\n  (fail :conversion \"no supported constructor exported\"))\n";
        const auto self = "(owner-id owner '" + klass + ")";
        counts.clear();
        for (const auto& fn : rec.methods) ++counts[fn.name];
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            auto why = problem(fn);
            if (counts[fn.name] > 1) why = "method overloads require an explicit facade";
            if (!why.empty()) { reject(owner + "::" + fn.name, why); continue; }
            const auto symbol = reserve(key + "__" + fn.name);
            const auto operation = key + "." + fn.name;
            const auto target = fn.is_static ? "::" + owner + "::" + fn.name : "rosetta_abi::object<::" + owner + ">(id)->" + fn.name;
            entry(operation, body(fn, target, {}));
            if (fn.is_static) lisp << "(defun " << symbol << " (&rest arguments) (invoke " << lisp_string(operation) << " 0 arguments))\n";
            else lisp << "(defun " << symbol << " (owner &rest arguments) (invoke " << lisp_string(operation) << ' ' << self << " arguments))\n";
        }
        for (const auto& field : rec.fields) {
            if (field.access != "public" || (config.restrict_fields && !config.fields.count(field.name))) continue;
            if (scalar(field.type).empty() || field.bitfield || field.type.is_volatile) {
                reject(owner + "::" + field.name, "unsupported Common Lisp field type"); continue;
            }
            const auto symbol = reserve(key + "__" + field.name);
            const auto get = key + ".get." + field.name, set = key + ".set." + field.name;
            entry(get, "rosetta_abi::arity(count, 0, 0); return rosetta_abi::to(rosetta_abi::object<::" + owner + ">(id)->" + field.name + ");\n");
            lisp << "(defun " << symbol << " (owner) (invoke " << lisp_string(get) << ' ' << self << " '()))\n";
            if (field.type.is_const)
                lisp << "(defun (setf " << symbol << ") (value owner)\n  (declare (ignore value owner))\n"
                     << "  (fail :conversion \"native property is readonly\"))\n";
            else {
                entry(set, "rosetta_abi::arity(count, 1, 1); auto value = rosetta_abi::from<" + scalar(field.type) + ">(args[0]);\nrosetta_abi::object<::" + owner + ">(id)->" + field.name + " = value; return {};\n");
                lisp << "(defun (setf " << symbol << ") (value owner)\n  (invoke " << lisp_string(set) << ' ' << self
                     << " (list value))\n  value)\n";
            }
        }
    }
    for (const auto& enumeration : module.enumerations)
        if (enumeration.selected) reject(enumeration.qualified_name(), "Common Lisp enum bindings are not yet supported");
    if (!skip && !result.diagnostics.empty()) {
        std::string error = "unsupported declaration for Common Lisp";
        for (const auto& entry : result.diagnostics) error += "\n  " + entry;
        throw BindingError(error);
    }
    out << "extern \"C\" {\nstd::uint64_t rosetta_" << name << "_abi() noexcept { return 1; }\n"
        << "void rosetta_" << name << "_free(const char* bytes) noexcept { std::free(const_cast<char*>(bytes)); }\n"
        << "void rosetta_" << name << "_shutdown() noexcept {\nstd::lock_guard<std::mutex> lock(rosetta_abi::registry().mutex);\nrosetta_abi::registry().owners.clear();\n}\n"
        << "void rosetta_" << name << "_call(const char* op, std::uint64_t id, const rosetta_abi::Value* args, std::size_t count, rosetta_abi::Result* result) noexcept {\n"
        << "rosetta_abi::guard(result, [&]() -> rosetta_abi::Value {\n(void)args; (void)count;\nconst std::string operation(op);\n"
        << "if (operation == \"__close\") { rosetta_abi::arity(count, 0, 0); rosetta_abi::registry().owners.erase(id); return {}; }\n"
        << dispatch.str() << "throw rosetta_abi::conversion_error(\"unknown native operation\");\n});\n}\n}\n";

    std::ostringstream interface;
    interface << ";;;; Generated by Rosetta; keep alongside " << name << ".<shared-library extension>.\n"
              << ";;;; Requires CFFI and trivial-garbage, loaded through ASDF when absent.\n"
              << "(eval-when (:compile-toplevel :load-toplevel :execute)\n"
              << "  (unless (and (find-package \"CFFI\") (find-package \"TRIVIAL-GARBAGE\"))\n"
              << "    (require \"asdf\")\n"
              << "    (dolist (system '(\"cffi\" \"trivial-garbage\"))\n"
              << "      (funcall (intern \"LOAD-SYSTEM\" \"ASDF\") system))))\n"
              << "(defpackage " << lisp_string(package + ".IMPL") << " (:use \"COMMON-LISP\"))\n"
              << "(defpackage " << lisp_string(package) << "\n  (:use)\n  (:export \"ROSETTA-ERROR\" \"ROSETTA-ERROR-KIND\" \"ROSETTA-ERROR-MESSAGE\"\n"
              << "           \"NATIVE-OWNER\" \"WITH-OWNER\"";
    for (const auto& symbol : exports) interface << "\n           " << lisp_string(symbol);
    interface << "))\n(in-package " << lisp_string(package + ".IMPL") << ")\n"
              << replace_all(replace_all(replace_all(detail::common_lisp_interface_runtime, "@PACKAGE@", "|" + package + "|"),
                                         "@LIBRARY@", name), "@ABI@", "rosetta_" + name)
              << lisp.str();
    result.source = out.str(); result.interface = interface.str();
    return result;
}
