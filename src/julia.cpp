GeneratedJuliaSource generate_julia(const Module& module, const std::string& name, bool skip, const BindingPolicy& policy) {
    static const std::set<std::string> reserved = {"baremodule", "begin", "break", "catch", "const", "continue", "do", "else", "elseif", "end",
        "export", "false", "finally", "for", "function", "global", "if", "import", "let", "local", "macro", "module", "quote", "return",
        "struct", "true", "try", "using", "while", "where", "in", "isa", "mutable", "primitive", "abstract", "type", "public", "as", "outer", "new",
        "Base", "Core", "Main", "Libdl", "Serialization", "RosettaError", "eval", "include", "nothing", "missing", "ccall",
        "Bool", "Int8", "Int16", "Int32", "Int64", "UInt8", "UInt16", "UInt32", "UInt64", "Float32", "Float64", "String", "Symbol",
        "Ptr", "Ref", "Csize_t", "Cvoid", "Cstring", "C_NULL", "Union", "Exception", "AbstractString", "IO", "IdDict", "GC",
        "map", "pointer", "sizeof", "unsafe_string", "getfield", "length", "joinpath", "error", "throw", "print", "finalizer", "atexit", "close"};
    if (!identifier(name)) throw BindingError("module name must be a simple ASCII identifier starting with a letter");
    if (reserved.count(name)) throw BindingError("module name is a reserved Julia name");
    if (!policy.callbacks.empty() || !policy.enum_flags.empty()) throw BindingError("Julia backend does not yet support callback or enum flag policies");
    GeneratedJuliaSource result{{}, {}, module.diagnostics};
    auto reject = [&](const std::string& context, const std::string& reason) { result.diagnostics.push_back(context + ": " + reason); };
    std::ostringstream out, dispatch, jl;
    out << "// Generated by Rosetta: private C ABI for Julia ccall.\n"
        << "#include <cmath>\n#include <cstdint>\n#include <cstdlib>\n#include <cstring>\n#include <limits>\n#include <memory>\n#include <mutex>\n"
        << "#include <new>\n#include <stdexcept>\n#include <string>\n#include <type_traits>\n#include <unordered_map>\n"
        << "#include " << quote(module.header) << '\n' << detail::julia_runtime;
    jl << "# Generated by Rosetta; keep alongside " << name << ".<shared-library extension>.\nmodule " << name << '\n'
        << detail::julia_interface_runtime
        << "const _library = joinpath(@__DIR__, " << jlquote(name + ".") << " * Libdl.dlext)\n"
        << "function _invoke(operation, id, arguments...)\n"
        << "args = map(x -> x isa AbstractString ? String(x) : x, arguments)\n"
        << "result = Ref(_Result(_empty, 0))\ntry\n"
        << "GC.@preserve args begin\n"
        << "packed = _Value[_pack(x) for x in args]\n"
        << "ccall((:rosetta_" << name << "_call, _library), Cvoid, (Cstring, UInt64, Ptr{_Value}, Csize_t, Ref{_Result}), operation, id, packed, length(packed), result)\nend\n"
        << "if result[].error != 0\n"
        << "kinds = (:allocation, :range, :index, :argument, :native, :conversion)\n"
        << "throw(RosettaError(kinds[result[].error], result[].value.data == C_NULL ? \"native allocation failed\" : _text(result[].value)))\nend\n"
        << "return _decode(result[].value)\nfinally\n"
        << "ccall((:rosetta_" << name << "_free, _library), Cvoid, (Ptr{UInt8},), result[].value.data)\nend\nend\n"
        << "Base.close(owner::_Owner) = (_invoke(\"__close\", getfield(owner, :_id)); nothing)\n"
        << "function __init__()\n"
        << "ccall((:rosetta_" << name << "_abi, _library), UInt64, ()) == 1 || error(\"Rosetta Julia ABI mismatch\")\n"
        << "atexit(() -> ccall((:rosetta_" << name << "_shutdown, _library), Cvoid, ()))\nend\n";
    std::set<std::string> exports{name};
    auto reserve = [&](const std::string& key) {
        if (!identifier(key) || reserved.count(key)) throw BindingError("invalid or reserved Julia export: " + key);
        if (!exports.insert(key).second) throw BindingError("Julia export name collision: " + key);
    };
    auto body = [&](const Function& fn, const std::string& target, const std::string& owner) {
        std::ostringstream code;
        code << "rosetta_jl::arity(count, " << fn.parameters.size() - fn.default_arguments << ", " << fn.parameters.size() << ");\nswitch (count) {\n";
        for (std::size_t count = fn.parameters.size() - fn.default_arguments; count <= fn.parameters.size(); ++count) {
            code << "case " << count << ": {\n";
            std::string actuals;
            for (std::size_t i = 0; i < count; ++i) {
                code << "auto value" << i << " = rosetta_jl::from<" << scalar(fn.parameters[i]) << ">(args[" << i << "]);\n";
                if (i) actuals += ", ";
                actuals += "value" + std::to_string(i);
            }
            if (fn.is_constructor)
                code << "return rosetta_jl::to(rosetta_jl::own(std::make_unique<::" << owner << ">(" << actuals << ")));\n";
            else if (fn.result.canonical == "void") code << target << '(' << actuals << "); return {};\n";
            else code << "auto result = " << target << '(' << actuals << "); return rosetta_jl::to(result);\n";
            code << "}\n";
        }
        code << "}\nthrow rosetta_jl::conversion_error(\"invalid argument dispatch\");\n";
        return code.str();
    };
    auto entry = [&](const std::string& key, const std::string& code) {
        dispatch << "if (operation == " << quote(key) << ") {\n" << code << "}\n";
    };
    std::map<std::string, std::size_t> counts;
    for (const auto& fn : module.functions) ++counts[fn.qualified_name()];
    for (const auto& fn : module.functions) {
        auto why = problem(fn);
        if (counts[fn.qualified_name()] > 1) why = "overloads require an explicit facade";
        if (!why.empty()) { reject(fn.qualified_name(), why); continue; }
        const auto key = exported(fn.qualified_name()); reserve(key);
        entry(key, body(fn, "::" + fn.qualified_name(), {}));
        jl << "function " << key << " end\n" << key << "(args...) = _invoke(" << jlquote(key) << ", 0, args...)\n";
    }
    for (const auto& selection : policy.classes)
        if (std::none_of(module.records.begin(), module.records.end(), [&](const Record& r) { return r.qualified_name() == selection.first; }))
            throw BindingError("unknown class in Julia policy: " + selection.first);
    for (const auto& rec : module.records) {
        const auto owner = rec.qualified_name();
        const auto selected = policy.classes.find(owner);
        if (selected == policy.classes.end()) {
            if (!policy.explicit_class_selection && policy.classes.empty()) reject(owner, "class requires an owned class policy");
            continue;
        }
        const auto& config = selected->second;
        for (const auto& requested : config.methods) {
            const auto found = std::find_if(rec.methods.begin(), rec.methods.end(), [&](const Function& f) { return f.name == requested; });
            if (found == rec.methods.end()) throw BindingError("unknown Julia policy method: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Julia policy method is not public: " + owner + "::" + requested);
        }
        for (const auto& requested : config.fields) {
            const auto found = std::find_if(rec.fields.begin(), rec.fields.end(), [&](const Field& f) { return f.name == requested; });
            if (found == rec.fields.end()) throw BindingError("unknown Julia policy field: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Julia policy field is not public: " + owner + "::" + requested);
        }
        if (!rec.complete || rec.abstract || rec.has_bases || !rec.public_destructor || !rec.unsupported_reason.empty()) {
            reject(owner, "Julia requires a complete, concrete class without bases and a public nonthrowing destructor"); continue;
        }
        if (!config.borrow_self.empty()) { reject(owner, "borrowed Julia results are not yet supported"); continue; }
        const auto key = exported(owner); reserve(key);
        out << "static_assert(std::is_nothrow_destructible_v<::" << owner << ">, \"native owners require nonthrowing destruction\");\n";
        jl << "mutable struct " << key << " <: _Owner\n_id::UInt64\nfunction " << key << "(args...)\n";
        std::vector<const Function*> constructors;
        for (const auto& ctor : rec.constructors) if (!ctor.is_deleted) constructors.push_back(&ctor);
        bool constructor = false;
        if (config.constructors) {
            if (constructors.size() != 1) reject(owner, "constructor overloads require an explicit facade");
            else {
                const auto& ctor = *constructors.front();
                auto why = problem(ctor);
                if (ctor.access != "public") why = "constructor is not public";
                if (!why.empty()) reject(owner, why);
                else {
                    entry(key + ".new", body(ctor, {}, owner));
                    jl << "id = _invoke(" << jlquote(key + ".new") << ", 0, args...)\ntry\nowner = new(id)\nfinalizer(close, owner)\nreturn owner\n"
                        << "catch\n_invoke(\"__close\", id)\nrethrow()\nend\n";
                    constructor = true;
                }
            }
        }
        if (!constructor) jl << "throw(RosettaError(:conversion, \"no supported constructor exported\"))\n";
        jl << "end\nend\n";
        std::ostringstream getters, setters, names;
        getters << "name === :close && return () -> close(owner)\n";
        names << ":close,";
        std::set<std::string> members{"close", "_id"};
        counts.clear();
        for (const auto& fn : rec.methods) ++counts[fn.name];
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            auto why = problem(fn);
            if (counts[fn.name] > 1) why = "method overloads require an explicit facade";
            if (!why.empty()) { reject(owner + "::" + fn.name, why); continue; }
            if (!members.insert(fn.name).second) throw BindingError("reserved or duplicate Julia member: " + fn.name);
            const auto symbol = key + "__" + fn.name; reserve(symbol);
            const auto operation = key + "." + fn.name;
            const auto target = fn.is_static ? "::" + owner + "::" + fn.name : "rosetta_jl::object<::" + owner + ">(id)->" + fn.name;
            entry(operation, body(fn, target, {}));
            if (fn.is_static) jl << "function " << symbol << " end\n" << symbol << "(args...) = _invoke(" << jlquote(operation) << ", 0, args...)\n";
            else {
                jl << "function " << symbol << " end\n" << symbol << "(owner::" << key << ", args...) = _invoke(" << jlquote(operation) << ", getfield(owner, :_id), args...)\n";
                getters << "name === Symbol(" << jlquote(fn.name) << ") && return (args...) -> " << symbol << "(owner, args...)\n";
                names << "Symbol(" << jlquote(fn.name) << "),";
            }
        }
        for (const auto& field : rec.fields) {
            if (field.access != "public" || (config.restrict_fields && !config.fields.count(field.name))) continue;
            if (scalar(field.type).empty() || field.bitfield || field.type.is_volatile) { reject(owner + "::" + field.name, "unsupported Julia field type"); continue; }
            if (!members.insert(field.name).second) throw BindingError("reserved or duplicate Julia member: " + field.name);
            const auto get = key + ".get." + field.name, set = key + ".set." + field.name;
            entry(get, "rosetta_jl::arity(count, 0, 0); return rosetta_jl::to(rosetta_jl::object<::" + owner + ">(id)->" + field.name + ");\n");
            getters << "name === Symbol(" << jlquote(field.name) << ") && return _invoke(" << jlquote(get) << ", getfield(owner, :_id))\n";
            names << "Symbol(" << jlquote(field.name) << "),";
            setters << "if name === Symbol(" << jlquote(field.name) << ")\n";
            if (field.type.is_const) setters << "throw(RosettaError(:conversion, \"native property is readonly\"))\n";
            else {
                entry(set, "rosetta_jl::arity(count, 1, 1); auto value = rosetta_jl::from<" + scalar(field.type) + ">(args[0]);\nrosetta_jl::object<::" + owner + ">(id)->" + field.name + " = value; return {};\n");
                setters << "_invoke(" << jlquote(set) << ", getfield(owner, :_id), value)\nreturn value\n";
            }
            setters << "end\n";
        }
        jl << "function Base.getproperty(owner::" << key << ", name::Symbol)\n" << getters.str()
            << "throw(RosettaError(:conversion, \"unknown native property or method\"))\nend\n"
            << "function Base.setproperty!(owner::" << key << ", name::Symbol, value)\n" << setters.str()
            << "throw(RosettaError(:conversion, \"unknown native property\"))\nend\n"
            << "Base.propertynames(::" << key << ", private::Bool=false) = (" << names.str() << ")\n";
    }
    for (const auto& enumeration : module.enumerations)
        if (enumeration.selected) reject(enumeration.qualified_name(), "Julia enum bindings are not yet supported");
    if (!skip && !result.diagnostics.empty()) {
        std::string error = "unsupported declaration for Julia";
        for (const auto& entry : result.diagnostics) error += "\n  " + entry;
        throw BindingError(error);
    }
    out << "extern \"C\" {\nstd::uint64_t rosetta_" << name << "_abi() noexcept { return 1; }\n"
        << "void rosetta_" << name << "_free(const char* bytes) noexcept { std::free(const_cast<char*>(bytes)); }\n"
        << "void rosetta_" << name << "_shutdown() noexcept {\nstd::lock_guard<std::mutex> lock(rosetta_jl::registry().mutex);\nrosetta_jl::registry().owners.clear();\n}\n"
        << "void rosetta_" << name << "_call(const char* op, std::uint64_t id, const rosetta_jl::Value* args, std::size_t count, rosetta_jl::Result* result) noexcept {\n"
        << "rosetta_jl::guard(result, [&]() -> rosetta_jl::Value {\n(void)args; (void)count;\nconst std::string operation(op);\n"
        << "if (operation == \"__close\") { rosetta_jl::arity(count, 0, 0); rosetta_jl::registry().owners.erase(id); return {}; }\n"
        << dispatch.str() << "throw rosetta_jl::conversion_error(\"unknown native operation\");\n});\n}\n}\n";
    jl << "end # module " << name << '\n';
    result.source = out.str(); result.interface = jl.str();
    return result;
}
