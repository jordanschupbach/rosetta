GeneratedRubySource generate_ruby(const Module& module, const std::string& name, bool skip, const BindingPolicy& policy) {
    if (!identifier(name)) throw BindingError("module name must be a simple ASCII identifier starting with a letter");
    if (!policy.callbacks.empty() || !policy.enum_flags.empty())
        throw BindingError("Ruby backend does not yet support callback or enum flag policies");
    GeneratedRubySource result{{}, module.diagnostics};
    auto reject = [&](const std::string& context, const std::string& reason) { result.diagnostics.push_back(context + ": " + reason); };
    std::ostringstream out, initialization;
    out << "// Generated by Rosetta: MRI Ruby native extension.\n#include <ruby.h>\n#include <ruby/version.h>\n"
        << "#if RUBY_API_VERSION_CODE < 30100\n#error Rosetta requires Ruby 3.1 or newer\n#endif\n"
        << "#include <climits>\n#include <cmath>\n#include <cstdio>\n#include <limits>\n#include <memory>\n#include <new>\n"
        << "#include <stdexcept>\n#include <string>\n#include <type_traits>\n"
        << "#include " << quote(module.header) << '\n' << detail::ruby_runtime;
    std::size_t next = 0;
    std::set<std::string> exports;
    auto reserve = [&](const std::string& key) {
        if (!exports.insert(key).second) throw BindingError("Ruby export name collision: " + key);
    };
    auto body = [&](const Function& fn, const std::string& target, const std::string& owner) {
        std::ostringstream code;
        code << "switch (rosetta_rb::arity(argc, " << fn.parameters.size() - fn.default_arguments << ", " << fn.parameters.size() << ")) {\n";
        for (std::size_t count = fn.parameters.size() - fn.default_arguments; count <= fn.parameters.size(); ++count) {
            code << "case " << count << ": {\n";
            std::string actuals;
            for (std::size_t i = 0; i < count; ++i) {
                code << "auto value" << i << " = rosetta_rb::from<" << scalar(fn.parameters[i]) << ">(argv[" << i << "]);\n";
                if (i) actuals += ", ";
                actuals += "value" + std::to_string(i);
            }
            // Conversion can allocate in Ruby. Resolve the owner only afterwards.
            if (!owner.empty() && !fn.is_constructor && !fn.is_static) {
                if (!fn.is_const) code << "rosetta_rb::writable(self);\n";
                code << "auto* native = rosetta_rb::object<::" << owner << ">(self);\n";
            }
            if (fn.is_constructor)
                code << "wrapper->ptr = new ::" << owner << '(' << actuals << ");\nwrapper->initialized = true;\nreturn Qnil;\n";
            else if (fn.result.canonical == "void") code << target << '(' << actuals << ");\nreturn Qnil;\n";
            else code << "auto result = " << target << '(' << actuals << ");\nreturn rosetta_rb::to(result);\n";
            code << "}\n";
        }
        code << "}\nrosetta_rb::fail(rb_eRuntimeError, \"invalid argument dispatch\");\n";
        return code.str();
    };
    auto emit_function = [&](const Function& fn, const std::string& owner) {
        const auto symbol = "rosetta_wrap_" + std::to_string(next++);
        out << "static VALUE " << symbol << "(int argc, VALUE* argv, VALUE self) {\n"
            << "return rosetta_rb::guard([&]() -> VALUE {\n(void)argv; (void)self;\n";
        const auto target = !owner.empty() && !fn.is_static ? "native->" + fn.name :
            "::" + (owner.empty() ? fn.qualified_name() : owner + "::" + fn.name);
        out << body(fn, target, owner) << "});\n}\n";
        return symbol;
    };
    std::map<std::string, std::size_t> counts;
    for (const auto& fn : module.functions) ++counts[fn.qualified_name()];
    for (const auto& fn : module.functions) {
        auto why = problem(fn);
        if (counts[fn.qualified_name()] > 1) why = "overloads require an explicit facade";
        if (!why.empty()) { reject(fn.qualified_name(), why); continue; }
        const auto key = exported(fn.qualified_name()); reserve("method:" + key);
        initialization << "rb_define_singleton_method(module, " << quote(key) << ", RUBY_METHOD_FUNC(" << emit_function(fn, {}) << "), -1);\n";
    }
    for (const auto& selection : policy.classes)
        if (std::none_of(module.records.begin(), module.records.end(), [&](const Record& r) { return r.qualified_name() == selection.first; }))
            throw BindingError("unknown class in Ruby policy: " + selection.first);
    for (const auto& rec : module.records) {
        const auto owner = rec.qualified_name();
        const auto selected = policy.classes.find(owner);
        if (selected == policy.classes.end()) {
            if (!policy.explicit_class_selection && policy.classes.empty()) reject(owner, "class requires an owned class policy");
            continue;
        }
        const auto& config = selected->second;
        for (const auto& requested : config.methods) {
            const auto found = std::find_if(rec.methods.begin(), rec.methods.end(), [&](const Function& f) { return f.name == requested; });
            if (found == rec.methods.end()) throw BindingError("unknown Ruby policy method: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Ruby policy method is not public: " + owner + "::" + requested);
        }
        for (const auto& requested : config.fields) {
            const auto found = std::find_if(rec.fields.begin(), rec.fields.end(), [&](const Field& f) { return f.name == requested; });
            if (found == rec.fields.end()) throw BindingError("unknown Ruby policy field: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Ruby policy field is not public: " + owner + "::" + requested);
        }
        if (!rec.complete || rec.abstract || rec.has_bases || !rec.public_destructor || !rec.unsupported_reason.empty()) {
            reject(owner, "Ruby requires a complete, concrete class without bases and a public nonthrowing destructor"); continue;
        }
        if (!config.borrow_self.empty()) { reject(owner, "borrowed Ruby results are not yet supported"); continue; }
        const auto key = constant(exported(owner));
        if (!identifier(key)) { reject(owner, "class name cannot form an ASCII Ruby constant"); continue; }
        reserve("constant:" + key);
        const auto prefix = "rosetta_class_" + std::to_string(next++);
        out << "static VALUE " << prefix << "_init(int argc, VALUE* argv, VALUE self) {\n"
            << "return rosetta_rb::guard([&]() -> VALUE {\n(void)argc; (void)argv;\n"
            << "rosetta_rb::writable(self);\nauto* wrapper = rosetta_rb::wrapper<::" << owner << ">(self);\n"
            << "if (wrapper->initialized) rosetta_rb::fail(rb_eRuntimeError, \"native object already initialized\");\n";
        std::vector<const Function*> constructors;
        for (const auto& ctor : rec.constructors) if (!ctor.is_deleted) constructors.push_back(&ctor);
        bool constructor = false;
        if (config.constructors) {
            if (constructors.size() != 1) reject(owner, "constructor overloads require an explicit facade");
            else {
                const auto& ctor = *constructors.front();
                auto why = problem(ctor);
                if (ctor.access != "public") why = "constructor is not public";
                if (!why.empty()) reject(owner, why);
                else { out << body(ctor, {}, owner); constructor = true; }
            }
        }
        if (!constructor) out << "rosetta_rb::fail(rb_eTypeError, \"no supported constructor exported\");\n";
        out << "});\n}\n";
        initialization << "{ VALUE klass = rb_define_class_under(module, " << quote(key) << ", rb_cObject);\n"
            << "rb_define_alloc_func(klass, &rosetta_rb::allocate<::" << owner << ">);\n"
            << "rb_define_private_method(klass, \"initialize\", RUBY_METHOD_FUNC(" << prefix << "_init), -1);\n"
            << "rb_define_method(klass, \"close\", RUBY_METHOD_FUNC(rosetta_rb::close_method<::" << owner << ">), 0);\n"
            << "rb_define_singleton_method(klass, \"open\", RUBY_METHOD_FUNC(rosetta_rb::open<::" << owner << ">), -1);\n"
            << "rb_define_private_method(klass, \"initialize_copy\", RUBY_METHOD_FUNC(rosetta_rb::uncopyable), 1);\n"
            << "rb_define_method(klass, \"marshal_dump\", RUBY_METHOD_FUNC(rosetta_rb::unmarshalable), 0);\n"
            << "rb_define_singleton_method(klass, \"inherited\", RUBY_METHOD_FUNC(rosetta_rb::uncopyable), 1);\n";
        const std::set<std::string> reserved = {"close", "open", "initialize", "initialize_copy", "initialize_clone", "initialize_dup",
            "allocate", "new", "inherited", "marshal_dump", "marshal_load", "_dump", "_load", "freeze", "frozen?"};
        std::set<std::string> members;
        counts.clear();
        for (const auto& fn : rec.methods) ++counts[fn.name];
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            auto why = problem(fn);
            if (counts[fn.name] > 1) why = "method overloads require an explicit facade";
            if (!why.empty()) { reject(owner + "::" + fn.name, why); continue; }
            if (reserved.count(fn.name) || !members.insert(fn.name).second) throw BindingError("reserved or duplicate Ruby member: " + fn.name);
            initialization << (fn.is_static ? "rb_define_singleton_method" : "rb_define_method") << "(klass, " << quote(fn.name)
                << ", RUBY_METHOD_FUNC(" << emit_function(fn, owner) << "), -1);\n";
        }
        for (const auto& field : rec.fields) {
            if (field.access != "public" || (config.restrict_fields && !config.fields.count(field.name))) continue;
            const auto type = scalar(field.type);
            if (type.empty() || field.bitfield || field.type.is_volatile) { reject(owner + "::" + field.name, "unsupported Ruby field type"); continue; }
            if (reserved.count(field.name) || !members.insert(field.name).second) throw BindingError("reserved or duplicate Ruby member: " + field.name);
            const auto symbol = "rosetta_field_" + std::to_string(next++);
            out << "static VALUE " << symbol << "_get(VALUE self) { return rosetta_rb::guard([&]() -> VALUE {\n"
                << "auto result = rosetta_rb::object<::" << owner << ">(self)->" << field.name << ";\nreturn rosetta_rb::to(result);\n}); }\n";
            initialization << "rb_define_method(klass, " << quote(field.name) << ", RUBY_METHOD_FUNC(" << symbol << "_get), 0);\n";
            if (!field.type.is_const) {
                out << "static VALUE " << symbol << "_set(VALUE self, VALUE value) { return rosetta_rb::guard([&]() -> VALUE {\n"
                    << "auto converted = rosetta_rb::from<" << type << ">(value);\nrosetta_rb::writable(self);\n"
                    << "rosetta_rb::object<::" << owner << ">(self)->" << field.name << " = converted;\nreturn value;\n}); }\n";
                initialization << "rb_define_method(klass, " << quote(field.name + "=") << ", RUBY_METHOD_FUNC(" << symbol << "_set), 1);\n";
            }
        }
        initialization << "}\n";
    }
    for (const auto& enumeration : module.enumerations)
        if (enumeration.selected) reject(enumeration.qualified_name(), "Ruby enum bindings are not yet supported");
    if (!skip && !result.diagnostics.empty()) {
        std::string error = "unsupported declaration for Ruby";
        for (const auto& entry : result.diagnostics) error += "\n  " + entry;
        throw BindingError(error);
    }
    // Registration uses only trivial C stack values; Ruby may raise directly.
    out << "extern \"C\" {\nRUBY_FUNC_EXPORTED void Init_" << name << "(void) {\n"
        << "if (rb_const_defined_at(rb_cObject, rb_intern(" << quote(module_constant(name)) << ")))\n"
        << "rb_raise(rb_eNameError, \"Rosetta module constant already exists\");\n"
        << "VALUE module = rb_define_module(" << quote(module_constant(name)) << ");\n(void)module;\n"
        << initialization.str() << "}\n}\n";
    result.source = out.str();
    return result;
}
