GeneratedTclSource generate_tcl(const Module& module, const std::string& name, bool skip, const BindingPolicy& policy) {
    if (!identifier(name)) throw BindingError("module name must be a simple ASCII identifier starting with a letter");
    if (name == "tcl" || name == "oo" || name == "tcl_platform")
        throw BindingError("module name is a reserved Tcl namespace");
    if (!policy.callbacks.empty() || !policy.enum_flags.empty())
        throw BindingError("Tcl backend does not yet support callback or enum flag policies");
    GeneratedTclSource result{{}, module.diagnostics};
    auto reject = [&](const std::string& context, const std::string& reason) { result.diagnostics.push_back(context + ": " + reason); };
    const auto ns = "::" + name + "::";
    std::ostringstream out, initialization;
    out << "// Generated by Rosetta: Tcl extension.\n#include <tcl.h>\n"
        << "#if TCL_MAJOR_VERSION < 9\n#error Rosetta requires Tcl 9.0 or newer\n#endif\n"
        << "#include <atomic>\n#include <cmath>\n#include <limits>\n#include <memory>\n#include <new>\n#include <optional>\n"
        << "#include <stdexcept>\n#include <string>\n#include <type_traits>\n#include <utility>\n"
        << "#include " << quote(module.header) << '\n' << detail::tcl_runtime;
    std::size_t next = 0;
    std::set<std::string> exports;
    auto reserve = [&](const std::string& key) {
        if (!exports.insert(key).second) throw BindingError("Tcl export name collision: " + key);
    };
    // Arguments start at objv[skip]; returns the call's Tcl_Obj (nullptr for void).
    auto body = [&](const Function& fn, const std::string& target, const std::string& owner, int skip) {
        std::ostringstream code;
        code << "switch (rosetta_tcl::arity(interp, objc, objv, " << skip << ", " << fn.parameters.size() - fn.default_arguments
             << ", " << fn.parameters.size() << ", " << quote(usage(fn)) << ")) {\n";
        for (std::size_t count = fn.parameters.size() - fn.default_arguments; count <= fn.parameters.size(); ++count) {
            code << "case " << count << ": {\n";
            std::string actuals;
            for (std::size_t i = 0; i < count; ++i) {
                code << "auto value" << i << " = rosetta_tcl::from<" << scalar(fn.parameters[i]) << ">(interp, objv[" << skip + static_cast<int>(i) << "]);\n";
                if (i) actuals += ", ";
                actuals += "value" + std::to_string(i);
            }
            if (fn.is_constructor)
                code << "return rosetta_tcl::adopt(interp, " << quote(ns + exported(owner)) << ", std::make_unique<::" << owner << ">("
                     << actuals << "), &" << owner_proc_placeholder << ");\n";
            else if (fn.result.canonical == "void") code << target << '(' << actuals << ");\nreturn nullptr;\n";
            else code << "auto result = " << target << '(' << actuals << ");\nreturn rosetta_tcl::to(result);\n";
            code << "}\n";
        }
        code << "}\nrosetta_tcl::fail(\"native\", \"invalid argument dispatch\");\n";
        return code.str();
    };
    std::map<std::string, std::size_t> counts;
    for (const auto& fn : module.functions) ++counts[fn.qualified_name()];
    for (const auto& fn : module.functions) {
        auto why = problem(fn);
        if (counts[fn.qualified_name()] > 1) why = "overloads require an explicit facade";
        if (!why.empty()) { reject(fn.qualified_name(), why); continue; }
        const auto key = exported(fn.qualified_name()); reserve(key);
        const auto symbol = "rosetta_command_" + std::to_string(next++);
        out << "static int " << symbol << "(void*, Tcl_Interp* interp, int objc, Tcl_Obj* const objv[]) {\n"
            << "return rosetta_tcl::guard(interp, [&]() -> Tcl_Obj* {\n" << body(fn, "::" + fn.qualified_name(), {}, 1) << "});\n}\n";
        initialization << "if (!Tcl_CreateObjCommand(interp, " << quote(ns + key) << ", " << symbol << ", nullptr, nullptr)) return TCL_ERROR;\n"
            << "if (Tcl_Export(interp, space, " << quote(key) << ", 0) != TCL_OK) return TCL_ERROR;\n";
    }
    for (const auto& selection : policy.classes)
        if (std::none_of(module.records.begin(), module.records.end(), [&](const Record& r) { return r.qualified_name() == selection.first; }))
            throw BindingError("unknown class in Tcl policy: " + selection.first);
    for (const auto& rec : module.records) {
        const auto owner = rec.qualified_name();
        const auto selected = policy.classes.find(owner);
        if (selected == policy.classes.end()) {
            if (!policy.explicit_class_selection && policy.classes.empty()) reject(owner, "class requires an owned class policy");
            continue;
        }
        const auto& config = selected->second;
        for (const auto& requested : config.methods) {
            const auto found = std::find_if(rec.methods.begin(), rec.methods.end(), [&](const Function& f) { return f.name == requested; });
            if (found == rec.methods.end()) throw BindingError("unknown Tcl policy method: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Tcl policy method is not public: " + owner + "::" + requested);
        }
        for (const auto& requested : config.fields) {
            const auto found = std::find_if(rec.fields.begin(), rec.fields.end(), [&](const Field& f) { return f.name == requested; });
            if (found == rec.fields.end()) throw BindingError("unknown Tcl policy field: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("Tcl policy field is not public: " + owner + "::" + requested);
        }
        if (!rec.complete || rec.abstract || rec.has_bases || !rec.public_destructor || !rec.unsupported_reason.empty()) {
            reject(owner, "Tcl requires a complete, concrete class without bases and a public nonthrowing destructor"); continue;
        }
        if (!config.borrow_self.empty()) { reject(owner, "borrowed Tcl results are not yet supported"); continue; }
        const auto key = exported(owner); reserve(key);
        const auto prefix = "rosetta_class_" + std::to_string(next++);
        out << "static_assert(std::is_nothrow_destructible_v<::" << owner << ">, \"native owners require nonthrowing destruction\");\n"
            << "static int " << prefix << "_object(void*, Tcl_Interp*, int, Tcl_Obj* const[]);\n";
        // Class command: `new` and static methods.
        std::vector<std::string> class_names{"new"};
        std::ostringstream class_cases;
        std::vector<const Function*> constructors;
        for (const auto& ctor : rec.constructors) if (!ctor.is_deleted) constructors.push_back(&ctor);
        bool constructor = false;
        if (config.constructors) {
            if (constructors.size() != 1) reject(owner, "constructor overloads require an explicit facade");
            else {
                const auto& ctor = *constructors.front();
                auto why = problem(ctor);
                if (ctor.access != "public") why = "constructor is not public";
                if (!why.empty()) reject(owner, why);
                else {
                    auto code = body(ctor, {}, owner, 2);
                    for (std::size_t i = 0; (i = code.find(owner_proc_placeholder, i)) != std::string::npos;)
                        code.replace(i, std::string(owner_proc_placeholder).size(), prefix + "_object");
                    class_cases << "case 0: {\n" << code << "}\n";
                    constructor = true;
                }
            }
        }
        if (!constructor) class_cases << "case 0: rosetta_tcl::fail(\"conversion\", \"no supported constructor exported\");\n";
        // Object command: methods, then cget/configure/close.
        static const std::set<std::string> reserved = {"cget", "configure", "close"};
        std::vector<std::string> object_names;
        std::ostringstream object_cases;
        std::set<std::string> members;
        counts.clear();
        for (const auto& fn : rec.methods) ++counts[fn.name];
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            auto why = problem(fn);
            if (counts[fn.name] > 1) why = "method overloads require an explicit facade";
            if (!why.empty()) { reject(owner + "::" + fn.name, why); continue; }
            if (fn.is_static) {
                if (fn.name == "new" || !members.insert("static:" + fn.name).second)
                    throw BindingError("reserved or duplicate Tcl class subcommand: " + fn.name);
                class_cases << "case " << class_names.size() << ": {\n" << body(fn, "::" + owner + "::" + fn.name, {}, 2) << "}\n";
                class_names.push_back(fn.name);
            } else {
                if (reserved.count(fn.name) || !members.insert(fn.name).second)
                    throw BindingError("reserved or duplicate Tcl object subcommand: " + fn.name);
                object_cases << "case " << object_names.size() << ": {\n" << body(fn, "self->" + fn.name, {}, 2) << "}\n";
                object_names.push_back(fn.name);
            }
        }
        struct Option { std::string name, type; bool readonly; };
        std::vector<Option> options;
        for (const auto& field : rec.fields) {
            if (field.access != "public" || (config.restrict_fields && !config.fields.count(field.name))) continue;
            const auto type = scalar(field.type);
            if (type.empty() || field.bitfield || field.type.is_volatile) { reject(owner + "::" + field.name, "unsupported Tcl field type"); continue; }
            options.push_back({field.name, type, field.type.is_const});
        }
        std::vector<std::string> option_names;
        for (const auto& option : options) option_names.push_back("-" + option.name);
        const auto base = object_names.size();
        object_names.insert(object_names.end(), {"cget", "configure", "close"});
        if (!options.empty()) out << "static const char* const " << prefix << "_options[] = " << table(option_names) << ";\n";
        // cget -option
        object_cases << "case " << base << ": {\nrosetta_tcl::arity(interp, objc, objv, 2, 1, 1, \"option\");\n";
        if (options.empty()) object_cases << "rosetta_tcl::fail(\"conversion\", \"no native options exported\");\n";
        else {
            object_cases << "switch (rosetta_tcl::choose(interp, objv[2], " << prefix << "_options, \"option\")) {\n";
            for (std::size_t i = 0; i < options.size(); ++i)
                object_cases << "case " << i << ": return rosetta_tcl::to(self->" << options[i].name << ");\n";
            object_cases << "}\nrosetta_tcl::fail(\"native\", \"invalid option dispatch\");\n";
        }
        object_cases << "}\n";
        // configure: all options as a dict, or set -option value pairs. Every
        // value converts before any is assigned.
        object_cases << "case " << base + 1 << ": {\nif (objc == 2) {\nTcl_Obj* all = Tcl_NewDictObj();\n";
        for (std::size_t i = 0; i < options.size(); ++i)
            object_cases << "Tcl_DictObjPut(nullptr, all, Tcl_NewStringObj(" << quote(option_names[i]) << ", -1), rosetta_tcl::to(self->"
                         << options[i].name << "));\n";
        object_cases << "return all;\n}\nif (objc % 2 != 0) { Tcl_WrongNumArgs(interp, 2, objv, \"?-option value ...?\"); throw rosetta_tcl::reported{}; }\n";
        if (options.empty()) object_cases << "rosetta_tcl::fail(\"conversion\", \"no native options exported\");\n";
        else {
            for (std::size_t i = 0; i < options.size(); ++i)
                if (!options[i].readonly) object_cases << "std::optional<" << options[i].type << "> pending" << i << ";\n";
            object_cases << "for (int i = 2; i < objc; i += 2) {\nswitch (rosetta_tcl::choose(interp, objv[i], " << prefix << "_options, \"option\")) {\n";
            for (std::size_t i = 0; i < options.size(); ++i) {
                object_cases << "case " << i << ": ";
                if (options[i].readonly) object_cases << "rosetta_tcl::fail(\"conversion\", " << quote("option " + option_names[i] + " is readonly") << ");\n";
                else object_cases << "pending" << i << " = rosetta_tcl::from<" << options[i].type << ">(interp, objv[i + 1]); break;\n";
            }
            object_cases << "}\n}\n";
            for (std::size_t i = 0; i < options.size(); ++i)
                if (!options[i].readonly) object_cases << "if (pending" << i << ") self->" << options[i].name << " = *pending" << i << ";\n";
            object_cases << "return nullptr;\n";
        }
        object_cases << "}\n";
        object_cases << "case " << base + 2 << ": {\nrosetta_tcl::arity(interp, objc, objv, 2, 0, 0, \"\");\nrosetta_tcl::close(interp, objv[0]);\nreturn nullptr;\n}\n";
        out << "static int " << prefix << "_object(void* data, Tcl_Interp* interp, int objc, Tcl_Obj* const objv[]) {\n"
            << "return rosetta_tcl::guard(interp, [&]() -> Tcl_Obj* {\nauto* self = static_cast<::" << owner << "*>(data);\n(void)self;\n"
            << "if (objc < 2) { Tcl_WrongNumArgs(interp, 1, objv, \"method ?arg ...?\"); throw rosetta_tcl::reported{}; }\n"
            << "static const char* const names[] = " << table(object_names) << ";\n"
            << "switch (rosetta_tcl::choose(interp, objv[1], names, \"method\")) {\n" << object_cases.str()
            << "}\nrosetta_tcl::fail(\"native\", \"invalid method dispatch\");\n});\n}\n"
            << "static int " << prefix << "_class(void*, Tcl_Interp* interp, int objc, Tcl_Obj* const objv[]) {\n"
            << "return rosetta_tcl::guard(interp, [&]() -> Tcl_Obj* {\n"
            << "if (objc < 2) { Tcl_WrongNumArgs(interp, 1, objv, \"subcommand ?arg ...?\"); throw rosetta_tcl::reported{}; }\n"
            << "static const char* const names[] = " << table(class_names) << ";\n"
            << "switch (rosetta_tcl::choose(interp, objv[1], names, \"subcommand\")) {\n" << class_cases.str()
            << "}\nrosetta_tcl::fail(\"native\", \"invalid subcommand dispatch\");\n});\n}\n";
        initialization << "if (!Tcl_CreateObjCommand(interp, " << quote(ns + key) << ", " << prefix << "_class, nullptr, nullptr)) return TCL_ERROR;\n"
            << "if (Tcl_Export(interp, space, " << quote(key) << ", 0) != TCL_OK) return TCL_ERROR;\n";
    }
    for (const auto& enumeration : module.enumerations)
        if (enumeration.selected) reject(enumeration.qualified_name(), "Tcl enum bindings are not yet supported");
    if (!skip && !result.diagnostics.empty()) {
        std::string error = "unsupported declaration for Tcl";
        for (const auto& entry : result.diagnostics) error += "\n  " + entry;
        throw BindingError(error);
    }
    out << "extern \"C\" {\nDLLEXPORT int " << init_prefix(name) << "_Init(Tcl_Interp* interp) {\n"
        << "if (!Tcl_InitStubs(interp, \"9.0\", 0)) return TCL_ERROR;\n"
        << "if (Tcl_FindNamespace(interp, " << quote("::" + name) << ", nullptr, 0)) {\n"
        << "Tcl_SetObjResult(interp, Tcl_NewStringObj(" << quote("namespace ::" + name + " already exists") << ", -1));\nreturn TCL_ERROR;\n}\n"
        << "Tcl_Namespace* space = Tcl_CreateNamespace(interp, " << quote("::" + name) << ", nullptr, nullptr);\n"
        << "if (!space) return TCL_ERROR;\n(void)space;\n"
        << initialization.str()
        << "return Tcl_PkgProvideEx(interp, " << quote(name) << ", \"1.0\", nullptr);\n}\n}\n";
    result.source = out.str();
    return result;
}
