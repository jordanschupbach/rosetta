GeneratedCSharpSource generate_csharp(const Module& module, const std::string& name, bool skip, const BindingPolicy& policy, const std::string& managed_namespace) {
    if (!identifier(name)) throw BindingError("module name must be a simple ASCII identifier starting with a letter");
    if (!managed_namespace.empty()) {
        std::istringstream parts(managed_namespace); std::string part;
        if (managed_namespace.back() == '.') throw BindingError("invalid C# namespace");
        while (std::getline(parts, part, '.')) if (!identifier(part)) throw BindingError("invalid C# namespace");
    }
    if (!policy.callbacks.empty() || !policy.enum_flags.empty()) throw BindingError("C# backend does not yet support callback or enum flag policies");
    GeneratedCSharpSource result{{}, {}, module.diagnostics};
    auto reject = [&](const std::string& context, const std::string& reason) { result.diagnostics.push_back(context + ": " + reason); };
    std::ostringstream out, dispatch, cs;
    out << "// Generated by Rosetta: private C ABI for C# P/Invoke.\n"
        << "#include <cmath>\n#include <cstdint>\n#include <cstdlib>\n#include <cstring>\n#include <limits>\n#include <memory>\n#include <mutex>\n"
        << "#include <new>\n#include <stdexcept>\n#include <string>\n#include <type_traits>\n#include <unordered_map>\n"
        << "#include " << quote(module.header) << '\n' << detail::cabi_runtime;
    cs << "// Generated by Rosetta. Native std::string values are byte arrays.\n#nullable enable\n";
    if (!managed_namespace.empty()) {
        cs << "namespace ";
        std::istringstream parts(managed_namespace); std::string part; bool first = true;
        while (std::getline(parts, part, '.')) { if (!first) cs << '.'; cs << '@' << part; first = false; }
        cs << " {\n";
    }
    cs << "public static class @" << name << " {\n";
    std::string runtime = detail::csharp_runtime;
    for (std::size_t pos = 0; (pos = runtime.find("MODULE", pos)) != std::string::npos; pos += name.size()) runtime.replace(pos, 6, name);
    cs << runtime;
    std::set<std::string> exports{name};
    auto reserve = [&](const std::string& key) {
        if (!identifier(key) || key.rfind("_Rosetta", 0) == 0) throw BindingError("invalid or reserved C# export: " + key);
        if (!exports.insert(key).second) throw BindingError("C# export name collision: " + key);
    };
    // Dependency enums are exported only when a selected signature needs them.
    std::set<std::string> needed, enums;
    std::map<std::string, std::string> enum_storage, enum_helpers;
    auto need = [&](const Type& type) { if (!enum_name(type).empty()) needed.insert(enum_name(type)); };
    for (const auto& fn : module.functions) { need(fn.result); for (const auto& p : fn.parameters) need(p); }
    for (const auto& rec : module.records) {
        const auto selected = policy.classes.find(rec.qualified_name());
        if (selected == policy.classes.end()) continue;
        const auto& config = selected->second;
        if (config.constructors) for (const auto& ctor : rec.constructors) for (const auto& p : ctor.parameters) need(p);
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            need(fn.result); for (const auto& p : fn.parameters) need(p);
        }
        for (const auto& f : rec.fields)
            if (f.access == "public" && (!config.restrict_fields || config.fields.count(f.name))) need(f.type);
    }
    for (const auto& e : module.enumerations) {
        const auto native = e.qualified_name();
        if (!e.selected && !needed.count(native)) continue;
        if (e.enumerators.empty() || e.enumerator_values.size() != e.enumerators.size()) {
            reject(native, "C# enum bindings require named values from a definition"); continue;
        }
        bool negative = false, wide = false, valid = true;
        auto exceeds = [](const std::string& value, const std::string& limit) {
            return value.size() > limit.size() || (value.size() == limit.size() && value > limit);
        };
        for (const auto& value : e.enumerator_values) {
            if (value.empty()) { valid = false; continue; }
            if (value.front() == '-') {
                negative = true;
                if (exceeds(value.substr(1), "9223372036854775808")) valid = false;
            } else {
                wide = wide || exceeds(value, "9223372036854775807");
                if (exceeds(value, "18446744073709551615")) valid = false;
            }
        }
        if (!valid || (negative && wide) || e.underlying_type.find("__int128") != std::string::npos) {
            reject(native, "C# enum values require a 64-bit integer representation"); continue;
        }
        const auto key = exported(native); reserve(key);
        const std::string storage = wide ? "ulong" : "long";
        const auto helper = "rosetta_csharp_enum_" + std::to_string(enums.size());
        enums.insert(native); enum_storage[native] = storage; enum_helpers[native] = helper;
        cs << "public enum @" << key << " : " << storage << " {\n";
        for (std::size_t i = 0; i < e.enumerators.size(); ++i) {
            const auto& member = e.enumerators[i];
            if (!identifier(member) || member == "value__" || member == key)
                throw BindingError("invalid or reserved C# enum member: " + member);
            cs << '@' << member << " = " << e.enumerator_values[i] << (wide ? "UL" : "L") << ",\n";
        }
        cs << "}\n";
        out << "[[maybe_unused]] static ::" << native << ' ' << helper << "_from(const rosetta_abi::Value& arg) {\n"
            << "using Underlying = std::underlying_type_t<::" << native << ">;\n"
            << "using Integer = std::conditional_t<std::is_same_v<Underlying, bool>, unsigned char, Underlying>;\n"
            << "auto value = rosetta_abi::from<Integer>(arg);\nif (";
        for (std::size_t i = 0; i < e.enumerators.size(); ++i) {
            if (i) out << " && ";
            out << "value != static_cast<Integer>(::" << native << "::" << e.enumerators[i] << ')';
        }
        out << ") throw rosetta_abi::conversion_error(\"unknown enum value\");\nreturn static_cast<::" << native << ">(value);\n}\n"
            << "[[maybe_unused]] static rosetta_abi::Value " << helper << "_to(::" << native << " value) {\n"
            << "auto raw = rosetta_abi::to(static_cast<std::underlying_type_t<::" << native << ">>(value));\n";
        // bool has a distinct ABI tag; normalize it to integer transport as well.
        out << "if (raw.tag == 4) raw.tag = 2;\n(void)" << helper << "_from(raw);\n"
            << "return rosetta_abi::to(static_cast<std::" << (wide ? "uint64_t" : "int64_t") << ">(value));\n}\n";
    }
    auto native_type = [&](const Type& type) { return enums.count(enum_name(type)) ? "::" + type.canonical : scalar(type); };
    auto read = [&](const Type& type, const std::string& value) {
        return enums.count(enum_name(type)) ? enum_helpers.at(enum_name(type)) + "_from(" + value + ")" :
            "rosetta_abi::from<" + native_type(type) + ">(" + value + ")";
    };
    auto write = [&](const Type& type, const std::string& value) {
        return enums.count(enum_name(type)) ? enum_helpers.at(enum_name(type)) + "_to(" + value + ")" : "rosetta_abi::to(" + value + ")";
    };
    auto managed_type = [&](const Type& type) -> std::string {
        if (enums.count(enum_name(type))) return "@" + exported(enum_name(type));
        const auto t = scalar(type);
        if (type.canonical == "void") return "void";
        if (t == "std::string") return "byte[]";
        if (t == "bool" || t == "float" || t == "double") return t;
        return t.rfind("unsigned", 0) == 0 ? "ulong" : "long";
    };
    auto result_cast = [&](const Type& type) {
        return "(" + managed_type(type) + ")" + (enums.count(enum_name(type)) ? "(" + enum_storage.at(enum_name(type)) + ")" : "");
    };
    auto argument = [&](const Type& type, const std::string& value) {
        return (enums.count(enum_name(type)) ? "(" + enum_storage.at(enum_name(type)) + ")" : "") + value;
    };
    auto method = [&](const Function& fn, const std::string& operation, const std::string& owner, bool ctor = false) {
        for (std::size_t count = fn.parameters.size() - fn.default_arguments; count <= fn.parameters.size(); ++count) {
            cs << "public ";
            if (ctor) cs << '@' << owner;
            else cs << (owner.empty() || fn.is_static ? "static " : "") << managed_type(fn.result) << " @" << fn.name;
            cs << '(';
            for (std::size_t i = 0; i < count; ++i) { if (i) cs << ", "; cs << managed_type(fn.parameters[i]) << " arg" << i; }
            cs << ") {\n";
            if (ctor) cs << "_handle = new _RosettaHandle(); try { _RosettaCreate(_handle, ";
            else if (fn.result.canonical != "void") cs << "return " << result_cast(fn.result) << "_RosettaInvoke(";
            else cs << "_RosettaInvoke(";
            cs << quote(operation);
            if (!ctor) cs << ", " << (owner.empty() || fn.is_static ? "null" : "_handle");
            for (std::size_t i = 0; i < count; ++i) cs << ", " << argument(fn.parameters[i], "arg" + std::to_string(i));
            cs << ')';
            if (ctor) cs << "; } catch { _handle.Dispose(); throw; }";
            else cs << (fn.result.canonical == "void" ? ";" : "!;");
            cs << "\n}\n";
        }
    };
    auto body = [&](const Function& fn, const std::string& target, const std::string& owner) {
        std::ostringstream code;
        code << "rosetta_abi::arity(count, " << fn.parameters.size() - fn.default_arguments << ", " << fn.parameters.size() << ");\nswitch (count) {\n";
        for (std::size_t count = fn.parameters.size() - fn.default_arguments; count <= fn.parameters.size(); ++count) {
            code << "case " << count << ": {\n";
            std::string actuals;
            for (std::size_t i = 0; i < count; ++i) {
                code << "auto value" << i << " = " << read(fn.parameters[i], "args[" + std::to_string(i) + "]") << ";\n";
                if (i) actuals += ", ";
                actuals += "value" + std::to_string(i);
            }
            if (fn.is_constructor)
                code << "return rosetta_abi::to(rosetta_abi::own(std::make_unique<::" << owner << ">(" << actuals << ")));\n";
            else if (fn.result.canonical == "void") code << target << '(' << actuals << "); return {};\n";
            else code << "auto result = " << target << '(' << actuals << "); return " << write(fn.result, "result") << ";\n";
            code << "}\n";
        }
        code << "}\nthrow rosetta_abi::conversion_error(\"invalid argument dispatch\");\n";
        return code.str();
    };
    auto entry = [&](const std::string& key, const std::string& code) {
        dispatch << "if (operation == " << quote(key) << ") {\n" << code << "}\n";
    };
    std::map<std::string, std::size_t> counts;
    for (const auto& fn : module.functions) ++counts[fn.qualified_name()];
    for (const auto& fn : module.functions) {
        auto why = problem(fn, enums);
        if (counts[fn.qualified_name()] > 1) why = "overloads require an explicit facade";
        if (!why.empty()) { reject(fn.qualified_name(), why); continue; }
        const auto key = exported(fn.qualified_name()); reserve(key);
        entry(key, body(fn, "::" + fn.qualified_name(), {}));
        auto public_fn = fn; public_fn.name = key; method(public_fn, key, {});
    }
    for (const auto& selection : policy.classes)
        if (std::none_of(module.records.begin(), module.records.end(), [&](const Record& r) { return r.qualified_name() == selection.first; }))
            throw BindingError("unknown class in C# policy: " + selection.first);
    for (const auto& rec : module.records) {
        const auto owner = rec.qualified_name();
        const auto selected = policy.classes.find(owner);
        if (selected == policy.classes.end()) {
            if (!policy.explicit_class_selection && policy.classes.empty()) reject(owner, "class requires an owned class policy");
            continue;
        }
        const auto& config = selected->second;
        for (const auto& requested : config.methods) {
            const auto found = std::find_if(rec.methods.begin(), rec.methods.end(), [&](const Function& f) { return f.name == requested; });
            if (found == rec.methods.end()) throw BindingError("unknown C# policy method: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("C# policy method is not public: " + owner + "::" + requested);
        }
        for (const auto& requested : config.fields) {
            const auto found = std::find_if(rec.fields.begin(), rec.fields.end(), [&](const Field& f) { return f.name == requested; });
            if (found == rec.fields.end()) throw BindingError("unknown C# policy field: " + owner + "::" + requested);
            if (found->access != "public") throw BindingError("C# policy field is not public: " + owner + "::" + requested);
        }
        if (!rec.complete || rec.abstract || rec.has_bases || !rec.public_destructor || !rec.unsupported_reason.empty()) {
            reject(owner, "C# requires a complete, concrete class without bases and a public nonthrowing destructor"); continue;
        }
        if (!config.borrow_self.empty()) { reject(owner, "borrowed C# results are not yet supported"); continue; }
        const auto key = exported(owner); reserve(key);
        out << "static_assert(std::is_nothrow_destructible_v<::" << owner << ">, \"native owners require nonthrowing destruction\");\n";
        cs << "public sealed class @" << key << " : global::System.IDisposable {\nprivate readonly _RosettaHandle _handle;\npublic void Dispose() { _handle.Dispose(); }\n";
        std::vector<const Function*> constructors;
        for (const auto& ctor : rec.constructors) if (!ctor.is_deleted) constructors.push_back(&ctor);
        bool constructor = false;
        if (config.constructors) {
            if (constructors.size() != 1) reject(owner, "constructor overloads require an explicit facade");
            else {
                const auto& ctor = *constructors.front();
                auto why = problem(ctor, enums);
                if (ctor.access != "public") why = "constructor is not public";
                if (!why.empty()) reject(owner, why);
                else {
                    entry(key + ".new", body(ctor, {}, owner));
                    method(ctor, key + ".new", key, true);
                    constructor = true;
                }
            }
        }
        if (!constructor) cs << "private @" << key << "() { _handle = new _RosettaHandle(); throw new global::System.InvalidOperationException(\"no supported constructor exported\"); }\n";
        std::set<std::string> members{"Dispose", "_handle", "Equals", "GetHashCode", "GetType", "ToString", "MemberwiseClone", "Finalize", "ReferenceEquals", key};
        counts.clear();
        for (const auto& fn : rec.methods) ++counts[fn.name];
        for (const auto& fn : rec.methods) {
            if (fn.access != "public" || (config.restrict_methods && !config.methods.count(fn.name))) continue;
            auto why = problem(fn, enums);
            if (counts[fn.name] > 1) why = "method overloads require an explicit facade";
            if (!why.empty()) { reject(owner + "::" + fn.name, why); continue; }
            if (fn.name.rfind("_Rosetta", 0) == 0 || !members.insert(fn.name).second) throw BindingError("reserved or duplicate C# member: " + fn.name);
            const auto symbol = key + "__" + fn.name; reserve(symbol);
            const auto operation = key + "." + fn.name;
            const auto target = fn.is_static ? "::" + owner + "::" + fn.name : "rosetta_abi::object<::" + owner + ">(id)->" + fn.name;
            entry(operation, body(fn, target, {}));
            method(fn, operation, key);
        }
        for (const auto& field : rec.fields) {
            if (field.access != "public" || (config.restrict_fields && !config.fields.count(field.name))) continue;
            if ((scalar(field.type).empty() && !enums.count(enum_name(field.type))) || field.bitfield || field.type.is_volatile) { reject(owner + "::" + field.name, "unsupported C# field type"); continue; }
            if (field.name.rfind("_Rosetta", 0) == 0 || !members.insert(field.name).second) throw BindingError("reserved or duplicate C# member: " + field.name);
            const auto get = key + ".get." + field.name, set = key + ".set." + field.name;
            entry(get, "rosetta_abi::arity(count, 0, 0); return " + write(field.type, "rosetta_abi::object<::" + owner + ">(id)->" + field.name) + ";\n");
            cs << "public " << managed_type(field.type) << " @" << field.name << " { get { return " << result_cast(field.type) << "_RosettaInvoke(" << quote(get) << ", _handle)!; }\n";
            if (!field.type.is_const) {
                entry(set, "rosetta_abi::arity(count, 1, 1); auto value = " + read(field.type, "args[0]") + ";\nrosetta_abi::object<::" + owner + ">(id)->" + field.name + " = value; return {};\n");
                cs << "set { _RosettaInvoke(" << quote(set) << ", _handle, " << argument(field.type, "value") << "); }\n";
            }
            cs << "}\n";
        }
        cs << "}\n";
    }
    if (!skip && !result.diagnostics.empty()) {
        std::string error = "unsupported declaration for C#";
        for (const auto& entry : result.diagnostics) error += "\n  " + entry;
        throw BindingError(error);
    }
    out << "extern \"C\" {\nstd::uint64_t rosetta_" << name << "_abi() noexcept { return 1; }\n"
        << "void rosetta_" << name << "_free(const char* bytes) noexcept { std::free(const_cast<char*>(bytes)); }\n"
        << "void rosetta_" << name << "_shutdown() noexcept {\nstd::lock_guard<std::mutex> lock(rosetta_abi::registry().mutex);\nrosetta_abi::registry().owners.clear();\n}\n"
        << "void rosetta_" << name << "_call(const char* op, std::uint64_t id, const rosetta_abi::Value* args, std::size_t count, rosetta_abi::Result* result) noexcept {\n"
        << "rosetta_abi::guard(result, [&]() -> rosetta_abi::Value {\n(void)args; (void)count;\nconst std::string operation(op);\n"
        << "if (operation == \"__close\") { rosetta_abi::arity(count, 0, 0); rosetta_abi::registry().owners.erase(id); return {}; }\n"
        << dispatch.str() << "throw rosetta_abi::conversion_error(\"unknown native operation\");\n});\n}\n}\n";
    out << "extern \"C\" void rosetta_" << name << "_release(std::uint64_t id) noexcept { try { std::lock_guard<std::mutex> lock(rosetta_abi::registry().mutex); rosetta_abi::registry().owners.erase(id); } catch (...) {} }\n";
    cs << "}\n";
    if (!managed_namespace.empty()) cs << "}\n";
    result.source = out.str(); result.interface = cs.str();
    return result;
}
