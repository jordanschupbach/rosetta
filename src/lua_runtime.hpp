template<class Set, bool Multiple = false> struct rosetta_set_codec {
    using Element = typename Set::value_type;
    using Box = std::tuple<Element>;
    static constexpr bool boxed = rosetta_nil_value<Element>::value;
    static Element read_element(lua_State* L, int index) {
        if constexpr (boxed) return std::get<0>(rosetta_codec<Box>::read(L, index));
        else return rosetta_codec<Element>::read(L, index);
    }
    static Set read(lua_State* L, int index) {
        const auto size = rosetta_sequence_size(L, index);
        index = lua_absindex(L, index);
        const int top = lua_gettop(L);
        Set result;
        try {
            for (size_t i = 0; i < size; ++i) {
                lua_rawgeti(L, index, static_cast<lua_Integer>(i + 1));
                auto element = read_element(L, -1);
                if constexpr (Multiple) result.emplace(std::move(element));
                else if (!result.emplace(std::move(element)).second) throw rosetta_conversion_error(index, "duplicate native set element");
                lua_pop(L, 1);
            }
        } catch (...) { lua_settop(L, top); throw; }
        return result;
    }
    static void push(lua_State* L, const Set& value) {
        static_assert(std::is_trivially_destructible_v<typename Set::const_iterator>, "set publication requires trivial native iterators");
        luaL_checkstack(L, 4, "set result nesting exceeds Lua stack capacity");
        lua_newtable(L);
        lua_Integer position = 0;
        for (const auto& element : value) {
            if (position == std::numeric_limits<lua_Integer>::max()) luaL_error(L, "set result is too large");
            if constexpr (boxed) {
                lua_newtable(L);
                rosetta_codec<Element>::push(L, element); lua_rawseti(L, -2, 1);
            } else rosetta_codec<Element>::push(L, element);
            lua_rawseti(L, -2, ++position);
        }
    }
};
template<class Key, class Compare, class Allocator>
struct rosetta_codec<std::set<Key, Compare, Allocator>> : rosetta_set_codec<std::set<Key, Compare, Allocator>> {};
template<class Key, class Compare, class Allocator>
struct rosetta_codec<std::multiset<Key, Compare, Allocator>> : rosetta_set_codec<std::multiset<Key, Compare, Allocator>, true> {};
