// Conversion failures are C++ exceptions until the wrapper's catch scope has
// exited. No Lua longjmp is allowed through a live native RAII value.
class rosetta_conversion_error : public std::exception {
    char message_[512];
public:
    explicit rosetta_conversion_error(const char* message) noexcept {
        std::snprintf(message_, sizeof(message_), "%s", message);
    }
    rosetta_conversion_error(int argument, const char* message) noexcept {
        std::snprintf(message_, sizeof(message_), "argument %d: %s", argument, message);
    }
    const char* what() const noexcept override { return message_; }
};

template<class T> static T rosetta_integer(lua_State* L, int index) {
    if (lua_type(L, index) != LUA_TNUMBER) throw rosetta_conversion_error(index, "number expected");
    int exact = 0;
    lua_Integer value = lua_tointegerx(L, index, &exact);
    if (!exact) throw rosetta_conversion_error(index, "integer expected");
    if constexpr (std::is_unsigned_v<T>) {
        if (value < 0 || static_cast<unsigned long long>(value) > std::numeric_limits<T>::max())
            throw rosetta_conversion_error(index, "integer out of C++ range");
    } else {
        if (value < std::numeric_limits<T>::min() || value > std::numeric_limits<T>::max())
            throw rosetta_conversion_error(index, "integer out of C++ range");
    }
    return static_cast<T>(value);
}
template<class T> static T rosetta_number(lua_State* L, int index) {
    if (lua_type(L, index) != LUA_TNUMBER) throw rosetta_conversion_error(index, "number expected");
    lua_Number value = lua_tonumber(L, index);
    if (!std::isfinite(value) || value < -std::numeric_limits<T>::max() || value > std::numeric_limits<T>::max())
        throw rosetta_conversion_error(index, "number out of C++ range");
    return static_cast<T>(value);
}
template<class T> static int rosetta_push_integer(lua_State* L, T value) {
    if constexpr (std::is_unsigned_v<T>) {
        if (value > static_cast<unsigned long long>(std::numeric_limits<lua_Integer>::max()))
            return luaL_error(L, "C++ result out of Lua integer range");
    } else {
        if (value < std::numeric_limits<lua_Integer>::min() || value > std::numeric_limits<lua_Integer>::max())
            return luaL_error(L, "C++ result out of Lua integer range");
    }
    lua_pushinteger(L, static_cast<lua_Integer>(value));
    return 1;
}
template<class Enum> static auto rosetta_enum_number(Enum value) {
    using Underlying = std::underlying_type_t<Enum>;
    // Enum transport is integer-valued even when the C++ underlying type is bool.
    using Number = std::conditional_t<std::is_same_v<Underlying, bool>, unsigned char, Underlying>;
    return static_cast<Number>(value);
}

