template<class T> using rosetta_value_t = std::remove_cv_t<std::remove_reference_t<T>>;
template<class T> static rosetta_value_t<T> rosetta_read(lua_State* L, int index) {
    return rosetta_codec<rosetta_value_t<T>>::read(L, index);
}

// The thunk owns no C++ objects. Lua may longjmp from any allocation within it;
// lua_pcall catches that error before it can cross the native values in publish.
template<class T> static int rosetta_publish_thunk(lua_State* L) {
    const auto* value = static_cast<const T*>(lua_touserdata(L, 1));
    rosetta_codec<T>::push(L, *value);
    return 1;
}
template<class T> static int rosetta_publish(lua_State* L, const T& value) {
    lua_pushcfunction(L, &rosetta_publish_thunk<T>); // zero upvalues: no allocation
    lua_pushlightuserdata(L, const_cast<T*>(&value));
    if (lua_pcall(L, 1, 1, 0) != LUA_OK) {
        const char* message = lua_type(L, -1) == LUA_TSTRING ? lua_tostring(L, -1) : "Lua result conversion failed";
        const rosetta_conversion_error error(message);
        lua_pop(L, 1);
        throw error;
    }
    return 1;
}

// Native objects stay on the C++ heap. The Lua userdata is a trivial header,
// initialized and given its finalizer before any native ownership is acquired.
struct rosetta_object {
    const void* tag;
    void* pointer;
    void* state;
    void (*destroy)(void*) noexcept;
    rosetta_object* parent;
    bool readonly;
    bool shared;
    size_t active_calls = 0;
};
template<class T> static char rosetta_type_key = 0;

template<class T> static rosetta_object* rosetta_test_object(lua_State* L, int index) noexcept {
    if (lua_type(L, index) != LUA_TUSERDATA || lua_rawlen(L, index) != sizeof(rosetta_object)) return nullptr;
    void* memory = lua_touserdata(L, index);
    const void* tag = nullptr;
    std::memcpy(&tag, memory, sizeof(tag));
    if (tag != &rosetta_type_key<T>) return nullptr;
    return static_cast<rosetta_object*>(memory);
}

template<class T> static rosetta_object* rosetta_get_object(lua_State* L, int index, bool mutable_access = false) {
    auto* object = rosetta_test_object<T>(L, index);
    if (!object) throw rosetta_conversion_error(index, "object of the expected class required");
    for (auto* owner = object; owner; owner = owner->parent)
        if (!owner->pointer) throw rosetta_conversion_error(index, "object is closed or owner has expired");
    if (mutable_access && object->readonly) throw rosetta_conversion_error(index, "object is readonly");
    return object;
}
template<class T> static T* rosetta_get(lua_State* L, int index, bool mutable_access = false) {
    return static_cast<T*>(rosetta_get_object<T>(L, index, mutable_access)->pointer);
}
template<class T> static T* rosetta_get_pointer(lua_State* L, int index, bool mutable_access) {
    if (lua_type(L, index) == LUA_TNIL) return nullptr;
    return rosetta_get<T>(L, index, mutable_access);
}
template<class T> static std::shared_ptr<T> rosetta_get_shared(lua_State* L, int index) {
    if (lua_type(L, index) == LUA_TNIL) return {};
    auto* object = rosetta_get_object<T>(L, index, true);
    if (!object->shared) throw rosetta_conversion_error(index, "shared ownership object required");
    return *static_cast<std::shared_ptr<T>*>(object->state);
}
template<class T> static T rosetta_copy_object(lua_State* L, int index) {
    if constexpr (std::is_copy_constructible_v<T>) return *rosetta_get<T>(L, index);
    else throw rosetta_conversion_error(index, "class is not copy constructible");
}

class rosetta_object_pin {
    rosetta_object* object_;
public:
    explicit rosetta_object_pin(rosetta_object* object) noexcept : object_(object) {
        for (auto* owner = object_; owner; owner = owner->parent) ++owner->active_calls;
    }
    ~rosetta_object_pin() {
        for (auto* owner = object_; owner; owner = owner->parent) --owner->active_calls;
    }
    rosetta_object_pin(const rosetta_object_pin&) = delete;
    rosetta_object_pin& operator=(const rosetta_object_pin&) = delete;
};

template<class T> static int rosetta_finalize_object(lua_State* L) noexcept {
    auto* object = rosetta_test_object<T>(L, 1);
    if (!object || object->active_calls) return 0; // reachable active objects cannot be collected
    void* state = object->state;
    auto destroy = object->destroy;
    object->pointer = nullptr;
    object->state = nullptr;
    object->destroy = nullptr;
    if (destroy) destroy(state);
    lua_pushnil(L);
    lua_setiuservalue(L, 1, 1);
    return 0;
}
template<class T> static int rosetta_close_object(lua_State* L) {
    auto* object = rosetta_test_object<T>(L, 1);
    if (object && object->active_calls) return luaL_error(L, "object has active native calls");
    return rosetta_finalize_object<T>(L);
}

struct rosetta_new_object_context {
    const void* tag;
    rosetta_object* parent;
    rosetta_object* result;
    bool readonly;
};
[[maybe_unused]] inline int rosetta_new_object_thunk(lua_State* L) {
    auto* context = static_cast<rosetta_new_object_context*>(lua_touserdata(L, 1));
    auto* memory = lua_newuserdatauv(L, sizeof(rosetta_object), 1);
    auto* object = ::new(memory) rosetta_object{context->tag, nullptr, nullptr, nullptr, context->parent, context->readonly, false};
    lua_rawgetp(L, LUA_REGISTRYINDEX, context->tag);
    if (lua_type(L, -1) != LUA_TTABLE) return luaL_error(L, "class metatable is not registered");
    lua_setmetatable(L, -2);
    if (context->parent) {
        lua_pushvalue(L, 2);
        lua_setiuservalue(L, -2, 1);
    }
    context->result = object;
    return 1;
}

template<class T> static rosetta_object* rosetta_new_object(lua_State* L, int parent_index = 0, bool readonly = false) {
    if (!lua_checkstack(L, 4)) throw rosetta_conversion_error("cannot reserve object publication stack");
    rosetta_object* parent = parent_index ? static_cast<rosetta_object*>(lua_touserdata(L, parent_index)) : nullptr;
    rosetta_new_object_context context{&rosetta_type_key<T>, parent, nullptr, readonly || (parent && parent->readonly)};
    lua_pushcfunction(L, rosetta_new_object_thunk);
    lua_pushlightuserdata(L, &context);
    if (parent) lua_pushvalue(L, parent_index);
    if (lua_pcall(L, parent ? 2 : 1, 1, 0) != LUA_OK) {
        const char* message = lua_type(L, -1) == LUA_TSTRING ? lua_tostring(L, -1) : "Lua object allocation failed";
        const rosetta_conversion_error error(message);
        lua_pop(L, 1);
        throw error;
    }
    return context.result;
}
template<class T> static void rosetta_delete_native(void* pointer) noexcept { delete static_cast<T*>(pointer); }
template<class T> static void rosetta_delete_shared(void* holder) noexcept { delete static_cast<std::shared_ptr<T>*>(holder); }

template<class T> static int rosetta_publish_owned(lua_State* L, T&& value) {
    using Native = rosetta_value_t<T>;
    auto* object = rosetta_new_object<Native>(L);
    if constexpr (std::is_move_constructible_v<Native> || std::is_copy_constructible_v<Native>) {
        auto* pointer = new Native(std::move_if_noexcept(value));
        object->pointer = pointer;
        object->state = pointer;
        object->destroy = &rosetta_delete_native<Native>;
        return 1;
    } else throw rosetta_conversion_error("class cannot be relocated; expose an owning pointer factory");
}
template<class T> static int rosetta_publish_unique(lua_State* L, std::unique_ptr<T>& value) {
    if (!value) { lua_pushnil(L); return 1; }
    auto* object = rosetta_new_object<T>(L);
    object->pointer = value.release();
    object->state = object->pointer;
    object->destroy = &rosetta_delete_native<T>;
    return 1;
}
template<class T> static int rosetta_publish_shared(lua_State* L, std::shared_ptr<T> value) {
    if (!value) { lua_pushnil(L); return 1; }
    auto* object = rosetta_new_object<T>(L);
    auto* holder = new std::shared_ptr<T>(std::move(value));
    object->pointer = holder->get();
    object->state = holder;
    object->destroy = &rosetta_delete_shared<T>;
    object->shared = true;
    return 1;
}
template<class T> static int rosetta_publish_borrow(lua_State* L, const T* value, int parent_index, bool readonly) {
    if (!value) { lua_pushnil(L); return 1; }
    auto* object = rosetta_new_object<T>(L, parent_index, readonly);
    object->pointer = const_cast<T*>(value);
    return 1;
}
