template<> struct rosetta_codec<const char*> {
    static const char* read(lua_State* L, int index) {
        const auto view = rosetta_codec<std::string_view>::read(L, index);
        if (std::memchr(view.data(), 0, view.size())) throw rosetta_conversion_error(index, "embedded NUL in argument");
        return view.data();
    }
    static void push(lua_State* L, const char* value) {
        if (value) lua_pushstring(L, value); else lua_pushnil(L);
    }
};

// Raw sequence reads do not allocate in Lua, invoke metamethods, or raise errors.
// Lua stack growth is checked with the non-throwing lua_checkstack API.
[[maybe_unused]] inline size_t rosetta_sequence_size(lua_State* L, int index) {
    if (lua_type(L, index) != LUA_TTABLE) throw rosetta_conversion_error(index, "table expected");
    if (!lua_checkstack(L, 3)) throw rosetta_conversion_error("Lua stack allocation failed");
    const auto size = lua_rawlen(L, index);
    if (size > static_cast<unsigned long long>(std::numeric_limits<lua_Integer>::max()))
        throw rosetta_conversion_error(index, "sequence is too large");
    index = lua_absindex(L, index);
    const int top = lua_gettop(L);
    lua_pushnil(L);
    while (lua_next(L, index) != 0) {
        int exact = 0;
        const auto key = lua_tointegerx(L, -2, &exact);
        if (lua_type(L, -2) != LUA_TNUMBER || !exact || key < 1 ||
            static_cast<unsigned long long>(key) > size) {
            lua_settop(L, top);
            throw rosetta_conversion_error(index, "dense sequence expected (keys 1..n)");
        }
        lua_pop(L, 1);
    }
    return size;
}

template<class T, class Allocator> struct rosetta_codec<std::vector<T, Allocator>> {
    static std::vector<T, Allocator> read(lua_State* L, int index) {
        const auto size = rosetta_sequence_size(L, index);
        index = lua_absindex(L, index);
        const int top = lua_gettop(L);
        std::vector<T, Allocator> value;
        value.reserve(size);
        try {
            for (size_t i = 0; i < size; ++i) {
                lua_rawgeti(L, index, static_cast<lua_Integer>(i + 1));
                value.push_back(rosetta_codec<T>::read(L, -1));
                lua_pop(L, 1);
            }
        } catch (...) { lua_settop(L, top); throw; }
        return value;
    }
    static void push(lua_State* L, const std::vector<T, Allocator>& value) {
        luaL_checkstack(L, 3, "result nesting exceeds Lua stack capacity");
        lua_newtable(L);
        for (size_t i = 0; i < value.size(); ++i) {
            rosetta_codec<T>::push(L, value[i]);
            lua_rawseti(L, -2, static_cast<lua_Integer>(i + 1));
        }
    }
};
template<class Sequence, bool Forward = false> struct rosetta_linear_codec {
    using Element = typename Sequence::value_type;
    static Element read_element(lua_State* L, int index, size_t position) {
        lua_rawgeti(L, index, static_cast<lua_Integer>(position + 1));
        auto value = rosetta_codec<Element>::read(L, -1);
        lua_pop(L, 1);
        return value;
    }
    static Sequence read(lua_State* L, int index) {
        const auto size = rosetta_sequence_size(L, index);
        index = lua_absindex(L, index);
        const int top = lua_gettop(L);
        Sequence result;
        try {
            if constexpr (Forward) {
                auto position = result.before_begin();
                for (size_t i = 0; i < size; ++i) position = result.emplace_after(position, read_element(L, index, i));
            } else {
                for (size_t i = 0; i < size; ++i) result.emplace_back(read_element(L, index, i));
            }
        } catch (...) { lua_settop(L, top); throw; }
        return result;
    }
    static void push(lua_State* L, const Sequence& value) {
        static_assert(std::is_trivially_destructible_v<typename Sequence::const_iterator>, "sequence publication requires trivial native iterators");
        luaL_checkstack(L, 3, "sequence result nesting exceeds Lua stack capacity");
        lua_newtable(L);
        lua_Integer position = 0;
        for (const auto& element : value) {
            if (position == std::numeric_limits<lua_Integer>::max()) luaL_error(L, "sequence result is too large");
            rosetta_codec<Element>::push(L, element);
            lua_rawseti(L, -2, ++position);
        }
    }
};
