class rosetta_view_scope {
    lua_State* L_;
    rosetta_view_scope* previous_;
    std::vector<int> references_;
    inline static thread_local rosetta_view_scope* current_ = nullptr;
    static int pin_thunk(lua_State* L) {
        // This protected thunk owns no C++ values across luaL_ref allocation.
        const int reference = luaL_ref(L, LUA_REGISTRYINDEX);
        lua_pushinteger(L, reference);
        return 1;
    }
public:
    explicit rosetta_view_scope(lua_State* L) : L_(L), previous_(current_) { current_ = this; }
    rosetta_view_scope(const rosetta_view_scope&) = delete;
    rosetta_view_scope& operator=(const rosetta_view_scope&) = delete;
    ~rosetta_view_scope() noexcept {
        for (const int reference : references_) luaL_unref(L_, LUA_REGISTRYINDEX, reference);
        current_ = previous_;
    }
    static void pin(lua_State* L, int index) {
        if (!current_ || current_->L_ != L) throw rosetta_conversion_error("view conversion requires its native call scope");
        index = lua_absindex(L, index);
        if (!lua_checkstack(L, 4)) throw rosetta_conversion_error("view pin stack allocation failed");
        lua_pushcfunction(L, pin_thunk);
        lua_pushvalue(L, index);
        if (lua_pcall(L, 1, 1, 0) != LUA_OK) {
            const rosetta_conversion_error error("view pin allocation failed");
            lua_pop(L, 1);
            throw error;
        }
        const int reference = static_cast<int>(lua_tointeger(L, -1));
        lua_pop(L, 1);
        try { current_->references_.push_back(reference); }
        catch (...) { luaL_unref(L, LUA_REGISTRYINDEX, reference); throw; }
    }
};
inline std::string_view rosetta_string_bytes(lua_State* L, int index) {
    if (lua_type(L, index) != LUA_TSTRING) throw rosetta_conversion_error(index, "string expected");
    size_t size = 0;
    // No allocation: strict type validation prevents number-to-string conversion.
    const char* data = lua_tolstring(L, index, &size);
    return {data, size};
}
template<> struct rosetta_codec<std::string_view> {
    static std::string_view read(lua_State* L, int index) {
        const auto value = rosetta_string_bytes(L, index);
        rosetta_view_scope::pin(L, index);
        return value;
    }
    static void push(lua_State* L, std::string_view value) {
        lua_pushlstring(L, value.data() ? value.data() : "", value.size());
    }
};
