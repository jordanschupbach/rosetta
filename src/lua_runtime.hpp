template<class Map, bool Multiple = false> struct rosetta_map_codec {
    using Key = std::remove_cv_t<typename Map::key_type>;
    using Mapped = std::remove_cv_t<typename Map::mapped_type>;
    using Entry = std::pair<Key, Mapped>;
    static constexpr bool dictionary = !Multiple && std::is_same_v<Key, std::string> && !rosetta_nil_value<Mapped>::value;
    static Map read(lua_State* L, int index) {
        if (lua_type(L, index) != LUA_TTABLE) throw rosetta_conversion_error(index, "map table expected");
        if (!lua_checkstack(L, 4)) throw rosetta_conversion_error("map stack allocation failed");
        index = lua_absindex(L, index);
        const int top = lua_gettop(L);
        Map result;
        try {
            if constexpr (dictionary) {
                lua_pushnil(L);
                while (rosetta_map_next(L, index)) {
                    if (lua_type(L, -2) != LUA_TSTRING) throw rosetta_conversion_error(index, "string map keys required");
                    auto key = rosetta_codec<Key>::read(L, -2);
                    auto mapped = rosetta_codec<Mapped>::read(L, -1);
                    if (!result.emplace(std::move(key), std::move(mapped)).second)
                        throw rosetta_conversion_error(index, "duplicate native map key");
                    lua_pop(L, 1);
                }
            } else {
                const auto size = rosetta_sequence_size(L, index);
                for (size_t i = 0; i < size; ++i) {
                    lua_rawgeti(L, index, static_cast<lua_Integer>(i + 1));
                    auto entry = rosetta_codec<Entry>::read(L, -1);
                    if constexpr (Multiple) result.emplace(std::move(entry.first), std::move(entry.second));
                    else if (!result.emplace(std::move(entry.first), std::move(entry.second)).second)
                            throw rosetta_conversion_error(index, "duplicate native map key");
                    lua_pop(L, 1);
                }
            }
        } catch (...) { lua_settop(L, top); throw; }
        return result;
    }
    static void push(lua_State* L, const Map& value) {
        static_assert(std::is_trivially_destructible_v<typename Map::const_iterator>, "map publication requires trivial native iterators");
        luaL_checkstack(L, 4, "map result nesting exceeds Lua stack capacity");
        lua_newtable(L);
        lua_Integer position = 0;
        for (const auto& entry : value) {
            if constexpr (dictionary) {
                rosetta_codec<Key>::push(L, entry.first);
                rosetta_codec<Mapped>::push(L, entry.second);
                lua_rawset(L, -3);
            } else {
                if (position == std::numeric_limits<lua_Integer>::max()) luaL_error(L, "map result is too large");
                lua_newtable(L);
                rosetta_codec<Key>::push(L, entry.first); lua_rawseti(L, -2, 1);
                rosetta_codec<Mapped>::push(L, entry.second); lua_rawseti(L, -2, 2);
                lua_rawseti(L, -2, ++position);
            }
        }
    }
};
