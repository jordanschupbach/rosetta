// Fixed product slots are defined by the native type, not Lua's length operator.
// Optional slots may be absent; all stored keys must be within 1..arity.
[[maybe_unused]] inline void rosetta_product_table(lua_State* L, int index, size_t arity) {
    if (lua_type(L, index) != LUA_TTABLE) throw rosetta_conversion_error(index, "product table expected");
    if (!lua_checkstack(L, 3)) throw rosetta_conversion_error("Lua stack allocation failed");
    index = lua_absindex(L, index);
    const int top = lua_gettop(L);
    lua_pushnil(L);
    while (lua_next(L, index) != 0) {
        int exact = 0;
        const auto key = lua_tointegerx(L, -2, &exact);
        if (lua_type(L, -2) != LUA_TNUMBER || !exact || key < 1 || static_cast<unsigned long long>(key) > arity) {
            lua_settop(L, top);
            throw rosetta_conversion_error(index, "product keys must be within 1..arity");
        }
        lua_pop(L, 1);
    }
}
template<class Product> struct rosetta_product_codec {
    template<size_t I> using Element = std::remove_cv_t<std::tuple_element_t<I, Product>>;
    template<size_t I> static Element<I> read_element(lua_State* L, int index) {
        lua_rawgeti(L, index, static_cast<lua_Integer>(I + 1));
        auto value = rosetta_codec<Element<I>>::read(L, -1);
        lua_pop(L, 1);
        return value;
    }
    template<size_t... I> static Product read_elements(lua_State* L, int index, std::index_sequence<I...>) {
        // Braced arguments convert left to right. If a later element fails,
        // earlier native values unwind before the exception reaches Lua.
        return Product{read_element<I>(L, index)...};
    }
    static Product read(lua_State* L, int index) {
        rosetta_product_table(L, index, std::tuple_size_v<Product>);
        index = lua_absindex(L, index);
        const int top = lua_gettop(L);
        try { return read_elements(L, index, std::make_index_sequence<std::tuple_size_v<Product>>{}); }
        catch (...) { lua_settop(L, top); throw; }
    }
    template<size_t I> static void push_element(lua_State* L, const Product& value) {
        rosetta_codec<Element<I>>::push(L, std::get<I>(value));
        lua_rawseti(L, -2, static_cast<lua_Integer>(I + 1));
    }
    template<size_t... I> static void push_elements(lua_State* L, const Product& value, std::index_sequence<I...>) {
        (push_element<I>(L, value), ...);
    }
    static void push(lua_State* L, const Product& value) {
        luaL_checkstack(L, 3, "result nesting exceeds Lua stack capacity");
        lua_newtable(L);
        push_elements(L, value, std::make_index_sequence<std::tuple_size_v<Product>>{});
    }
};
template<class... T> struct rosetta_codec<std::tuple<T...>> : rosetta_product_codec<std::tuple<T...>> {};
template<class First, class Second> struct rosetta_codec<std::pair<First, Second>> : rosetta_product_codec<std::pair<First, Second>> {};

template<class... Alternatives> struct rosetta_codec<std::variant<Alternatives...>> {
    using Variant = std::variant<Alternatives...>;
    template<size_t I = 0> static Variant read_alternative(lua_State* L, int index, size_t selected) {
        if (selected == I) {
            using Element = std::remove_cv_t<std::variant_alternative_t<I, Variant>>;
            return Variant(std::in_place_index<I>, rosetta_codec<Element>::read(L, index));
        }
        if constexpr (I + 1 < sizeof...(Alternatives)) return read_alternative<I + 1>(L, index, selected);
        else throw rosetta_conversion_error(index, "variant index out of range");
    }
    static Variant read(lua_State* L, int index) {
        if (lua_type(L, index) != LUA_TTABLE) throw rosetta_conversion_error(index, "variant table expected");
        if (!lua_checkstack(L, 4)) throw rosetta_conversion_error("variant stack allocation failed");
        index = lua_absindex(L, index);
        const int top = lua_gettop(L);
        try {
            bool has_index = false;
            lua_Integer selected = 0;
            lua_pushnil(L);
            while (lua_next(L, index)) {
                if (lua_type(L, -2) != LUA_TSTRING) throw rosetta_conversion_error(index, "variant keys must be index or value");
                const auto key = rosetta_string_bytes(L, -2);
                if (key == "index") { selected = rosetta_integer<lua_Integer>(L, -1); has_index = true; }
                else if (key != "value") throw rosetta_conversion_error(index, "variant keys must be index or value");
                lua_pop(L, 1);
            }
            if (!has_index) throw rosetta_conversion_error(index, "variant index required");
            if (selected < 1 || static_cast<unsigned long long>(selected) > sizeof...(Alternatives))
                throw rosetta_conversion_error(index, "variant index out of range");
            // Locate the payload without allocating/interning Lua field names
            // across native values. Leave the selected payload rooted on stack.
            bool found = false;
            lua_pushnil(L);
            while (lua_next(L, index)) {
                if (rosetta_string_bytes(L, -2) == "value") { found = true; break; }
                lua_pop(L, 1);
            }
            if (!found) lua_pushnil(L);
            auto result = read_alternative(L, lua_absindex(L, -1), static_cast<size_t>(selected - 1));
            lua_settop(L, top);
            return result;
        } catch (...) { lua_settop(L, top); throw; }
    }
    template<size_t I = 0> static void push_alternative(lua_State* L, const Variant& value) {
        if (value.index() == I) {
            using Element = std::remove_cv_t<std::variant_alternative_t<I, Variant>>;
            rosetta_codec<Element>::push(L, std::get<I>(value));
        } else if constexpr (I + 1 < sizeof...(Alternatives)) push_alternative<I + 1>(L, value);
    }
    static void push(lua_State* L, const Variant& value) {
        if (value.valueless_by_exception()) { luaL_error(L, "valueless variant cannot be published"); return; }
        luaL_checkstack(L, 3, "variant result nesting exceeds Lua stack capacity");
        lua_newtable(L);
        lua_pushinteger(L, static_cast<lua_Integer>(value.index() + 1)); lua_setfield(L, -2, "index");
        push_alternative(L, value); lua_setfield(L, -2, "value");
    }
};

// A mapped view can pin a Lua string and trigger GC while decoding. Protect
// next() so reentrant table mutation cannot longjmp across native map values.
[[maybe_unused]] static int rosetta_map_next_thunk(lua_State* L) {
    return lua_next(L, 1) ? 2 : 0;
}
[[maybe_unused]] inline bool rosetta_map_next(lua_State* L, int index) {
    index = lua_absindex(L, index);
    const int previous = lua_gettop(L);
    if (!lua_checkstack(L, 4)) throw rosetta_conversion_error("map iteration stack allocation failed");
    lua_pushcfunction(L, rosetta_map_next_thunk);
    lua_pushvalue(L, index);
    lua_pushvalue(L, previous);
    if (lua_pcall(L, 2, 2, 0) != LUA_OK) {
        const rosetta_conversion_error error(lua_type(L, -1) == LUA_TSTRING ? lua_tostring(L, -1) : "map iteration failed");
        lua_pop(L, 1);
        throw error;
    }
    lua_remove(L, previous);
    if (lua_isnil(L, -2)) { lua_pop(L, 2); return false; }
    return true;
}
